def gpu_h(prefix):
    s = 0.0
    for f in glob.glob("/home/boa-dit*/results/gpu_hours.csv"):
        for line in open(f):
            r = line.strip().split(",")
            if r and r[0] == "f6" and r[1].startswith(prefix):
                s += float(r[-1])
    return s


def boot(a, b, ratio, n=2000):
    a, b = np.asarray(a), np.asarray(b)
    g = np.random.default_rng(0)
    idx = [g.integers(0, len(a), len(a)) for _ in range(n)]
    if ratio:
        d = [a[i].mean() / b[i].mean() - 1 for i in idx]
        return f"{100 * (a.mean() / b.mean() - 1):+.2f}% [{100 * np.percentile(d, 2.5):+.2f}, {100 * np.percentile(d, 97.5):+.2f}]"
    d = [np.mean(a[i] - b[i]) for i in idx]
    return f"{np.mean(a - b):+.4f} [{np.percentile(d, 2.5):+.4f}, {np.percentile(d, 97.5):+.4f}]"


