"""results/dns_response/REPORT.md from the r1 JSONs. Run: python scripts/make_dns_response.py"""
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boa_dit.common import atomic_write_text

OUT = os.path.join(ROOT, "results", "dns_response")
J = lambda f: json.load(open(os.path.join(OUT, f))) if os.path.exists(os.path.join(OUT, f)) else None
CO, CP, FI, SE, PA, CF, BU = (J(f) for f in ("correctness.json", "components.json", "fit.json", "select.json", "parameters.json", "confirm.json", "budget.json"))
FIDS = {a: J(f"fid_{a}.json") for a in ("plain", "dns", "L", "T")}


def boot(a, b, ratio, n=2000):
    a, b = np.asarray(a), np.asarray(b)
    idx = np.random.default_rng(0).integers(0, len(a), (n, len(a)))
    d = (a[idx].mean(1) / b[idx].mean(1) - 1) if ratio else (a[idx] - b[idx]).mean(1)
    v = (a.mean() / b.mean() - 1) if ratio else (a - b).mean()
    return f"{100 * v:+.2f}% [{100 * np.percentile(d, 2.5):+.2f}, {100 * np.percentile(d, 97.5):+.2f}]" if ratio else \
        f"{v:+.4f} [{np.percentile(d, 2.5):+.4f}, {np.percentile(d, 97.5):+.4f}]"


L = ["# DNS response pilot (r1): report (generated by `scripts/make_dns_response.py`)", "",
     "Question: does a small band-wise latent impulse on top of faithful DNS (x ← x + θ_j·P_low(x) after updates 9/19/29/39/48; **not** a per-band timestep), "
     "calibrated against the signed moment mismatch through measured downstream responses (T), beat the same actuator calibrated locally (L) and faithful DNS?",
     "Bed: DiT-XL/2 256, heig-8 W4 + rank-8 carry, A16, DDIM-50, cfg 1.5; frozen DNS calibration. Protocol: `results/dns_response/PROTOCOL.md`.", ""]
if BU:
    L.append(f"Budget: {BU['spent_gpu_h']:.2f} of {BU['caps']['gpu_h']} GPU-h; elapsed {BU['elapsed_h']:.2f} of {BU['caps']['elapsed_h']} h. Stage log in budget.json.")
L += ["", "## Stages", ""]
for name, obj in (("correctness checks", CO), ("component removals", CP), ("responses / L / T fits", FI), ("development selection", SE), ("fidelity confirmation", CF)):
    L.append(f"- {name}: {'completed' if obj else 'NOT RUN'}" + (f" (pass {obj.get('pass')})" if name == "correctness checks" and obj else ""))
for a, f in FIDS.items():
    L.append(f"- FID-2k / KID {a}: {'completed' if f else 'NOT RUN'}")
if CP:
    L += ["", "## Component removals (frozen DNS calibration; context only)", "", "| arm | fit latent | fit J | dev latent | dev J |", "| --- | ---: | ---: | ---: | ---: |"]
    for m in ("plain", "affine", "sched", "affsched", "dns"):
        L.append(f"| {m} | {CP['fit'][m]['latent']:.5f} | {CP['fit'][m]['J_full']:.4f} | {CP['dev'][m]['latent']:.5f} | {CP['dev'][m]['J_full']:.4f} |")
if FI:
    g = FI["G0"]
    L += ["", "## Response matrix at θ = 0 (fit seeds, live rollouts)",
          f"- Column norms {np.round(g['col_norm'], 3).tolist()}; ±0.002 vs ±0.004 relative differences {np.round(g['rel_diff_h1_h2'], 3).tolist()}; usable {g['usable']}.",
          f"- Singular values {np.round(g['singular_values'], 4).tolist()} (condition {g['condition']:.3g}); off-time block norms {np.round(g['offtime_block_norm'], 3).tolist()}.",
          f"- Repeat-run variation: {FI.get('repeat_variation')}. DNS on fit: latent {FI['dns_fit']['latent']:.5f}, J_full {FI['dns_fit']['J_full']:.4f}, J_local {FI['dns_fit']['J_local']:.4f}."]
    for arm, its in FI["arms"].items():
        L.append(f"- **{arm}** iterates: " + "; ".join(f"it{e['it']} θ {np.round(e['theta'], 5).tolist()} J_arm {e['J_arm']:.4f} latent {e['latent']:.5f}"
                                                      + ("" if e['it'] == 0 else f" (accepted {e['accepted']}; predicted {e.get('pred_J_arm', float('nan')):.4f})") for e in its))
if SE:
    L += ["", "## Development selection (common full objective; fidelity guard 1.25× DNS)", f"- DNS dev: latent {SE['dns_dev']['latent']:.5f}, J {SE['dns_dev']['J_full']:.4f}."]
    for arm, v in SE["arms"].items():
        s = v["selected"]
        L.append(f"- {arm}: selected it{s['it']} θ {np.round(s['theta'], 5).tolist()}, J_dev {s['J_full_dev']:.4f}, latent {s['latent_dev']:.5f}" + (" (**identity**)" if v["identity_selected"] else ""))
if CF:
    A = CF["arms"]
    L += ["", "## Fidelity confirmation (seeds 72200–72327, n = 128; paired bootstrap over images)", "", "| arm | latent rel. MSE | PSNR | LPIPS | J (moments) |", "| --- | ---: | ---: | ---: | ---: |"]
    for k, v in A.items():
        if "same_as" in v:
            L.append(f"| {k} | identical to {v['same_as']} | | | |")
            continue
        L.append(f"| {k} | {np.mean(v['rel_mse']):.5f} | {np.mean(v['psnr']):.2f} | {np.mean(v['lpips']):.4f} | {v['J_full']:.4f} |")
    L += ["", "| contrast | latent | PSNR | LPIPS |", "| --- | --- | --- | --- |"]
    for a, b in (("dns", "plain"), ("L", "dns"), ("T", "dns"), ("T", "L")):
        if a in A and b in A and "rel_mse" in A[a] and "rel_mse" in A[b]:
            L.append(f"| {a} vs {b} | {boot(A[a]['rel_mse'], A[b]['rel_mse'], True)} | {boot(A[a]['psnr'], A[b]['psnr'], False)} | {boot(A[a]['lpips'], A[b]['lpips'], False)} |")
if any(FIDS.values()):
    L += ["", "## Generation (seeds 74000–75999; exploratory finite-sample points, no percentile-bootstrap CIs)", "", "| arm | FID-2k | KID (subset sd) |", "| --- | ---: | --- |"]
    for a, f in FIDS.items():
        if f:
            L.append(f"| {a} | {f['fid2000']:.3f} | {f['kid']:.5f} ({f['kid_subset_sd']:.5f}) |")
L += ["", "## Interpretation (protocol §7 rules)",
      "- T better on moments only: a better calibration diagnostic, not a demonstrated generation method.",
      "- T better than DNS but not L: the correction may help; the downstream-calibration contribution is not established.",
      "- T better than both DNS and L on generation quality, with acceptable fidelity and cost: promising, needs replication and a second bed (≈ 0.5 FID-2k vs both motivates replication; not a significance threshold).",
      "- No gain: a bounded result for this actuator, objective, data and model. It does not show that all covariance-aware or sampler-side corrections fail."]
atomic_write_text(os.path.join(OUT, "REPORT.md"), "\n".join(L) + "\n")
print("\n".join(L))
