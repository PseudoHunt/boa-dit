dci = lambda d, k: f"{d['diff']:+.{k}f} [{d['ci'][0]:+.{k}f}, {d['ci'][1]:+.{k}f}]"


def R_ci(n, f, c):
    n, f, c = map(np.asarray, (n, f, c))
    rng = np.random.default_rng(0)
    idx = [rng.integers(0, len(n), len(n)) for _ in range(2000)]
    R = (n.mean() - c.mean()) / (n.mean() - f.mean())
    return R, np.percentile([(n[i].mean() - c[i].mean()) / (n[i].mean() - f[i].mean()) for i in idx], [2.5, 97.5])


