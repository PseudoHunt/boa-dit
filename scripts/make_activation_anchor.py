"""Generate results/activation_anchor/REPORT.md from the aa1 JSON outputs (missing stages reported as unrun)."""
import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "results", "activation_anchor")
ORDER = ("FP50", "Q", "A", "C", "AC", "C_anchor_only", "AC_anchor_only")


def j(n):
    f = os.path.join(OUT, n)
    return json.load(open(f)) if os.path.exists(f) else None


def results_block(res, L, n_label):
    L += ["| arm | cheap / FP calls | latent rel. MSE mean | median | PSNR (dB) | LPIPS |", "|---|---|---:|---:|---:|---:|"]
    for a in ORDER:
        c = res["calls"][a]
        if a in res["summary"]:
            s = res["summary"][a]
            L.append(f"| {a} | {c['cheap']} / {c['fp']} | {s['rel_mse']['mean']:.5f} | {s['rel_mse']['median']:.5f} | {s['psnr']['mean']:.2f} | {s['lpips']['mean']:.4f} |")
        else:
            L.append(f"| {a} | {c['cheap']} / {c['fp']} | 0 (reference) | 0 | — | — |")
    L += ["", f"Paired contrasts ({n_label}):", "", "| contrast | mean-MSE ratio [95% CI] | mean diff [CI] | median diff | wins | ΔLPIPS [CI] | ΔPSNR [CI] |",
          "|---|---:|---:|---:|---:|---:|---:|"]
    for k, v in res["contrasts"].items():
        m, lp, ps = v["rel_mse"], v["lpips"], v["psnr"]
        L.append(f"| {k.replace('_vs_', ' vs ')} | {m['ratio']:.3f} [{m['ratio_ci'][0]:.3f}, {m['ratio_ci'][1]:.3f}] | {m['diff']:+.5f} [{m['diff_ci'][0]:+.5f}, "
                 f"{m['diff_ci'][1]:+.5f}] | {m['median_diff']:+.5f} | {m['wins_x']}/{m['n']} | {lp['diff']:+.4f} [{lp['diff_ci'][0]:+.4f}, {lp['diff_ci'][1]:+.4f}] | "
                 f"{ps['diff']:+.2f} [{ps['diff_ci'][0]:+.2f}, {ps['diff_ci'][1]:+.2f}] |")
    it = res["interaction"]
    L += ["", f"- **Reading of AC vs C:** {res['reading_AC_vs_C']}.",
          f"- Interaction I = [E(C) − E(AC)] − [E(Q) − E(A)] = {it['I_abs']:+.5f} [{it['I_abs_ci'][0]:+.5f}, {it['I_abs_ci'][1]:+.5f}] "
          f"(feedback gain with anchors {it['feedback_gain_with_anchors']:+.5f} [{it['feedback_gain_with_anchors_ci'][0]:+.5f}, {it['feedback_gain_with_anchors_ci'][1]:+.5f}], "
          f"without {it['feedback_gain_without_anchors']:+.5f} [{it['feedback_gain_without_anchors_ci'][0]:+.5f}, {it['feedback_gain_without_anchors_ci'][1]:+.5f}]); "
          f"relative: [E(AC)/E(C)] / [E(A)/E(Q)] = {it['rel_ratio_of_ratios']:.3f} [{it['rel_ratio_of_ratios_ci'][0]:.3f}, {it['rel_ratio_of_ratios_ci'][1]:.3f}]."]


def main():
    P, C, D, G, F = (j(n) for n in ("PROTOCOL", "checks.json", "dev.json", "diag.json", "conf.json"))
    rows = [r for r in csv.reader(open(os.path.join(ROOT, "results", "gpu_hours.csv"))) if r and r[0] == "aa1"]
    tot = sum(float(r[-1]) for r in rows)
    L = ["# Activation feedback + measured anchoring (aa1): report", "",
         "Protocol `PROTOCOL.md` (pre-registered 2026-10-30, commit 82d574f). Generated by `scripts/make_activation_anchor.py`.",
         f"**GPU: {tot:.3f} of 1.5 A30-h** ({', '.join(f'{r[1]} {float(r[-1]):.4f}' for r in rows)}). Combined with the shared-weight phase (0.367 h): "
         f"{tot + 0.367:.3f} of 2.0 A30-h.",
         "Integration / accuracy pilot: fidelity to a generated FP-50 reference. **No deployable speedup or generation-quality claim; no FID.**", "",
         "IDs: Q = static A8; A = DCT-4 feedback; C = FP anchors every 4 calls + reused discrepancy; AC = both; *_anchor_only = FP anchors, raw cheap output between.",
         "Cheap model: unrefitted common smoothed rank-8 W4 base + original carry + static single8 A8 tables (dit_joint); teacher = FP weights/activations.", ""]
    L += ["## Correctness gates"]
    if C:
        L += [f"- G1 reproduce joint-pilot latents (61000–61031, batch 32): {C['G1_reproduce_joint_pilot_batch32']}",
              f"- G2 correction disabled = anchor-only: {C['G2_zero_correction_equals_anchor_only']}; G3 K = 1 = FP50: {C['G3_K1_equals_FP50']}",
              f"- G4 no-anchor = plain: {C['G4_no_anchor_equals_plain']}; G5 identical low/high: FP50 trajectory {C['G5_identical_low_high_equals_FP50']}, zero discrepancy {C['G5_zero_discrepancy']}",
              f"- G6 anchor inputs identical {C['G6_anchor_inputs_identical']}; counts {C['G6_counts_pass']}; feedback updates per site per trajectory {C['G6_fb_updates_per_site_per_trajectory']}; "
              f"FP isolated (no hooks, disjoint params) {C['fp_isolated_no_hooks_disjoint_params']}",
              f"- G7 save/resume bitwise {C['G7_save_resume_bitwise']} (saved: {', '.join(C['G7_saved_fields'])}); G8 finite {C['G8_finite']}, variance channels unused {C['G8_zero_aux_equals_Q']}",
              f"- **All gates pass: {C['pass']}**"]
    else:
        L.append("- **Unrun.**")
    for title, res, nl in (("Development (60200–60215, batch 16; exploratory, nothing selected)", D, "16 images, 10,000 bootstrap draws"),
                           ("Confirmation (96100–96163, fresh, batch 32, opened once)", F, "64 images, 10,000 paired bootstrap draws, seed 0")):
        L += ["", f"## {title}", ""]
        if not res:
            L.append("- **Unrun.**")
            continue
        results_block(res, L, nl)
    if F:
        L += ["", "Simulation timing (diagnostics off; fake-quant with fp32 weights; not a deployable speed): " +
              ", ".join(f"{a} {v['median']:.1f} s" for a, v in F["timing_s_per_batch32"].items()) + " per 32-image trajectory; "
              f"peak allocated {F['peak_mem_live']['allocated'] / 1e9:.2f} GB (three models resident). Clip rates (representable range): " +
              ", ".join(f"{a} {sum(v) / len(v):.2e}" for a, v in F["clip_rate"].items()) + "."]
    L += ["", "## Mechanism diagnostic (8 dev images, own trajectories, same-state FP; diagnostic FP calls not counted)", ""]
    if G:
        L += [f"- Pooling: {G['pooling']}. {G['note']}.", "",
              "| arm | lag | E_t | E_a | ⟨e_t, e_a⟩ | ρ | Σ‖e_t−e_a‖²/Σ‖e_t‖² [CI] | identity residual |", "|---|---:|---:|---:|---:|---:|---:|---:|"]
        for arm, r in G["arms"].items():
            for lg, s in r["lags_raw"].items():
                L.append(f"| {arm} | {lg} | {s['E_t']:.4g} | {s['E_a']:.4g} | {s['cross']:.4g} | {s['rho']:.3f} | {s['ratio_diff_over_Et']['v']:.3f} "
                         f"[{s['ratio_diff_over_Et']['ci'][0]:.3f}, {s['ratio_diff_over_Et']['ci'][1]:.3f}] | {s['identity_residual_rel']:.1e} |")
        L.append("")
        for arm, r in G["arms"].items():
            line = f"- {arm}: clip rate {r['clip_rate_representable_range']:.2e}; mean raw error energy per step {sum(r['per_step_raw_energy_mean']) / 50:.4g}"
            if "corrected_over_raw_nonanchor" in r:
                cr = r["corrected_over_raw_nonanchor"]
                line += (f"; non-anchor corrected/raw energy {cr['v']:.3f} [{cr['ci'][0]:.3f}, {cr['ci'][1]:.3f}] (raw {r['raw_energy_nonanchor']:.4g}, corrected "
                         f"{r['corrected_energy_nonanchor']:.4g}); anchor identity residual {r['anchor_identity_rel_residual']:.1e}")
            L.append(line + ".")
        L.append("- Residual-clamp and discarded-subspace energies: not measured (frozen quantizer). The local identity is not an endpoint prediction.")
    else:
        L.append("- Not run.")
    open(os.path.join(OUT, "REPORT.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
