"""Regenerate results/gate1.md (and gain.png) from Stage 1 JSONs. Never type numbers by hand."""
import glob
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boa_dit.common import atomic_savefig, atomic_write_json, atomic_write_text  # noqa: E402

S1 = os.path.join(ROOT, "results", "stage1")
CHOICE = json.load(open(os.path.join(ROOT, "configs", "gain_choice.json")))


def load(name):
    return json.load(open(os.path.join(S1, name)))


def gain_runs():
    runs = {}
    for p in sorted(glob.glob(os.path.join(S1, "gain_*.json"))):
        d = json.load(open(p))
        if "tag" not in d:
            continue
        runs[d["tag"]] = d
    return runs


def estimators(d):
    g_mean = np.array(d["gain2"])
    g_med = np.array([np.median(r) for r in d["gain2_per_seed"]])
    return {"ratio_of_means": g_mean, "median_of_ratios": g_med}


def main():
    runs = gain_runs()
    gstats = load("gates_stats.json")["per_block"]
    dis = {k: v for k, v in load("gram_dissim.json").items() if not k.startswith("_")}
    tok = {k: v for k, v in load("token_norms.json").items() if not k.startswith("_")}
    attn = load("attn_position_stability.json")
    L = []
    L.append("# Gate 1 — diagnostics (full precision)\n")
    L.append("_Generated by `scripts/make_gate1.py` from `results/stage1/*.json`._\n")
    L.append(f"Stage 1 seeds 2000–2015 (16 images, both CFG branches), cfg 1.5, DDIM-50. Step i = 0 is the noisiest step.\n")

    # ---------- 4.1 gain
    L.append("## 4.1 Sampler gain g_t²\n")
    L.append("| run | forward | ρ | estimator | max/median over t | argmax step | argmin step |")
    L.append("| --- | --- | ---: | --- | ---: | ---: | ---: |")
    for tag, d in runs.items():
        for en, g in estimators(d).items():
            L.append(f"| {tag} | {d.get('forward', 'fp16-autocast')} | {d['rho']:g} | {en} | {g.max() / np.median(g):.2f} | "
                     f"{int(g.argmax())} | {int(g.argmin())} |")
    L.append("")
    # rho-independence checks
    L.append("**ρ-independence** (handoff: within 10%). Median over steps of |log ratio| between paired runs, and the "
             "fraction of steps whose two estimates differ by more than 10%:\n")
    L.append("| pair | estimator | median abs ratio-1 | steps > 10% off |")
    L.append("| --- | --- | ---: | ---: |")
    for a, b in CHOICE["rho_pairs"]:
        if a in runs and b in runs:
            for en in ("ratio_of_means", "median_of_ratios"):
                ga, gb = estimators(runs[a])[en], estimators(runs[b])[en]
                r = ga / gb
                L.append(f"| {a} vs {b} | {en} | {np.median(np.abs(r - 1)):.3f} | {int((np.abs(r - 1) > 0.1).sum())}/50 |")
    L.append("")
    if "floor_tag" in CHOICE and CHOICE["floor_tag"] in runs:
        fl = runs[CHOICE["floor_tag"]]
        L.append(f"**fp16 rounding floor:** `{fl['tag']}` (ρ = {fl['rho']:g}, signal ≈ 0) gives an apparent gain2 of "
                 f"{np.median(fl['gain2']):.3g} (median over steps): ‖Δx₀‖² there is pure rounding chaos, so fp16 "
                 "finite differences cannot resolve the linear gain.\n")
    chosen = runs[CHOICE["tag"]]
    g = estimators(chosen)[{"mean": "ratio_of_means", "median": "median_of_ratios"}[CHOICE["stat"]]]
    L.append(f"**Chosen for Stage 2:** `{CHOICE['tag']}`, estimator `{CHOICE['stat']}`. {CHOICE['why']}\n")
    L.append(f"Chosen curve: max/median = {g.max() / np.median(g):.2f}, monotone non-increasing: "
             f"{bool(np.all(np.diff(g) <= 0))}.\n")
    L.append("Approved (RESPONSE to the Stage 2 report, item 1): the fp32 median-over-seeds curve is the method's weight. "
             "Both curves are kept in `results/stage1/gain.json`; steps where mean/median > 3 are marked as bifurcation steps.\n")
    L.append("![gain](stage1/gain.png)\n")

    # ---------- 4.2 gates
    L.append("## 4.2 Gate energies\n")
    L.append("| block | msa max/med (t) | msa dead | msa K4 inertia | mlp max/med (t) | mlp dead | mlp K4 inertia |")
    L.append("| ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
    for b in range(28):
        m, p = gstats["msa"][b], gstats["mlp"][b]
        L.append(f"| {b} | {m['max_over_median_t']:.2f} | {m['dead_frac']:.3f} | {m['kmeans4_inertia_ratio']:.3f} | "
                 f"{p['max_over_median_t']:.2f} | {p['dead_frac']:.3f} | {p['kmeans4_inertia_ratio']:.3f} |")
    L.append("")
    qual = {gn: {r["block"] for r in gstats[gn] if r["max_over_median_t"] >= 3 and r["kmeans4_inertia_ratio"] <= 0.5}
            for gn in ("msa", "mlp")}
    low = {gn: {r["block"] for r in gstats[gn] if r["max_over_median_t"] < 2} for gn in ("msa", "mlp")}
    union = qual["msa"] | qual["mlp"]
    L.append(f"Blocks with mean-energy max/median ≥ 3 and inertia ≤ 0.5: gate_msa {len(qual['msa'])} "
             f"{sorted(qual['msa'])}; gate_mlp {len(qual['mlp'])} {sorted(qual['mlp'])}; either gate {len(union)}.\n")
    L.append("![gates_mean](stage1/gates_mean.png)\n\n![gates_channels](stage1/gates_channels.png)\n")

    # ---------- 4.3 trace
    L.append("## 4.3 Gram trace vs step\n\n![trace](stage1/trace.png)\n")

    # ---------- 4.4 dissimilarity
    L.append("## 4.4 Do per-bucket Grams disagree?\n")
    L.append("| block.layer | median off-diag rel. Frobenius | min Spearman | median Spearman | median top-32 overlap | differs? |")
    L.append("| --- | ---: | ---: | ---: | ---: | --- |")
    n_diff = 0
    scalar_everywhere = True
    for k, v in dis.items():
        diff = v["median_offdiag_rel_fro"] >= 0.10 or v["min_spearman"] <= 0.9
        n_diff += diff
        scalar_everywhere &= (v["median_offdiag_rel_fro"] < 0.03 and v["min_spearman"] > 0.97)
        L.append(f"| {k} | {v['median_offdiag_rel_fro']:.3f} | {v['min_spearman']:.3f} | {v['median_spearman']:.3f} | "
                 f"{v['median_offdiag_overlap']:.3f} | {'yes' if diff else 'no'} |")
    L.append(f"\n{n_diff}/{len(dis)} (block, layer) pairs differ (median rel. Frobenius ≥ 0.10 or min Spearman ≤ 0.9).\n")
    L.append("![gram_dissim](stage1/gram_dissim.png)\n")

    # ---------- 4.5 sinks
    L.append("## 4.5 Token-norm sinks\n")
    L.append("| block.layer | worst max/median over buckets |")
    L.append("| --- | ---: |")
    sinks = False
    for k, v in tok.items():
        L.append(f"| {k} | {v['max_over_median_worst']:.1f} |")
        sinks |= v["max_over_median_worst"] > 100
    L.append(f"\nSinks (max/median > 100) present: **{sinks}** → Gate 2 λ default: "
             f"{'run λ = 0.5 alongside λ = 1' if sinks else 'λ = 1 only (λ = 0.5 stays a Stage 3 arm)'}.\n")

    # ---------- verdict
    gmm = g.max() / np.median(g)
    a = gmm >= 3
    b_msa, b_mlp, b_union = len(qual["msa"]) >= 10, len(qual["mlp"]) >= 10, len(union) >= 10
    dis_ok = n_diff >= len(dis) / 2
    stop1 = gmm < 2 and all(len(low[gn]) > 20 for gn in ("msa", "mlp"))
    verdict = "STOP" if (stop1 or scalar_everywhere) else ("PASS" if ((a or b_mlp or b_msa) and dis_ok) else "NO-PASS (neither PASS nor STOP; human decision)")
    L.append("## 4.6 Verdict\n")
    L.append(f"- (a) gain2 max/median ≥ 3 (chosen estimator): **{a}** ({gmm:.2f}). Holds under every estimator/ρ above: "
             f"**{all(estimators(d)[en].max() / np.median(estimators(d)[en]) >= 3 for d in runs.values() for en in ('ratio_of_means', 'median_of_ratios'))}**.")
    L.append(f"- (b) gate-energy criterion in ≥ 10 blocks: gate_msa {b_msa} ({len(qual['msa'])}), gate_mlp {b_mlp} "
             f"({len(qual['mlp'])}), either gate {b_union} ({len(union)}).")
    L.append(f"- Gram dissimilarity in ≥ half of (block, layer) pairs: **{dis_ok}** ({n_diff}/{len(dis)}).")
    L.append(f"- STOP conditions: low-gain-and-flat-gates {stop1}; Grams scalar multiples everywhere {scalar_everywhere}.\n")
    L.append(f"**Gate 1: {verdict}**\n")

    # ---------- 4.7
    L.append("## 4.7 Attention-pattern stability per grid position (log-only)\n")
    L.append("![attn](stage1/attn_position_stability.png)\n")
    L.append("| block | head | step | within med | within p10 | adjacent med | far med | frac within > 0.8 |")
    L.append("| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
    for v in attn["per"].values():
        L.append(f"| {v['block']} | {v['head']} | {v['step']} | {v['within_median']:.3f} | {v['within_p10']:.3f} | "
                 f"{v['adjacent_median']:.3f} | {v['far_median']:.3f} | {v['frac_within_gt_0.8']:.3f} |")
    chk = [c["rel_fro"] for cs in attn["pv_check_vs_sdpa"].values() for c in cs]
    L.append(f"\nP recomputed from the qkv output; P@V vs the SDPA output: max relative Frobenius error {max(chk):.2e} "
             "(fused attention left untouched, so block outputs are unchanged by construction).\n")
    spb = attn["steps_meeting_criterion_per_block"]
    L.append(("**per-(position, bucket) pooling plausible**" if attn["pooling_plausible"] else
              "**per-(position, bucket) pooling not plausible**") +
             f" — steps (of 10) with head-median within ≥ 0.8 and far ≤ 0.5: " +
             ", ".join(f"block {b}: {n}" for b, n in spb.items()) + ".")
    L.append("Within-image agreement is high at the noisy steps and falls with denoising (content-dependent attention), "
             "while patterns 25 steps apart mostly stay similar (far > 0.5) except block 27 heads 0/15.\n")
    atomic_write_text(os.path.join(ROOT, "results", "gate1.md"), "\n".join(L))

    # gain.png
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    # gain.json: the method's weight (approved: fp32, median over seeds) plus the mean curve, and bifurcation steps
    em = estimators(chosen)
    ratio = em["ratio_of_means"] / em["median_of_ratios"]
    bif = [int(i) for i in np.where(ratio > 3)[0]]
    atomic_write_json(os.path.join(S1, "gain.json"), {
        "source_run": CHOICE["tag"], "method_weight": "median_of_ratios",
        "step_convention": chosen["step_convention"], "timesteps": chosen["timesteps"],
        "gain2_median": em["median_of_ratios"].tolist(), "gain2_mean": em["ratio_of_means"].tolist(),
        "mean_over_median": ratio.tolist(), "bifurcation_steps": bif,
        "bifurcation_rule": "steps where ratio-of-means / median-of-ratios > 3"})

    fig, axs = plt.subplots(1, 3, figsize=(20, 4.8))
    ax = axs[0]
    for i in bif:
        ax.axvspan(i - 0.5, i + 0.5, color="tab:red", alpha=0.15, lw=0)
    ax.plot(em["ratio_of_means"], marker=".", label="mean over seeds (ratio of means)")
    ax.plot(em["median_of_ratios"], marker=".", label="median over seeds (method weight)")
    ax.set_yscale("log"); ax.set_xlabel("sampling step i (0 = noisiest)"); ax.set_ylabel("‖Δx₀‖² / ‖D‖²")
    ax.set_title(f"{CHOICE['tag']}: shaded = bifurcation steps (mean/median > 3), n = {len(bif)}")
    ax.legend(fontsize=8)
    for ax, en in zip(axs[1:], ("ratio_of_means", "median_of_ratios")):
        for tag, d in runs.items():
            ls = "-" if d.get("forward") == "fp32" else ":"
            ax.plot(estimators(d)[en], ls, marker=".", label=f"{tag}")
        ax.set_yscale("log"); ax.set_title(f"all runs — {en}"); ax.set_xlabel("sampling step i (0 = noisiest)")
    axs[2].legend(fontsize=7)
    fig.tight_layout(); atomic_savefig(fig, os.path.join(S1, "gain.png")); plt.close(fig)
    print(verdict)


if __name__ == "__main__":
    main()
