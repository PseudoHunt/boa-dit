ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boa_dit.common import atomic_write_json, atomic_write_text
from boa_dit.f5 import spent

OUT = os.path.join(ROOT, "results", "e3c")
E = json.load(open(os.path.join(OUT, "eval.json")))["arms"]
TR = {os.path.basename(f)[:-5]: json.load(open(f)) for f in glob.glob(os.path.join(OUT, "train", "*.json"))}
FID = {json.load(open(f))["arm"]: json.load(open(f)) for f in glob.glob(os.path.join(OUT, "fid", "fid2000_*.json"))}
FB = json.load(open(os.path.join(OUT, "fid_boot.json"))) if os.path.exists(os.path.join(OUT, "fid_boot.json")) else None
MULTI = ["C1t", "C1u", "C2", "C2L", "C1L"]


def per_image(arm, key):
    """single arms as stored; multi-seed arms averaged per image over the training seeds present."""
    if arm in E:
        return np.asarray(E[arm][key]), 1
    runs = [np.asarray(E[f"{arm}_s{s}"][key]) for s in range(3) if f"{arm}_s{s}" in E]
    return (np.mean(runs, 0), len(runs)) if runs else (None, 0)


def boot(a, b, ratio, n=2000):
    g = np.random.default_rng(0)
    idx = [g.integers(0, len(a), len(a)) for _ in range(n)]
    if ratio:
        d = [a[i].mean() / b[i].mean() - 1 for i in idx]
        return {"v": float(a.mean() / b.mean() - 1), "ci": [float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))]}
    d = [np.mean(a[i] - b[i]) for i in idx]
    return {"v": float(np.mean(a - b)), "ci": [float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))]}


def contrast(a, b):
    out = {}
    for key, ratio in (("rel_mse", True), ("psnr", False), ("lpips", False)):
        x, na = per_image(a, key)
        y, nb = per_image(b, key)
        if x is None or y is None:
            return None
        out[key] = boot(x, y, ratio)
    signs = []
    if a in MULTI and b in MULTI:                                               # seed-paired contrasts (s vs s)
        for s in range(3):
            if f"{a}_s{s}" in E and f"{b}_s{s}" in E:
                signs.append(float(np.mean(E[f"{a}_s{s}"]["rel_mse"]) / np.mean(E[f"{b}_s{s}"]["rel_mse"]) - 1))
    elif a in MULTI:
        signs = [float(np.mean(E[f"{a}_s{s}"]["rel_mse"]) / np.mean(per_image(b, "rel_mse")[0]) - 1) for s in range(3) if f"{a}_s{s}" in E]
    out["per_seed_latent"] = signs
    out["n_seeds"] = (per_image(a, "rel_mse")[1], per_image(b, "rel_mse")[1])
    return out


PAIRS = [("C1t", "C0"), ("C1u", "C0"), ("C2", "C0"), ("H16", "C0"), ("C2", "C1t"), ("C2", "C1u"), ("C2", "H16"),
         ("C2L", "C2"), ("C1L", "C1t"), ("C2L", "C1L"), ("C2L", "H16"), ("C2M_s0", "C2_s0")]
RES = {f"{a}_vs_{b}": contrast(a, b) for a, b in PAIRS}
RES = {k: v for k, v in RES.items() if v is not None}
pct = lambda v: f"{100 * v['v']:+.1f}% [{100 * v['ci'][0]:+.1f}, {100 * v['ci'][1]:+.1f}]"
dif = lambda v, f="+.3f": f"{v['v']:{f}} [{v['ci'][0]:{f}}, {v['ci'][1]:{f}}]"
sig = lambda v: v["ci"][0] > 0 or v["ci"][1] < 0


def read(k, need_signs=True):
    v = RES.get(k)
    if v is None:
        return "not available"
    lat = v["rel_mse"]
    s = v["per_seed_latent"]
    agree = (all(x < 0 for x in s) or all(x > 0 for x in s)) if s else None
    ok = sig(lat) and (agree or not need_signs)
    return f"latent {pct(lat)}; per-seed {', '.join(f'{100 * x:+.1f}%' for x in s) or '—'} → **{'passes' if ok else 'does not pass'}**"


L = ["# E3 confirmation, Part 1: DiT-XL/2 256 heig-8 (report generated by `scripts/make_e3c.py`)", "",
     f"Compute: stage f5 so far {spent():.2f} A30-h (no cap; the user removed it). Protocol and dated amendments: `results/e3c/PROTOCOL.md`.", "",
     "## Training runs", "", "| run | objective | updates | train time |", "| --- | --- | ---: | ---: |"]
for k in sorted(TR):
    t = TR[k]
    L.append(f"| {k} | {t.get('arm', '')} λ={t.get('lam', 0)} | {t['updates']:,} | {t['train_seconds'] / 3600:.3f} h |" + (" (E3 run, reused)" if "reused_from" in t else ""))
L += ["", "## Paired metrics (seeds 20000–20127, n = 128; multi-seed arms averaged per image over their training seeds)", "",
      "| arm | seeds | latent rel. MSE | PSNR | LPIPS |", "| --- | ---: | ---: | ---: | ---: |"]
for arm in ["C0", "H16"] + MULTI + ["C2M_s0"]:
    x, n = per_image(arm, "rel_mse")
    if x is None:
        continue
    L.append(f"| {arm} | {n} | {x.mean():.5f} | {per_image(arm, 'psnr')[0].mean():.2f} | {per_image(arm, 'lpips')[0].mean():.4f} |")
L += ["", "| comparison | latent | PSNR | LPIPS | per-seed latent |", "| --- | --- | --- | --- | --- |"]
for k, v in RES.items():
    L.append(f"| {k.replace('_vs_', ' vs ')} | {pct(v['rel_mse'])} | {dif(v['psnr'])} | {dif(v['lpips'], '+.4f')} | "
             f"{', '.join(f'{100 * x:+.1f}%' for x in v['per_seed_latent']) or '—'} |")
L += ["", "## FID-2k (seeds 30000–31999; ADM reference statistics; paired bootstrap over generated images, 1,000 resamples)", ""]
if FID:
    L += ["| arm | FID-2k | 95% CI (conditional on reference and n) |", "| --- | ---: | --- |"]
    for a in ["C0", "H16", "C1t_s0", "C2_s0", "C2M_s0", "C2L_s0"]:
        if a in FID:
            ci = FB["fid_ci"].get(a) if FB else None
            L.append(f"| {a} | {FID[a]['fid']:.2f} | {'—' if ci is None else f'[{ci[0]:.2f}, {ci[1]:.2f}]'} |")
    if FB:
        L += ["", "| FID difference | value [95% CI] |", "| --- | --- |"]
        L += [f"| {k.replace('_vs_', ' − ')} | {v['diff']:+.2f} [{v['ci'][0]:+.2f}, {v['ci'][1]:+.2f}] |" for k, v in FB["pairs"].items()]
L += ["", "## Pre-registered reads",
      f"1. **Trajectory objective, replicated (C2 vs C1t):** {read('C2_vs_C1t')}",
      f"2. **vs matched updates (C2 vs C1u):** {read('C2_vs_C1u')}",
      f"3. **Better carry vs more carry (C2 rank 8, 0.148 bits vs H16 rank 16, 0.296 bits):** {read('C2_vs_H16', need_signs=False)}"
      + (f"; FID C2 − H16 {FB['pairs']['C2_s0_vs_H16']['diff']:+.2f} [{FB['pairs']['C2_s0_vs_H16']['ci'][0]:+.2f}, {FB['pairs']['C2_s0_vs_H16']['ci'][1]:+.2f}]" if FB and "C2_s0_vs_H16" in FB["pairs"] else ""),
      f"4. **Saturation:** C2L vs C2 {read('C2L_vs_C2')}; C1L vs C1t {read('C1L_vs_C1t')}; time-matched at 0.9 h, C2L vs C1L {read('C2L_vs_C1L')}",
      "5. **Distributional:** see the FID table. Each arm vs C0 is given with its bootstrap CI.",
      f"6. **M on C2:** paired {read('C2M_s0_vs_C2_s0', need_signs=False)}" + (f"; FID C2+M − C2 {FB['pairs']['C2M_s0_vs_C2_s0']['diff']:+.2f} [{FB['pairs']['C2M_s0_vs_C2_s0']['ci'][0]:+.2f}, {FB['pairs']['C2M_s0_vs_C2_s0']['ci'][1]:+.2f}]" if FB and "C2M_s0_vs_C2_s0" in FB["pairs"] else ""),
      "", "Latent, PSNR and LPIPS measure fidelity against FP. FID-2k is one distributional estimate. Neither is called 'better generation' on its own."]
atomic_write_json(os.path.join(OUT, "contrasts.json"), RES)
