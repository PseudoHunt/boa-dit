"""Regenerate results/gate2.md from Stage 2 eval/quant JSONs (run list: configs/gate2_runs.json)."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boa_dit.common import atomic_write_text  # noqa: E402

S2 = os.path.join(ROOT, "results", "stage2")
CFG = json.load(open(os.path.join(ROOT, "configs", "gate2_runs.json")))


def jload(*p):
    p = os.path.join(*p)
    return json.load(open(p)) if os.path.exists(p) else None


def row(label, name):
    lat = jload(S2, "eval", f"latent_{name}.json")
    fid = jload(S2, "eval", f"fid2000_{name}.json")
    q = jload(S2, "quant", f"{name}.json")
    return {"label": label, "name": name, "lat": lat, "fid": fid["fid"] if fid else None,
            "qmin": (q["quant_wall_s"] / 60) if q and "quant_wall_s" in q else None}


def fmt(x, f):
    return "—" if x is None else format(x, f)


def main():
    L = ["# Gate 2 — weighted BoA, layer-output path\n",
         "_Generated by `scripts/make_gate2.py` from `results/stage2/{quant,eval}/*.json`._\n",
         f"{CFG['note']}\n",
         "Primary metric: relative latent MSE ‖x₀_q − x₀_fp‖²/‖x₀_fp‖² on eval seeds 0–511 (matched seeds, fixed batch "
         "layout), mean ± s.e.m. over images. FID-2k is a sanity check only (noisy by 1–2 points, biased upward).\n"]
    fp_fid = jload(S2, "eval", "fid2000_fp.json")
    L.append(f"FP FID-2k: {fmt(fp_fid['fid'] if fp_fid else None, '.2f')}\n")
    res = {}
    for bits in (4, 3):
        L.append(f"## W{bits}\n")
        L.append("| run | name | rel. latent MSE | latent PSNR (dB) | pixel PSNR, 64 imgs (dB) | FID-2k | quant min |")
        L.append("| --- | --- | ---: | ---: | ---: | ---: | ---: |")
        for label, name in CFG["runs"][str(bits)]:
            r = row(label, name)
            res[(bits, label)] = r
            lat = r["lat"]
            L.append(f"| {label} | `{name}` | " +
                     (f"{lat['rel_mse_mean']:.5f} ± {lat['rel_mse_sem']:.5f} | {lat['latent_psnr_mean']:.2f} | "
                      f"{lat['pixel_psnr_mean_64']:.2f}" if lat else "— | — | —") +
                     f" | {fmt(r['fid'], '.2f')} | {fmt(r['qmin'], '.1f')} |")
        L.append("")

    def rel(bits, a, b):
        ra, rb = res.get((bits, a)), res.get((bits, b))
        if not (ra and rb and ra["lat"] and rb["lat"]):
            return None
        return 1 - ra["lat"]["rel_mse_mean"] / rb["lat"]["rel_mse_mean"]

    def paired(bits, a, b):
        """Matched seeds: paired per-image difference, share of images improved, bootstrap 95% CI of the reduction."""
        import numpy as np
        ra, rb = res.get((bits, a)), res.get((bits, b))
        if not (ra and rb and ra["lat"] and rb["lat"]):
            return ""
        x, y = np.array(ra["lat"]["rel_mse_per_image"]), np.array(rb["lat"]["rel_mse_per_image"])
        d = x - y
        rng = np.random.default_rng(0)
        bs = [1 - x[i].mean() / y[i].mean() for i in (rng.integers(0, len(x), len(x)) for _ in range(2000))]
        lo, hi = np.percentile(bs, [2.5, 97.5])
        return (f" Paired Δ = {d.mean():+.4f} ± {d.std() / np.sqrt(len(d)):.4f} (s.e.m.); improved on "
                f"{100 * (d < 0).mean():.0f}% of images; reduction 95% bootstrap CI [{100 * lo:.1f}%, {100 * hi:.1f}%].")

    L.append("## Verdict\n")
    ref, arm = CFG["compare"]
    cut = {b: rel(b, arm, ref) for b in (4, 3)}
    for b in (4, 3):
        L.append(f"- W{b}: `{arm}` vs `{ref}`: relative-MSE reduction **{fmt(None if cut[b] is None else 100 * cut[b], '.1f')}%** "
                 f"(threshold {'5' if b == 4 else '10'}%)." + paired(b, arm, ref))
    for extra in CFG.get("also_compare", []):
        for b in (4, 3):
            c = rel(b, extra[1], extra[0])
            L.append(f"- W{b}: `{extra[1]}` vs `{extra[0]}`: {fmt(None if c is None else 100 * c, '.1f')}%.")
    sat = res.get((4, ref))
    saturated = bool(sat and sat["lat"] and sat["lat"]["rel_mse_mean"] < 0.01)
    L.append(f"- W4 saturation check (`{ref}` rel. MSE < 1%): **{saturated}**.")
    if None in cut.values():
        verdict = "PENDING"
    elif saturated:
        verdict = "PASS" if cut[3] >= 0.10 else "STOP"
    else:
        # Handoff 5.5: PASS if >= 10% at W3 or >= 5% at W4; STOP if `full` is no better than `uniform`
        # at either bit-width, or worse. A regression at any bit-width is therefore a STOP.
        if cut[3] >= 0.10 or cut[4] >= 0.05:
            verdict = "PASS"
        elif min(cut.values()) < 0 or max(cut.values()) <= 0:
            verdict = "STOP"
        else:
            verdict = "NO-PASS (improves at both bit-widths but below thresholds; human decision)"
    L.append(f"\n**Gate 2: {verdict}**\n")
    atomic_write_text(os.path.join(ROOT, "results", "gate2.md"), "\n".join(L))
    print(verdict, cut)


if __name__ == "__main__":
    main()
