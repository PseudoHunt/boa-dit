"""results/temporal/dist/REPORT.md (consolidated §3 + the DCT-16 swap + D3) from the JSONs. Run: python scripts/make_dist.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from boa_dit.common import atomic_write_text
from boa_dit.temporal.c3 import spent
from boa_dit.temporal.common import OUT

J = lambda *p: json.load(open(os.path.join(OUT, *p)))
S = J("dist", "pixart_scores.json")
fid = {k: J("stage3", f"fid2000_dit_bp_single8_{k}.json")["fid"] for k in ("none", "feedback", "feedback_dct4")}
e2 = J("ext", "e2_confirm.json")["arms"]
ci = lambda v, f="+.4f": f"{v['diff']:{f}} [{v['ci'][0]:{f}}, {v['ci'][1]:{f}}]"
lat = lambda v: f"{-100 * v['reduction']:+.1f}% [{-100 * v['ci'][1]:+.1f}, {-100 * v['ci'][0]:+.1f}]"

# PixArt deployed state: 28 blocks x 8 static-A8 sites (7 with 1152 inputs, fc2 with 4608), 4096 image tokens, 2 CFG rows, fp16
C_SUM, TOK, ROWS = 28 * (7 * 1152 + 4608), 4096, 2
px_full = C_SUM * TOK * ROWS * 2
px_k = lambda k: C_SUM * k * ROWS * 2
FWD = 2 * 0.6e9 * ROWS * TOK
px_flops = lambda k: 2 * 2 * TOK * C_SUM * k * ROWS                           # projection + synthesis (multiply-add = 2 FLOPs), per step

L = ["# Distributional metrics for the activation method (consolidated §3, DCT-16 swap, D3): report (generated by `scripts/make_dist.py`)", "",
     f"Compute: c3 total {spent():.3f} A30-h against the 3.0 cap. The overrun was approved by the user (see `rule_distribution.md`). "
     "Pre-registration and all deviations: `results/temporal/rule_distribution.md`.", "",
     "## Read D (per component; cannot pass in this allocation)",
     f"- **DiT FID-2k, set 1 (seeds 0–1999):** single table {fid['none']:.2f}, full feedback {fid['feedback']:.2f}, DCT-4 feedback {fid['feedback_dct4']:.2f}. "
     "Single runs, no CIs. Set 2 (D5) is unrun by cost, so the sign is unconfirmed.",
     "- **PixArt FID-2k:** unrun by cost (≈ 2,000 images per arm at 10–34 s/image).",
     "- **PixArt ImageReward:** the sign is **not confirmed**. It flips between the two prompt sets and every CI includes 0.",
     "- **Read D: not passed.** PixArt FID is missing and the ImageReward sign is unconfirmed, independently of FID.", ""]
for setname, title in (("screen", "Screen set mjhq1k[0:64] (the existing MJHQ-64 images)"),
                       ("untouched", "Second set mjhq1k[64:96] (unused by any feedback arm; part of the earlier MJHQ-256 base validation, see the provenance note)")):
    L += [f"## {title}", "", "| arm | ImageReward | PSNR | LPIPS | latent rel. MSE | vs single: IR | PSNR | LPIPS | latent |", "| --- | ---: | ---: | ---: | ---: | --- | --- | --- | --- |"]
    for name, r in S[setname]["arms"].items():
        vs = r.get("vs_single")
        ir = f"{r['ir_mean']:+.4f}" if "ir_mean" in r else "—"
        fidc = f"{r['psnr_mean']:.2f} | {r['lpips_mean']:.4f} | {r['latent_mean']:.5f}" if "psnr_mean" in r else "— | — | —"
        vsc = (f"{ci(vs['ir']) if 'ir' in vs else '—'} | {ci(vs['psnr'], '+.2f')} | {ci(vs['lpips'])} | {lat(vs['latent'])}") if vs else "— | — | — | —"
        L.append(f"| {r['label']} | {ir} | {fidc} | {vsc} |")
    L.append("")
r16 = S["read_dct16"]
L += ["## LPIPS settlement",
      "- The screen-set pattern (full feedback worse than single, DCT-4 better) **replicates in sign** on the second set. Full feedback's LPIPS increase is "
      "significant on both sets. DCT-4's decrease is significant on the screen set only.",
      "- PSNR and latent move the other way: full feedback has the best PSNR and latent on both sets. Full feedback improves pixel/latent fidelity but "
      "worsens LPIPS, while DCT-4 improves all three moderately.", "",
      "## DCT-16 trade-off read (user swap, pre-registered)",
      "| set | single | DCT-4 | DCT-16 | full | latent between | PSNR between | LPIPS ≤ single |", "| --- | --- | --- | --- | --- | :---: | :---: | :---: |"]
for s in ("screen", "untouched"):
    k = r16[s]["k_curve"]
    cell = lambda a: f"{k[a]['latent']:.4f} / {k[a]['psnr']:.2f} / {k[a]['lpips']:.4f}"
    L.append(f"| {s} | {cell('single')} | {cell('dct4')} | {cell('dct16')} | {cell('full')} | {r16[s]['latent_between']} | {r16[s]['psnr_between']} | {r16[s]['lpips_le_single']} |")
L += ["", "Cells: latent rel. MSE / PSNR / LPIPS.",
      f"**Trade-off exists: {r16['trade_off_exists']}.** DCT-16 is worse than DCT-4 on latent and PSNR on both sets, so the curve is not monotone in k "
      "between 4 and full. No band-limited setting is recommended on this evidence. The D3 lower-bound clause does not apply.", "",
      "## Deployed cost (separate from simulation time)",
      "| bed | arm | persistent state per image | extra per element per step | extra FLOPs per step |", "| --- | --- | ---: | --- | ---: |",
      f"| DiT-XL/2 256 (112 sites, batch-32 measured / 32) | full feedback | {e2['full']['persistent_state_bytes_per_image'] / 2**20:.1f} MiB | 1 add + 1 subtract + clamp | — |",
      f"| DiT-XL/2 256 | DCT-4 feedback | {e2['dct4']['persistent_state_bytes_per_image'] / 2**20:.2f} MiB | as above, on the synthesized state | projection + synthesis |",
      f"| PixArt-Σ 1024² (224 sites, 4096 tokens, 2 CFG rows, fp16) | full feedback | {px_full / 2**30:.2f} GiB | 1 add + 1 subtract + clamp | — |",
      f"| PixArt-Σ 1024² | DCT-4 feedback | {px_k(4) / 2**20:.2f} MiB | as above | {px_flops(4) / 1e9:.2f} GFLOP |",
      f"| PixArt-Σ 1024² | DCT-16 feedback | {px_k(16) / 2**20:.2f} MiB | as above | {px_flops(16) / 1e9:.2f} GFLOP |",
      "",
      "- The PixArt state sizes are computed from the site shapes (Σ C_in over the 224 static-A8 sites = "
      f"{C_SUM:,}). The DiT sizes are the allocated tensors measured in `ext/e2_confirm.json`.",
      f"- For scale: one PixArt-Σ forward is ≈ 2 × 0.6 B params × 2 rows × 4096 tokens ≈ {FWD / 1e12:.1f} TFLOP, so the DCT-4 / DCT-16 projections add "
      f"≈ {100 * px_flops(4) / FWD:.1f}% / {100 * px_flops(16) / FWD:.1f}% compute per step (unfused). Full feedback's {px_full / 2**30:.1f} GiB of "
      "persistent state per image is the binding deployment cost.", "",
      "## Unrun (by cost or by instruction)",
      "- D4 (DiT FID-2k, uniform dither) and D5 (DiT second set 2000–3999): by cost.",
      "- PixArt FID-2k: by cost.",
      "- §5 memory engineering (INT4 state, η, site budget): dropped from this allocation by the user. `mem.py` is written but untested on GPU."]
atomic_write_text(os.path.join(OUT, "dist", "REPORT.md"), "\n".join(L) + "\n")
print("\n".join(L))
