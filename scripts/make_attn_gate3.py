"""Gate 3 (attention sharing): storage variants at k_pass -> results/attn_share/gate3.md from the arm JSONs."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boa_dit.attn_share.gate2 import storage_bytes  # noqa: E402
from boa_dit.common import atomic_write_json, atomic_write_text  # noqa: E402

OUT = os.path.join(ROOT, "results", "attn_share")
VAR = [("V2", "windowed", "one mean map per (block, head) per 5-step window"),
       ("V3", "kernel", "31×31 offset kernel per (block, head, window), row-normalized at use"),
       ("V4", "sparse32", "top-32 entries per row of V1, renormalized (fp16 values + uint8 indices)"),
       ("V5", "condonly", "V1 with the cond map reused for the uncond branch")]


def load(p):
    p = os.path.join(OUT, "eval", p)
    return json.load(open(p)) if os.path.exists(p) else None


def main():
    k = json.load(open(os.path.join(OUT, "gate2_verdict.json")))["k_pass"]
    v1 = load(f"gate2_k{k}.json")
    b1 = storage_bytes("perstep", k)
    L = ["# Attention sharing — Gate 3: can the maps be stored cheaply?\n",
         "Generated by `scripts/make_attn_gate3.py`. FID-2k, seeds 0–1999, same protocol as Gate 2; V1 is the Gate 2 "
         f"arm `k{k}` itself (same seeds and maps, so it is not rerun). Sizes are for both CFG branches.\n",
         f"k_pass = **{k}**.\n",
         "| variant | what is stored | size | % of V1 | FID-2k | ΔFID vs V1 | rel. latent MSE vs FP | class changed |",
         "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
         f"| V1 | M for every (block, head, s < {k}) | {b1 / 1e6:.1f} MB | 100% | {v1['fid2k']:.2f} | — | "
         f"{v1['rel_mse_mean_512']:.4f} | {100 * v1['class_changed_frac_512']:.1f}% |"]
    res = {"k_pass": k, "V1": {"bytes": b1, "fid2k": v1["fid2k"]}}
    for name, kind, desc in VAR:
        b = storage_bytes(kind, k)
        r = load(f"gate3_{name}_k{k}.json")
        res[name] = {"bytes": b, "frac_of_V1": b / b1, "fid2k": r["fid2k"] if r else None}
        if r is None:
            L.append(f"| {name} | {desc} | {b / 1e6:.1f} MB | {100 * b / b1:.1f}% | pending | — | — | — |")
            continue
        res[name]["delta_vs_V1"] = r["fid2k"] - v1["fid2k"]
        L.append(f"| {name} | {desc} | {b / 1e6:.2f} MB | {100 * b / b1:.2f}% | {r['fid2k']:.2f} | "
                 f"{r['fid2k'] - v1['fid2k']:+.2f} | {r['rel_mse_mean_512']:.4f} | {100 * r['class_changed_frac_512']:.1f}% |")
    L.append("")
    L.append("Size note, known before any Gate 3 arm ran: on its own, only V3 can meet the ≤ 10% size condition. "
             f"V2 stores {-(-k // 5)} maps instead of {k} ({100 * storage_bytes('windowed', k) / b1:.0f}%), and V4 stores 3 bytes "
             f"for each of 32 of the 256 entries per row ({100 * storage_bytes('sparse32', k) / b1:.1f}%). With V5's branch sharing "
             f"applied, they would be {50 * storage_bytes('windowed', k) / b1:.0f}% and {50 * storage_bytes('sparse32', k) / b1:.1f}%; "
             "that combination was not run unless it appears in the table. The rule is unchanged.\n")
    done = all(res[n]["fid2k"] is not None for n, _, _ in VAR[:3])
    if done:
        ok = [n for n, _, _ in VAR[:3] if res[n]["delta_vs_V1"] <= 0.5 and res[n]["frac_of_V1"] <= 0.10]
        res["passing"] = ok
        res["verdict"] = "PASS" if ok else "STOP"
        L.append(f"Rule: PASS if any of V2–V4 is within +0.5 FID-2k of V1 at ≤ 10% of V1's size. Passing: {ok or 'none'}.")
        if res["V5"]["fid2k"] is not None:
            L.append(f"V5 (branch sharing) ΔFID vs V1: {res['V5']['delta_vs_V1']:+.2f}.")
        L.append(f"\n**Gate 3: {res['verdict']}**\n")
    else:
        L.append("**Gate 3: PENDING**\n")
    atomic_write_json(os.path.join(OUT, "gate3_verdict.json"), res)
    atomic_write_text(os.path.join(OUT, "gate3.md"), "\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
