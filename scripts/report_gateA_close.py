"""Prints the dated Gate A close entry for REPORT.md from the JSONs (append with >>)."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import make_gateA as G  # noqa: E402

u = {b: G.uniform(b) for b in (4, 3)}
a = {(x, b): G.arm(x, b) for x in G.ORDER for b in (4, 3)}
ts = {b: G.paired(a[("time2-16", b)], a[("static-32", b)]) for b in (4, 3)}
t3 = {b: G.paired(a[("time3-16", b)], a[("static-48", b)]) for b in (4, 3)}
su = {b: G.paired(a[("static-32", b)], u[b]) for b in (4, 3)}
ra = json.load(open(os.path.join(G.RES, "stage2", "row_attribution.json")))
gd = {(s, b): G.paired(G.load(os.path.join(G.RES, "stage2", "eval", f"latent_guard_{s}_w{b}.json")), u[b])
      for s in ("gate", "err") for b in (4, 3)}
sp = G.spent()
p = lambda r: f"{100 * r[0]:+.1f}% [{100 * r[1]:+.1f}, {100 * r[2]:+.1f}]"
print(f"""
## 2026-10-25 — FINAL STOP: Gate A (time-indexed low-rank correction) failed its pre-registered rule
- `results/gateA.md` (pre-registered in commit 01544c0; results generated by `scripts/make_gateA.py`).
- Rule pair, time2-16 vs static-32 (equal extra bits, 0.593/param): W4 {p(ts[4])}, W3 {p(ts[3])}. Needs ≥ +5% (W4) or
  ≥ +10% (W3) with CI > 0 → **fail at both**. time3-16 vs static-48 (equal bits, 0.889): W4 {p(t3[4])}, W3 {p(t3[3])}.
  Splitting rank across timestep regimes is strictly worse than spending it on one static correction.
- The static correction itself works (not a pre-registered question): static-32 vs plain uniform W4 {p(su[4])},
  W3 {p(su[3])}; static-48 reaches rel. latent MSE {a[('static-48', 4)]['rel_mse_mean']:.4f} (W4) and
  {a[('static-48', 3)]['rel_mse_mean']:.4f} (W3). Not FID-checked; W3 stays far from usable per the FID anchors.
- Item 2a: block {ra['top3_blocks'][0]} carries {100 * ra['blocks'][str(ra['top3_blocks'][0])]['contribution_share']:.0f}% of the
  W4 error on its own, almost all of it in `attn.qkv` ({100 * ra['layers'][f"b{ra['top3_blocks'][0]}.attn.qkv"]['contribution_share']:.0f}%).
- Item 2b: keeping the top-100 rows at W8 RTN makes things worse at both bit-widths and for both selections (gate-weighted
  W4 {p(gd[('gate', 4)])}, error-only W4 {p(gd[('err', 4)])}; W3 {p(gd[('gate', 3)])} / {p(gd[('err', 3)])}); the gate
  weighting adds nothing over the error ranking. Likely cause (untested): W8 RTN rows discard BoA's compensation for
  upstream quantization error.
- GPU-hours for items 1–3: {sum(sp.values()):.2f} (cap 3.5). The BoA-for-DiT line is closed; heavy BoA processes are done.
""")
