"""results/quantizer_observer/REPORT.md from the qo1 JSONs. Run: python scripts/make_quantizer_observer.py"""
import csv
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boa_dit.common import atomic_write_text

OUT = os.path.join(ROOT, "results", "quantizer_observer")
J = lambda f: json.load(open(os.path.join(OUT, f))) if os.path.exists(os.path.join(OUT, f)) else None
CH, PR, HR, SA, ES, OS_, OB, CO, MAN = (J(f) for f in ("checks.json", "profile.json", "headroom.json", "site_accounting.json", "errstats.json", "observer_select.json",
                                                    "observer.json", "cost.json", "manifest.json"))
rows = [r for r in csv.reader(open(os.path.join(ROOT, "results", "gpu_hours.csv"))) if r and r[0] == "qo1"]
spent = sum(float(r[-1]) for r in rows)
ci = lambda d, f=".4f", s=1: f"{s * d['v']:{f}} [{s * d['ci'][0]:{f}}, {s * d['ci'][1]:{f}}]"
pct = lambda d: f"{100 * d['v']:+.1f}% [{100 * d['ci'][0]:+.1f}, {100 * d['ci'][1]:+.1f}]"
st = lambda o: "completed" if o else "NOT RUN"
L = ["# Quantizer-informed error observability (qo1): report (generated by `scripts/make_quantizer_observer.py`)", "",
     "Bed: DiT-XL/2 256, DDIM-50, cfg 1.5, common smoothed W4, frozen single8 A8 + DCT-4 feedback, primary carry **E_L u100** "
     "(`ckpt/dit_joint/carry_E_L_u100.pt`, sha256 c2b70026…). Protocol and amendments: `results/quantizer_observer/PROTOCOL.md`.",
     f"**Budget: {spent:.2f} of 2.0 A30-h** (unique qo1 rows incl. failed/superseded runs). Diagnostic pilot; not a DNS extension; no FID.", "", "## Stages", ""]
for n, o in (("checks", CH), ("profile", PR), ("A1 headroom (fit/dev)", HR and HR.get("dev")), ("dev carry-transfer check", HR and HR.get("dev_original_carry")),
             ("site accounting", SA), ("A2 error statistics", ES), ("observer selection (fit/dev)", OS_), ("observer confirmation", OB and OB.get("gate")),
             ("propagation audit (D)", os.path.exists(os.path.join(OUT, "propagation_audit.md"))), ("live correction", J("live.json")), ("cost", CO)):
    L.append(f"- {n}: {st(o)}")
if CH:
    L += ["", f"Checks pass: {CH['pass']} (instrumented trace bit-exact vs deployed WA: {CH['c2_instrumented_trace_equals_deployed_WA']}; identity residual "
              f"{CH['c5_identity_max_rel_resid_energy']:.1e} relative; recompute mismatches {CH['c5_consumed_recompute_mismatch']}; rows independent {CH['c3_row_independence_img0']})."]
if HR:
    L += ["", "## A1. Removing activation quantization (conditional on these weights/carry)", "",
          "| split / carry | MSE_WA | ‖d_W‖² | ‖d_A‖² | 2⟨d_W,d_A⟩ | gain 1 − MSE_W/MSE_WA | closure |", "| --- | --- | --- | --- | --- | --- | ---: |"]
    for k in ("fit", "dev", "conf", "dev_original_carry"):
        if k in HR:
            h = HR[k]
            L.append(f"| {k} | {ci(h['mse_WA'])} | {ci(h['dW2'])} | {ci(h['dA2'])} | {ci(h['cross'])} | {pct(h['gain_remove_A8'])} | {h['closure_max_abs']:.1e} |")
    if "activation_prioritization" in HR:
        L.append(f"\nActivation prioritization (dev): **{HR['activation_prioritization']['rule']}** ({HR['activation_prioritization']['definition']}).")
if SA:
    a = SA["groups"]["all"]
    L += ["", "## Site accounting of the guarded compressed feedback (fit, first batch; float64)", "", SA["identity"], "",
          "| term | energy / ‖q − x‖² (all sites, steps) |", "| --- | ---: |"] + [f"| {k} | {v:.4g} |" for k, v in a["term_energy_frac_of_q_minus_x"].items()]
    big = sorted(a["cross_terms_2Gij"].items(), key=lambda kv: -abs(kv[1]))[:5]
    L += ["", "Largest cross terms (2G_ij / ‖q − x‖²): " + ", ".join(f"{k} {v / a['energy_q_minus_x']:+.3g}" for k, v in big) + ".",
          "Rates (all 64 fit images): " + ", ".join(f"{k} {v:.3g}" for k, v in a["rates"].items()) + ".",
          f"Identity residual (max over site/step) {SA['identity_resid_rel_max_site_step']:.1e} relative.", "", "| type | input clip | state guard | second clip | rounding clamp | spare code |",
          "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for t in ("attn.qkv", "attn.proj", "mlp.fc1", "mlp.fc2"):
        r = SA["groups"][f"type:{t}"]["rates"]
        L.append(f"| {t} | " + " | ".join(f"{v:.3g}" for v in r.values()) + " |")
    L.append(f"\n{SA['note']}")
if ES:
    L += ["", "## A2. Aligned local errors along the actual WA trajectory (fit + dev)", "",
          "| source | energy/img | lag-1 cos | lag-5 cos | DC frac | 4×4 DCT frac | bands 1–4 | temporal const / period-2 / rest | c (imagewise) |",
          "| --- | ---: | ---: | ---: | ---: | ---: | --- | --- | ---: |"]
    for s in ("eW", "eAW", "etot"):
        e = ES[s]
        L.append(f"| {s} | {e['energy_mean_per_image']:.4g} | {e['lag1_cos']:.3f} | {e['lag5_cos']:.3f} | {e['spatial_DC_frac']:.4f} | {e['dct4x4_frac']:.4f} | "
                 f"{' / '.join(f'{b:.3f}' for b in e['radial_band_frac'])} | {e['temporal_constant_frac']:.4f} / {e['temporal_period2_frac']:.4f} / {e['temporal_remaining_frac']:.4f} | "
                 f"{e['coherence_c_mean_imagewise']:.4f} |")
    L.append(f"\nc for independent zero-mean errors ≈ 1/T = 0.02. {ES['definition']}.")


def obs_table(res, title):
    out = ["", title, "", "| target | model | ratio raw | ratio centered | vs H (rel. change) | wins vs H | temporal-mean left | shuffle vs H (mean, min) | λ |",
           "| --- | --- | ---: | ---: | --- | ---: | ---: | --- | ---: |"]
    for tgt in ("eW", "eAW", "etot"):
        for m, r in res[tgt].items():
            vs = pct(r["vs_H_rel_change"]) if "vs_H_rel_change" in r else "—"
            sh = f"{100 * np.mean(r['shuffle_vs_H_rel_change']):+.1f}%, {100 * np.min(r['shuffle_vs_H_rel_change']):+.1f}%" if "shuffle_vs_H_rel_change" in r else "—"
            out.append(f"| {tgt} | {m} | {r['ratio_raw']:.4f} | {r['ratio_centered']:.4f} | {vs} | {r.get('wins_vs_H', '—')} | {r['temporal_mean_left_frac']:.4f} | {sh} | {r.get('lambda', '—')} |")
    return out


