"""W4A4 PixArt-Σ phase: results/w4a4/REPORT.md from the JSONs (pre-registration results/w4a4/rule.md)."""
import csv
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boa_dit.common import atomic_write_text  # noqa: E402

W = os.path.join(ROOT, "results", "w4a4")
BASE = "hsvd_r4_b0.5"
PAPER = {"H-SVDQuant r4": (16.47, 0.386), "SVDQuant r4": (14.94, 0.478), "SVDQuant r32": (16.27, 0.385), "DiRotQ": (16.36, 0.389)}
TYPES = ["attn1.to_q", "attn1.to_k", "attn1.to_v", "attn1.to_out.0", "attn2.to_q", "attn2.to_k", "attn2.to_v", "attn2.to_out.0",
         "ff.net.0.proj", "ff.net.2"]


def load(*p):
    p = os.path.join(W, *p)
    return json.load(open(p)) if os.path.exists(p) else None


def paired(x, y, key="rel_mse_per_triple"):
    """1 - mean(x)/mean(y), paired bootstrap 95% CI (2,000 resamples, seed 0); positive = x better."""
    x, y = np.array(x[key]), np.array(y[key])
    rng = np.random.default_rng(0)
    bs = [1 - x[i].mean() / y[i].mean() for i in (rng.integers(0, len(x), len(x)) for _ in range(2000))]
    lo, hi = np.percentile(bs, [2.5, 97.5])
    return 1 - x.mean() / y.mean(), lo, hi


def fmt(r):
    return "pending" if r is None else f"{100 * r[0]:+.1f}% [{100 * r[1]:+.1f}, {100 * r[2]:+.1f}]"


def passes(r, thr=0.05):
    return r is not None and r[0] >= thr and r[1] > 0


def spent():
    tot, by = 0.0, {}
    for row in csv.reader(open(os.path.join(ROOT, "results", "gpu_hours.csv"))):
        if len(row) >= 6 and row[0] == "w4a4" and row[5] != "gpu_hours":
            tot += float(row[5])
            k = row[1].split("_")[0]
            by[k] = by.get(k, 0.0) + float(row[5])
    return tot, by


def main():
    L = ["# W4A4 PixArt-Σ — report (generated by `scripts/make_w4a4.py`; pre-registration `rule.md`, prior art `prior_art.md`)\n"]
    base = load("screen", f"{BASE}.json")
    # screening table
    L.append("## Screening proxy (64 MJHQ prompts × 10 steps × 2 branches = 1,280 triples; rel. MSE of the noise prediction vs bf16)")
    L.append("Reduction vs the base (H-SVDQuant r4, β = ½) = 1 − proxy(arm)/proxy(base), paired bootstrap 95% CI over triples. "
             "An arm advances iff the reduction is ≥ 5% with the CI above 0.\n")
    L.append("| arm | bits/weight | proxy | vs base | advances |")
    L.append("| --- | ---: | ---: | --- | --- |")
    rows = [("fp", "bf16 through the harness (batch-layout floor)"), ("fp16", "fp16 pipeline (deepcompressor build), dtype floor"),
            ("rtn_r0", "RTN"), ("gptq_r0", "GPTQ-r0"), ("svdq_dc_r32", "SVDQuant r32 (deepcompressor)"), ("svdq_r32", "SVDQuant r32 (reimpl.)"),
            ("hsvd_r0_b0.5", "H-SVDQuant r0"), (BASE, "**H-SVDQuant r4 (base)**"), (f"{BASE}_rep2", "base, second run (determinism)"),
            ("hsvd_r4_b0", "X1: β = 0, r4"), ("hsvd_r4_heig", "X1: heig, r4"), ("hsvd_r8_b0.5", "X1: β = ½, r8"), ("hsvd_r8_heig", "X1: heig, r8"),
            ("hsvd_rw4a4_alloc_b0.5", "X2: allocation"), ("hsvdB4_r4_b0.5", "X3: B4 (error order + asymmetric)")]
    scr = {}
    for name, lab in rows:
        js = load("screen", f"{name}.json")
        if js is None:
            continue
        q = load("quant", f"{name}.json")
        scr[name] = js
        r = paired(js, base) if base and name not in (BASE,) else None
        L.append(f"| {lab} (`{name}`) | {q['bits_per_weight']:.3f} |" if q else f"| {lab} (`{name}`) | — |")
        L[-1] += f" {js['rel_mse_mean']:.4f} | {fmt(r) if r else '—'} | {('yes' if passes(r) else 'no') if r and name.startswith('hsvd') and name != f'{BASE}_rep2' else '—'} |"
    if base and scr.get(f"{BASE}_rep2"):
        same = scr[f"{BASE}_rep2"]["rel_mse_per_triple"] == base["rel_mse_per_triple"]
        L.append(f"\nDeterminism: the base screened twice gives {'identical' if same else 'DIFFERENT'} per-triple values.")
    L.append("")
    # base validation images
    L.append("## Base validation (MJHQ-256, 1024², PSNR / LPIPS-VGG vs the bf16 image)")
    L.append("| method | ours PSNR | ours LPIPS | paper PSNR | paper LPIPS |")
    L.append("| --- | ---: | ---: | ---: | ---: |")
    img = {n: load("eval", f"img256_{n}.json") for n in (BASE, "svdq_dc_r32", "svdq_r32")}
    for n, lab, pk in ((BASE, "H-SVDQuant r4 (ours)", "H-SVDQuant r4"), ("svdq_dc_r32", "SVDQuant r32 (deepcompressor)", "SVDQuant r32"),
                       ("svdq_r32", "SVDQuant r32 (reimpl.)", "SVDQuant r32")):
        js = img[n]
        if js:
            L.append(f"| {lab} | {js['psnr_mean']:.2f} | {js['lpips_mean']:.3f} | {PAPER[pk][0]:.2f} | {PAPER[pk][1]:.3f} |")
    sv = img["svdq_dc_r32"] or img["svdq_r32"]
    if img[BASE] and sv:
        off_p, off_l = sv["psnr_mean"] - PAPER["SVDQuant r32"][0], sv["lpips_mean"] - PAPER["SVDQuant r32"][1]
        adj = img[BASE]["psnr_mean"] - off_p
        within = abs(adj - PAPER["H-SVDQuant r4"][0]) <= 0.5
        ge = img[BASE]["psnr_mean"] >= sv["psnr_mean"] or img[BASE]["lpips_mean"] <= sv["lpips_mean"]
        L.append(f"\nProtocol offset (ours − paper, SVDQuant r32): PSNR {off_p:+.2f} dB, LPIPS {off_l:+.3f}. "
                 f"Offset-adjusted base PSNR {adj:.2f} vs paper 16.47.")
        L.append(f"\n**Read 1 (base valid): {'HOLDS' if within and ge else 'FAILS'}** (within 0.5 dB: {within}; "
                 f"≥ SVDQuant r32 on PSNR or LPIPS: {ge}).\n")
    # rho
    rho = load("rho.json")
    L.append("## ρ diagnostic (base model, FP-reference inputs)")
    if rho:
        L.append("| block | step | λmax/λmedian | ρ |")
        L.append("| ---: | --- | ---: | ---: |")
        for b, d in rho["blocks"].items():
            for k, m in d.items():
                L.append(f"| {b} | {k} | {m['lmax_over_lmedian']:.3g} | {m['rho']:.3f} |")
        L.append(f"\nGate (ρ ≥ 1 and spread ≥ 10, step mean, ≥ 2 of 4 blocks): **{'PASS' if rho['gate_pass'] else 'FAIL'}** "
                 f"({rho['gate_blocks_passing']}/4){'; ρ < 1 in all four blocks: GPTQ + branch already leaves its error where the network is insensitive, X4 not built' if rho['rho_below_1_everywhere'] else ''}.\n")
    else:
        L.append("pending\n")
    # X1 trace ratios
    L.append("## X1 subspace: tr(H̃_⊥)/tr(H̃) by layer type (chosen iteration's first-iteration value, mean over 28 blocks)")
    arms = [("hsvd_r4_b0", "β = 0, r4"), (BASE, "β = ½, r4"), ("hsvd_r4_heig", "heig, r4"), ("hsvd_r8_b0.5", "β = ½, r8"), ("hsvd_r8_heig", "heig, r8")]
    have = [(n, lab, load("quant", f"{n}.json")) for n, lab in arms]
    have = [h for h in have if h[2]]
    if have:
        L.append("| layer type | " + " | ".join(lab for _, lab, _ in have) + " |")
        L.append("| --- | " + " | ".join("---:" for _ in have) + " |")
        for t in TYPES:
            vals = []
            for _, _, q in have:
                v = [q["layers"][k]["iters"][0]["trace_ratio_Hperp"] for k in q["layers"] if k.split(".", 1)[1] == t]
                vals.append(f"{np.mean(v):.3f}" if v else "—")
            L.append(f"| {t} | " + " | ".join(vals) + " |")
    L.append("")
    al = load("alloc.json")
    if al:
        L.append(f"## X2 allocation\nRule used: **{al['rule']}** (90% rule degenerate: {al['degenerate_r90']}; r90 range "
                 f"{al['r90_range']}; cap {al['cap']}). Branch params {al['params']:,} = {al['params_ratio']:.3f} × the fixed-r4 total. "
                 f"r distribution {al['r_distribution']}.\n")
        L.append("| layer type | mean r | histogram |")
        L.append("| --- | ---: | --- |")
        for t, v in al["by_type"].items():
            L.append(f"| {t} | {v['mean']:.1f} | {v['hist']} |")
        L.append("")
    # reads (screen part)
    L.append("## Reads (screen stage)")
    def red(a, b):
        return paired(scr[a], scr[b]) if a in scr and b in scr else None
    for r_, (h, b) in ((4, ("hsvd_r4_heig", BASE)), (8, ("hsvd_r8_heig", "hsvd_r8_b0.5"))):
        x = red(h, b)
        if x:
            verdict = "heig wins" if passes(x) else ("β = ½ wins" if (x[0] <= -0.05 and x[2] < 0) else "tie")
            L.append(f"- Subspace at r = {r_}: heig vs β = ½ {fmt(x)} → **{verdict}**.")
    x = red("hsvd_rw4a4_alloc_b0.5", BASE)
    if x:
        L.append(f"- Allocation (X2 vs base): {fmt(x)} → {'passes screen' if passes(x) else 'does not pass'}.")
    x = red("hsvdB4_r4_b0.5", BASE)
    if x:
        L.append(f"- Asymmetric target (B4 vs B1 = base): {fmt(x)} → {'passes screen' if passes(x) else 'does not pass'}.")
    tot, by = spent()
    L.append(f"\n## Compute\nA30-hours, stage w4a4 (from `gpu_hours.csv`, incl. hand-logged deepcompressor time): **{tot:.2f}** of 14. "
             + ", ".join(f"{k} {v:.2f}" for k, v in sorted(by.items())) + ".\n")
    L.append("## Deviations (recorded as they happened)")
    L.append("- Gram GEMMs use TF32 inputs (fp32 storage and accumulation), the only TF32 use; pre-registered as fp32. "
             "Reason: fp32 Grams made calibration ~42 min/arm (fc2's 4,608² Gram dominated); with TF32, 28 min/arm.")
    L.append("- H̃_⊥ is formed in fp64 and symmetrized; GPTQ's Cholesky retries with damping ×10 when M_Q is not numerically PD "
             "(the damping actually used is logged per layer as `gptq_damp_used`). fp32 cancellation broke PD-ness on PixArt's "
             "outlier channels (block 0, attn2.to_q).")
    L.append("- deepcompressor needed Python 3.11 features (`typing.Self`, `enum.StrEnum`); it runs in an isolated venv on 3.10 "
             "with a two-line backport (`sitecustomize.py`) and without xformers / ImageReward / lm_eval extras. Its SVDQuant uses "
             "its own protocol (128 calibration prompts, fp16, activation shift + unsigned activations, weight range search); "
             "its GPU time is logged by hand from its run log.")
    atomic_write_text(os.path.join(W, "REPORT.md"), "\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
