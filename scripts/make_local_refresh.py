"""Generate results/local_error_refresh/REPORT.md from the ler1 JSON outputs (missing stages reported as unrun)."""
import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "results", "local_error_refresh")


def j(n):
    f = os.path.join(OUT, n)
    return json.load(open(f)) if os.path.exists(f) else None


def arms_table(res, L):
    L += ["| arm | latent rel. MSE mean | median | PSNR (dB) | LPIPS |", "|---|---:|---:|---:|---:|"]
    for a, s in res["summary"].items():
        L.append(f"| {a} | {s['rel_mse']['mean']:.5f} | {s['rel_mse']['median']:.5f} | {s['psnr']['mean']:.2f} | {s['lpips']['mean']:.4f} |")


def contrast_table(C, L):
    L += ["", "| contrast | mean-MSE ratio [95% CI] | mean diff [CI] | median diff | wins | ΔLPIPS [CI] | ΔPSNR [CI] |", "|---|---:|---:|---:|---:|---:|---:|"]
    for k, v in C.items():
        m, lp, ps = v["rel_mse"], v["lpips"], v["psnr"]
        L.append(f"| {k.replace('_vs_', ' / ')} | {m['ratio']:.3f} [{m['ratio_ci'][0]:.3f}, {m['ratio_ci'][1]:.3f}] | {m['diff']:+.5f} [{m['diff_ci'][0]:+.5f}, "
                 f"{m['diff_ci'][1]:+.5f}] | {m['median_diff']:+.5f} | {m['wins_x']}/{m['n']} | {lp['diff']:+.4f} [{lp['diff_ci'][0]:+.4f}, {lp['diff_ci'][1]:+.4f}] | "
                 f"{ps['diff']:+.2f} [{ps['diff_ci'][0]:+.2f}, {ps['diff_ci'][1]:+.2f}] |")


def inter(it):
    return (f"I = [E(L) − E(LA)] − [E(G) − E(A)] = {it['I_abs']:+.5f} [{it['I_abs_ci'][0]:+.5f}, {it['I_abs_ci'][1]:+.5f}] (feedback gain with local correction "
            f"{it['feedback_gain_with_local']:+.5f} [{it['feedback_gain_with_local_ci'][0]:+.5f}, {it['feedback_gain_with_local_ci'][1]:+.5f}], without "
            f"{it['feedback_gain_without']:+.5f} [{it['feedback_gain_without_ci'][0]:+.5f}, {it['feedback_gain_without_ci'][1]:+.5f}])")


def main():
    ch, sel, tr, e1, e2, dg, fr, cf, co = (j(n) for n in ("checks.json", "selection.json", "trace.json", "dev_e1.json", "dev_e2.json", "diag.json",
                                                          "frozen.json", "conf.json", "cost.json"))
    rows = [r for r in csv.reader(open(os.path.join(ROOT, "results", "gpu_hours.csv"))) if r and r[0] == "ler1"]
    tot = sum(float(r[-1]) for r in rows)
    L = ["# Local weight-error refresh with temporal activation feedback (ler1): report", "",
         "Protocol `PROTOCOL.md` (pre-registered 2026-10-30, commit c61fe26; amendments dated). Generated by `scripts/make_local_refresh.py`.",
         f"**GPU: {tot:.3f} of 2.0 A30-h** ({', '.join(f'{r[1]} {float(r[-1]):.4f}' for r in rows)}).",
         "Fidelity to a generated FP-50 reference on DiT-XL/2 256 (fake-quant simulation). **No deployable speedup, novelty or generation-quality claim; no FID.**", "",
         "IDs: G = guarded DCT-4 quantizer with zero previous state every step (no temporal feedback); A = DCT-4 feedback; Q = historical static A8 (dev sanity);",
         "O = fresh (K = 1) local correction; L_K / LA_K = local held corrections refreshed every K steps without / with feedback; MP / MPA = selected linears",
         "replaced by reference weights (no carry there) without / with feedback; C_K = full-FP output anchoring with reuse on G.", ""]
    L += ["## Engineering checks"]
    if ch:
        L += [f"- C1 parent reproduction bitwise (61000–61031, batch 32): {ch['C1_parent_bitwise']}; zero-state A = G {ch['C1_zero_state_A_equals_G']}; "
              f"G = A after step 0 {ch['C1_G_A_equal_after_step0']}",
              f"- C2 capture point pass {ch['C2_pass']} (h·s vs raw input rel. L2: " +
              ", ".join(f"{k} {v['v']:.1e} ({v['dtype'].replace('torch.', '')})" for k, v in ch['C2_h_times_s_equals_raw_rel_l2'].items()) + ")",
              f"- C3 synthetic fp64 identities pass {ch['C3_pass']} (max identity residual "
              f"{max(v['identity_rel_residual'] for v in ch['C3_synthetic_fp64'].values()):.1e}; ideal-feedback identity violated by clipping/compression as expected: " +
              ", ".join(f"{k} {v['full_state_identity_rel_residual']:.2f}" for k, v in ch['C3_synthetic_fp64'].items()) + ")",
              f"- C4 M h helper vs module fp32 max rel. L2 {max(ch['C4_helper_vs_module_fp32_rel'].values()):.1e}; live fp16-autocast defect max "
              f"{max(ch['C4_live_autocast_defect_rel'].values()):.1e}",
              f"- C5 K = 1 vs W h + M(q − h) + bias: max rel. L2 {ch['C5_K1_max_rel_l2']:.1e} (tol 5e-3) pass {ch['C5_K1_pass']}; M = W: b = 0 {ch['C5_M_equals_W_zero_b']}, "
              f"trajectory = G {ch['C5_M_equals_W_trajectory_equals_G']}",
              f"- C6 zero correction = G / A {ch['C6_zero_b_bitwise']}; MP weights = W {ch['C6_MP_weights_equal_W']}, carry removed at selected "
              f"{ch['C6_MP_carry_removed_selected']}, kept elsewhere {ch['C6_MP_carry_present_elsewhere']}, output = F.linear(q, W, bias) {ch['C6_MP_output_equals_Wq_bitwise']}",
              f"- C7/C9 one quantizer update per site per call, refresh counts 13 / 7, FP calls 0: {ch['C7_C9_pass']}; helper touches no quantizer {ch['C7_measure_no_quantizer_call']}",
              f"- C8 save/resume bitwise {ch['C8_save_resume_bitwise']}",
              "- C10 profile (s per 16-image trajectory, 12 sites): " + ", ".join(f"{k} {v:.1f}" for k, v in ch["C10_profile_s_per_16_images_12_sites"].items()),
              f"- **All checks pass: {ch['pass']}**"]
    else:
        L.append("- **Unrun.**")
    L += ["", "## E0 site screen (60200–60207, steps 5/25/45 of G's trajectory)"]
    if sel:
        L += ["", "| rank | site | abs. SSE reduction | relative |", "|---:|---|---:|---:|"]
        for i, k in enumerate(sel["ranking"]):
            L.append(f"| {i + 1} | {k}{' **(selected)**' if k in sel['selected'] else ''} | {sel['score_abs_reduction'][k]:+.4g} | {sel['score_rel_reduction'][k]:+.2%} |")
        L += ["", f"Selected (top three within this pool, ≤ 1 per block): {', '.join(sel['selected'])}."]
    else:
        L.append("- **Unrun.**")
    L += ["", "## E1 local persistence of eW_t = (M − W) h_t (8 dev images, nothing applied)"]
    if tr:
        L += ["", "| trajectory | site | lag 1 Σ‖Δ‖²/Σ‖eW‖² [CI] | lag 4 | lag 8 | ρ lag 1 / 4 / 8 | E_t/E_a lag 4 | K4 periodic residual [CI] | K8 [CI] |",
              "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
        for arm, res in tr["arms"].items():
            for k, r in res.items():
                f = lambda d: f"{d['v']:.3f} [{d['ci'][0]:.3f}, {d['ci'][1]:.3f}]"
                L.append(f"| {arm} | {k} | {f(r['lag1']['diff_over_Et'])} | {r['lag4']['diff_over_Et']['v']:.3f} | {r['lag8']['diff_over_Et']['v']:.3f} | "
                         f"{r['lag1']['uncentered_corr']:.3f} / {r['lag4']['uncentered_corr']:.3f} / {r['lag8']['uncentered_corr']:.3f} | {r['lag4']['Et_over_Ea']:.3f} | "
                         f"{f(r['periodic_K4_residual_over_total'])} | {f(r['periodic_K8_residual_over_total'])} |")
        L += ["", "Periodic residual uses the actual age since the last refresh (0..K−1), i.e. the error a K-schedule leaves before any feedback/nonlinear effects."]
    else:
        L.append("- **Unrun.**")
    L += ["", "## E1 fresh-correction headroom (16 dev images 60208–60223, batch 16)", ""]
    if e1:
        arms_table(e1, L)
        contrast_table(e1["contrasts"], L)
        h = e1["headroom"]
        L += ["", f"- Headroom rule: O3/G = {h['O3_over_G']:.3f}, OA3/A = {h['OA3_over_A']:.3f} → **{'proceed' if h['proceed'] else 'stop'}**."]
    else:
        L.append("- **Unrun.**")
    L += ["", "## E2 held corrections (same 16 dev images; G, A, Q, FP50 reused from E1)", ""]
    if e2:
        arms_table(e2, L)
        contrast_table(e2["contrasts"], L)
        k, s = e2["K_rule"], e2["stop_rule"]
        L += ["", f"- K rule: E(LA8)/E(LA4) = {k['E_LA8_over_E_LA4']:.3f}, ΔLPIPS(LA8 − LA4) = {k['LPIPS_LA8_minus_LA4']:+.4f} → **K* = {k['K_star']}**.",
              f"- Stop rule: E(LA4)/E(G) = {s['E_LA4_over_G']:.3f}, E(LA8)/E(G) = {s['E_LA8_over_G']:.3f} → stop before confirmation: **{s['stop_before_confirmation']}**.",
              f"- Dev interaction (K4): {inter(e2['interaction_K4'])}.", f"- Dev interaction (K8): {inter(e2['interaction_K8'])}."]
        sh = e2.get("shuffle")
        if sh:
            rf = "n/a" if sh["recovered_fraction"] is None else f"{sh['recovered_fraction']:.2f}"
            L.append(f"- Sample-specificity control {sh['arm']}: genuine gain over A {sh['genuine_gain_over_A']:+.5f}, shuffled {sh['shuffled_gain_over_A']:+.5f} "
                     f"(recovered fraction {rf}; label repeats {sh['label_repeats']}/16) → mean-bias control triggered: {sh['mean_bias_control_triggered']}.")
    else:
        L.append("- **Unrun.**")
    L += ["", "## Layer and feedback accounting (8 dev images, own trajectories)"]
    if dg:
        L += ["", "Energies relative to E[lhs] = Σ‖y_concept − (W h + bias)‖² at each selected site (sums over steps, rows, tokens, channels).", "",
              "| arm | site | E[a] | E[v] | E[δb] | 2⟨a,v⟩ | 2⟨a,δb⟩ | 2⟨v,δb⟩ | E[eW]/E[lhs] | identity residual | live fp16 defect |", "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for arm, r in dg["arms"].items():
            for k, v in r["layer"].items():
                e = v["E[lhs]"]
                L.append(f"| {arm} | {k} | {v['E[a]'] / e:.3f} | {v['E[v]'] / e:.3f} | {v['E[db]'] / e:.1e} | {v['2<a,v>'] / e:+.3f} | {v['2<a,db>'] / e:+.1e} | "
                         f"{v['2<v,db>'] / e:+.1e} | {v['E[eW]'] / e:.3f} | {v['identity_rel_residual']:.1e} | {v['live_defect_rel']:.1e} |")
        L += ["", "Guarded-feedback accounting (quantizer-observer identity q − x = p − p_next + c0 + g + ρ_u + c1 − (I−P)r − a + η; energies / E[q − x]; rates per element):", "",
              "| arm | group | p | −p_next | c0 input clip | g guard | c1 2nd clip | −(I−P)r discarded | −a clamp | η storage | input-clip rate | guard rate | 2nd-clip rate (old counter) | spare-code rate | id. residual |",
              "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for arm, r in dg["arms"].items():
            for gname in sorted(r["feedback_accounting"], key=lambda s: (not s.startswith("all"), s)):
                g = r["feedback_accounting"][gname]
                e = g["E[q-x]"]
                L.append(f"| {arm} | {gname} | {g['E[p]'] / e:.3f} | {g['E[-p_next]'] / e:.3f} | {g['E[c0_input_clip]'] / e:.2e} | {g['E[g_state_guard]'] / e:.2e} | "
                         f"{g['E[c1_second_clip]'] / e:.2e} | {g['E[-(I-P)r_discarded]'] / e:.3f} | {g['E[-a_residual_clamp]'] / e:.2e} | {g['E[eta_storage]'] / e:.2e} | "
                         f"{g['rate_input_clip']:.2e} | {g['rate_state_guard']:.2e} | {g['rate_second_clip_old_counter']:.2e} | {g['rate_spare_code']:.2e} | {g['identity_rel_residual']:.1e} |")
        L += ["", "- Layer identities are local (relative to W h on the cheap path's current input); a and v can cancel; not an endpoint decomposition."]
    else:
        L.append("- Not run.")
    L += ["", "## E3 confirmation (97100–97163, fresh, batch 32, opened once)", ""]
    if cf:
        L += [f"Frozen: sites {', '.join(cf['sites'])}; K* = {cf['K_star']}; arms {cf['arm_names']}.", ""]
        arms_table(cf, L)
        contrast_table(cf["contrasts"], L)
        L += ["", f"- **Integration (LA / L): {cf['reading_integration_LA_vs_L']}.**", f"- **Local correction (L / G): {cf['reading_local_L_vs_G']}**; LA / A: {cf['reading_LA_vs_A']}.",
              f"- Versus ordinary mixed precision: L / MP {cf['reading_L_vs_MP']}; LA / MPA {cf['reading_LA_vs_MPA']}.",
              f"- Versus output anchoring: LA / C {cf['reading_LA_vs_C']} (lower ratio = LA better).", f"- {inter(cf['interaction'])}.",
              "- Simulation timing during confirmation (s per 32-image trajectory, all models resident): " +
              ", ".join(f"{a} {v['median']:.1f}" for a, v in cf["timing_s_per_batch32"].items()) + "."]
    else:
        L.append("- **Unrun.**")
    L += ["", "## Costs"]
    if co:
        L += ["", f"{co['note']}. Batch {co['batch']}.", "", "| arm | load s | median s / batch | s / image | peak GB during sampling | held-correction bytes / image | feedback-state bytes / image |",
              "|---|---:|---:|---:|---:|---:|---:|"]
        for k, v in co["arms"].items():
            st = v["state"] or {}
            L.append(f"| {k} ({v['arm']}) | {v['load_s']:.1f} | {v['median_s']:.2f} | {v['per_image_s']:.3f} | {v['peak_bytes_during_sampling'] / 1e9:.2f} | "
                     f"{st.get('held_correction_bytes_per_image_incl_cfg', 0) / 1e6:.2f} MB | {st.get('feedback_state_bytes_per_image_incl_cfg', 0) / 1e6:.2f} MB |")
        an = co["analytic"]
        L += ["", f"- Decode: {co['decode_s_per_batch']:.2f} s per batch. Refreshes per trajectory: {an['refreshes_per_trajectory']}.",
              f"- Analytic: selected reference weights add {an['local_extra_weight_bytes_fp16'] / 1e6:.1f} MB (fp16); MP optimized change "
              f"{an['MP_optimized_delta_bytes'] / 1e6:+.1f} MB (fp16 W replaces packed W4 codes + carry; scales excluded). {an['note']}"]
    else:
        L.append("- Not measured.")
    open(os.path.join(OUT, "REPORT.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
