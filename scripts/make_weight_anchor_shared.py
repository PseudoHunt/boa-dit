"""Generate results/weight_anchor_shared/REPORT.md from the ws1 JSON outputs (missing stages reported as unrun)."""
import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "results", "weight_anchor_shared")


def j(name):
    f = os.path.join(OUT, name)
    return json.load(open(f)) if os.path.exists(f) else None


def r3(c):
    return f"{c['ratio']:.3f} [{c['ratio_ci'][0]:.3f}, {c['ratio_ci'][1]:.3f}]"


def arms_table(res, L, order):
    L += ["| arm | latent rel. MSE mean | median | PSNR mean (dB) | LPIPS mean |", "|---|---:|---:|---:|---:|"]
    for a in order:
        if a in res["summary"]:
            s = res["summary"][a]
            L.append(f"| {a} | {s['rel_mse']['mean']:.5f} | {s['rel_mse']['median']:.5f} | {s['psnr']['mean']:.2f} | {s['lpips']['mean']:.4f} |")


def contrast_table(res, L):
    L += ["| contrast | mean-MSE ratio [95% CI] | mean diff [CI] | median diff | wins | ΔLPIPS [CI] | ΔPSNR [CI] |", "|---|---:|---:|---:|---:|---:|---:|"]
    for k, v in res["contrasts"].items():
        m, lp, ps = v["rel_mse"], v["lpips"], v["psnr"]
        L.append(f"| {k.replace('_vs_', ' vs ')} | {r3(m)} | {m['diff']:+.5f} [{m['diff_ci'][0]:+.5f}, {m['diff_ci'][1]:+.5f}] | {m['median_diff']:+.5f} | "
                 f"{m['wins_x']}/{m['n']} | {lp['diff']:+.4f} [{lp['diff_ci'][0]:+.4f}, {lp['diff_ci'][1]:+.4f}] | {ps['diff']:+.2f} [{ps['diff_ci'][0]:+.2f}, {ps['diff_ci'][1]:+.2f}] |")


def main():
    st, B, C, D, DR, TR, F, S = (j(n) for n in ("selftest.json", "build.json", "checks.json", "dev.json", "dev_rtn.json", "traces.json", "conf.json", "storage.json"))
    rows = [r for r in csv.reader(open(os.path.join(ROOT, "results", "gpu_hours.csv"))) if r and r[0] == "ws1"]
    tot = sum(float(r[-1]) for r in rows)
    L = ["# Shared W4 / higher-precision anchors (ws1): report", "",
         "Protocol `PROTOCOL.md` (pre-registered 2026-10-30, commit 20e2ef5). Implementation notes `implementation.md`. Generated by `scripts/make_weight_anchor_shared.py`.",
         f"**GPU: {tot:.3f} of 2.0 A30-h** ({', '.join(f'{r[1]} {float(r[-1]):.4f}' for r in rows)}); remaining {2.0 - tot:.3f} h unspent.",
         "Storage-and-accuracy pilot. **No speedup, peak-RAM or generation-quality claim follows.** Fidelity is to a generated FP-50 reference.", ""]
    L += ["## Status", ""]
    if F:
        d = F["decisions"]
        L += [f"- **Low model identical:** {bool(C and C['K1_q4_state_bitexact_vs_heig8'] and C['K1_q4_equals_wa8_cache'])} (state dict, forward and DDIM-50 trajectory bitwise vs heig-8 / wa8 cache).",
              f"- **Selected candidate (dev rule):** {F['selected']}.",
              f"- **Decision 1, useful reuse (R_shared vs A_shared):** {d['1_useful_reuse']}.",
              f"- **Decision 2, preserve independent-anchor performance (vs R8, margins 1.10 / 0.01):** {d['2_preserve_independent']} "
              f"(ratio {d['2_detail']['ratio_R_shared_over_R8']:.3f} [{d['2_detail']['ratio_ci'][0]:.3f}, {d['2_detail']['ratio_ci'][1]:.3f}], "
              f"ΔLPIPS {d['2_detail']['dLPIPS']:+.4f} [{d['2_detail']['dLPIPS_ci'][0]:+.4f}, {d['2_detail']['dLPIPS_ci'][1]:+.4f}]).",
              f"- **Decision 3, storage:** shared smaller than the independent pair: {d['3_storage']['shared_smaller_than_pair']} "
              f"(saves {d['3_storage']['saving_bytes']:,} B = {100 * d['3_storage']['saving_frac_of_pair']:.1f}% of the pair file).",
              f"- Retained gain B = (E_Q4 − E_Rshared)/(E_Q4 − E_R8) = {F['retained']['B']:.3f} [{F['retained']['B_ci'][0]:.3f}, {F['retained']['B_ci'][1]:.3f}]; "
              f"gains over Q4: shared {F['retained']['gain_shared']:.5f} [{F['retained']['gain_shared_ci'][0]:.5f}, {F['retained']['gain_shared_ci'][1]:.5f}], "
              f"R8 {F['retained']['gain_R8']:.5f} [{F['retained']['gain_R8_ci'][0]:.5f}, {F['retained']['gain_R8_ci'][1]:.5f}]. Not a headline: the residual-error penalty vs R8 is decision 2."]
    else:
        L.append("- Confirmation **unrun**.")
    L += ["", "## Constructions (local, 112 block linears)", ""]
    if B:
        a = B["aggregate"]
        L += ["| construction | mean ‖W−Q‖/‖W‖ | mean after carry ‖(W−Q)−δVᵀ‖/‖W‖ | Σ projected quadratic tr(E·PHP·Eᵀ) |", "|---|---:|---:|---:|"]
        for c, nm in (("w4", "Q4 (heig-8, frozen)"), ("A_gptq", "A-GPTQ (residual, own grid)"), ("A_rtn", "A-RTN (residual, rtn)"), ("B_gptq", "B-GPTQ (fixed prefix)")):
            L.append(f"| {nm} | {a[c]['rel_frob']:.4f} | {a[c]['rel_frob_after_carry']:.4f} | {a[c]['proj_quad_sum']:.4g} |")
        L.append("| H8 (wa8, independent) | 0.0146 | — | 29.53 |")
        ce = a["B_gptq"]["ceiling"]
        L += ["", f"- Projected metric is blind to span(V) (cannot measure the carry); the full unprojected metric is {B['full_unprojected_metric']}.",
              f"- B ceiling: {100 * ce['outside_frac_mean']:.1f}% of elements wanted a fine code outside their fixed W4 cell during GPTQ "
              f"({100 * ce['static_outside_frac_mean']:.1f}% for the uncompensated residual); those elements carry {100 * ce['outside_err_energy_share']:.1f}% of B's error energy.",
              "  B's admissible correction is [−s4/2, 7s4/16] per element; this is a ceiling of the fixed-prefix construction, not of jointly optimized nested quantizers.",
              f"- Carry for A, direct vs algebraic (δ4 − D̂V, fp32): max-abs {max(B['carry_alg_vs_direct_max_abs'].values()):.2g}. Round-trip of all artifacts: {B['roundtrip']['pass']}.",
              f"- Selftest (CPU): constrained rounding vs index-domain enumeration 0 non-tie mismatches, ties half-to-even; column loop = unblocked reference: "
              f"{st['column_loop_vs_reference']['bitexact'] if st else '—'}; full-grid loop reproduces heig-8 layer 0: {B['loop_full_grid_reproduces_q4_layer0']}."]
    L += ["", "## Storage (exact bytes; MB = 10⁶ B, MiB = 2²⁰ B)", ""]
    if S:
        nm = {"q4": "(d) Q4 alone", "h8": "(c) H8 alone", "pair": "(a) independent Q4 + H8 (V, adaLN, other shared once)", "A_gptq": "(b) shared Q4 + A refinement",
              "B_gptq": "(b) shared Q4 + B refinement", "A_rtn": "(b) shared Q4 + A-RTN refinement"}
        L += ["| artifact | on-disk bytes | MB | MiB | logical tensor bytes |", "|---|---:|---:|---:|---:|"]
        for k in ("pair", "A_gptq", "B_gptq", "A_rtn", "h8", "q4"):
            s = S["summary"][k]
            L.append(f"| {nm[k]} | {s['on_disk']['bytes']:,} | {s['on_disk']['MB']:.1f} | {s['on_disk']['MiB']:.1f} | {s['logical']['bytes']:,} |")
        f16 = S["fp16_reference_computed"]
        L.append(f"| (e) FP16 reference (computed, 2 B × state-dict elements) | {f16['bytes']:,} | {f16['MB']:.1f} | {f16['MiB']:.1f} | — |")
        bc = S["files"]["A_gptq"]["by_component"]
        L += ["", "Components of the shared A artifact (bytes): " + ", ".join(f"{k} {v:,}" for k, v in bc.items()) + ".",
              f"- Ideal dense-payload saving (12 → 8 bits on 445,906,944 weights) = {S['ideal_dense_payload_saving_bytes']:,} B; measured whole-file saving A "
              f"{S['shared_vs_pair']['A_gptq']['saving_bytes']:,} B ({100 * S['shared_vs_pair']['A_gptq']['saving_frac_of_pair']:.1f}% of the pair), "
              f"B {S['shared_vs_pair']['B_gptq']['saving_bytes']:,} B ({100 * S['shared_vs_pair']['B_gptq']['saving_frac_of_pair']:.1f}%; no refinement scale/zero). "
              "adaLN (8-bit), fp32 other tensors, scales and carries are unchanged, so the whole-model saving is ~24%, not 33%.",
              "- Metadata kept at evaluated precision (fp32 scales, fp32 other tensors, fp16 carry); an fp16 metadata ablation was not run.",
              f"- Resident simulated weights: each live model is fp32-dequantized (2.70 GB) + fp16 carry; measured peak during confirmation (4 models resident): "
              f"allocated {F['peak_mem_live']['allocated'] / 1e9:.2f} GB, reserved {F['peak_mem_live']['reserved'] / 1e9:.2f} GB. The two-plane artifact saves ROM; this "
              "simulation does not save RAM. Packed-kernel memory = logical bytes above (**unmeasured**; lazy decoding would need a buffer and work)." if F else ""]
    for title, res, order in (("Development (94000–94031, exploratory; cached wa8 FP50/Q4/H8/R8 after K1)", D,
                               ["Q4", "H8", "R8", "H_A_gptq", "A_A_gptq", "R_A_gptq", "H_B_gptq", "A_B_gptq", "R_B_gptq"]),
                              ("A-RTN live control (development only, never promotable)", DR, ["H_A_rtn", "A_A_rtn", "R_A_rtn"]),
                              ("Confirmation (95100–95163, fresh, opened once; 10,000 paired bootstrap replicates, seed 0)", F,
                               ["Q4", "H8", "R8", "H_shared", "A_shared", "R_shared"])):
        L += ["", f"## {title}", ""]
        if not res:
            L.append("- **Unrun.**")
            continue
        arms_table(res, L, order)
        L.append("")
        contrast_table(res, L)
        if res is D:
            s = D["selection"]
            L += ["", f"- Selection: {s['rule']}; E(R): " + ", ".join(f"{k} {v:.5f}" for k, v in s["E_R_shared"].items())
                  + f"; eligible {s['eligible']}; gap {100 * s['rel_gap']:.1f}% → **{s['selected']}** (frozen {s['frozen_utc']})."]
    L += ["", "## Same-state traces (selected candidate, 8 dev seeds, along Q4)", ""]
    if TR:
        L += ["| lag | cos(d_t, d_a) | ‖d_t‖/‖d_a‖ median | Σ‖d_t−d_a‖²/Σ‖d_t‖² | shuffled | Σ‖e_t−d_a‖²/Σ‖e_t‖² |", "|---:|---:|---:|---:|---:|---:|"]
        for lg, r in TR["lags"].items():
            L.append(f"| {lg} | {r['cos_mean']:.3f} | {r['norm_ratio_median']:.3f} | {r['ratio_d']['v']:.3f} | {r['shuffled_ratio_d']['v']:.3f} | "
                     f"{r['corrected_fp_err_ratio']['v']:.3f} [{r['corrected_fp_err_ratio']['ci'][0]:.3f}, {r['corrected_fp_err_ratio']['ci'][1]:.3f}] |")
        L.append(f"- {TR['note']}; trace trajectory equals Q4: {TR['trace_trajectory_equals_Q4']}.")
    else:
        L.append("- Not run.")
    L += ["", "## Runtime (not measured)",
          "- No simulated timings were recorded (all models are fp32-dequantized, so simulation time says nothing about packed cost).",
          "- K = 4 cost condition: 50·C_Q4 + 13·C_high + overhead < 50·C_high. For A the high layer is Q4 + D̂ (two 4-bit products or reconstruction), so C_high ≥ C_Q4-class work twice;",
          "  shared storage does not relax this condition. Any future speed claim must also beat H_shared-50 and H8-50 at matched latency (both are in the tables above).", ""]
    open(os.path.join(OUT, "REPORT.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
