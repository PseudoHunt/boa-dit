"""results/temporal/spatial/REPORT.md from spatial/diag.json. Run: python scripts/make_spatial.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from boa_dit.common import atomic_write_text
from boa_dit.temporal.common import OUT
from boa_dit.temporal.c3 import spent
D = os.path.join(OUT, "spatial")
r = json.load(open(os.path.join(D, "diag.json")))
L = ["# Spatial structure of W4A4 activation rounding error, PixArt-Σ (consolidated §1; generated by `scripts/make_spatial.py`, "
     "pre-registration `rule_spatial.md`)", "",
     f"Compute: this job {r['gpu_hours']:.2f} A30-h; consolidated allocation spent so far {spent():.2f} of 3.0 (stage `c3`, both branches).",
     f"Base `{r['base']}` (dynamic per-token A4, groups of 64), design prompts {r['prompts'][0]}–{r['prompts'][-1]}, steps {r['steps'][0]}–{r['steps'][-1]} (even), "
     "64×64 token grid; A8 dynamic computed on the same inputs as a reference.", ""]
for bits in ("A4", "A8"):
    a = r[bits]
    L += [f"## {bits}", "", "| layer type | share of output-space error | adjacent corr h / v (centred) | uncentred h | x̃ corr h (context) | same-cell h / v | bands 1–4 | DC share |",
          "| --- | ---: | ---: | ---: | ---: | ---: | --- | ---: |"]
    for k in a["order"]:
        t = a["types"][k]
        L.append(f"| {k} | {t['share']:.3f} | {t['corr_h']:.3f} / {t['corr_v']:.3f} | {t['corr_h_uncentred']:.3f} | {t['x_corr_h']:.3f} | "
                 f"{t['same_cell_h']:.3f} / {t['same_cell_v']:.3f} | {' / '.join(f'{b:.3f}' for b in t['bands'])} | {t['dc_share']:.4f} |")
    L += ["", f"Half-error set: {', '.join(a['half_set'])}; minimum centred correlation in it {a['a_min_corr_in_half_set']:.3f}; "
          f"error-share-weighted band-1 fraction {a['b_weighted_band1']:.3f} (white = 0.25).", ""]
s = r["read_S"]
L += ["## Read S (pre-registered, on A4)",
      f"- (a) correlation ≥ 0.3 in the half-error set: **{s['a']}**; (b) ≥ 40% of energy in band 1: **{s['b']}**.",
      f"- **Read S: {'PASS' if s['pass'] else 'FAIL'}.** " + ("" if s["pass"] else "As pre-registered, §4 (error diffusion, blue-noise masks) was **not run** in that allocation. "
      "**Correction (2026-10-28):** a white baseline error spectrum is not a valid impossibility gate for noise shaping. Shaping creates spatial "
      "structure rather than exploiting existing structure; what matters is downstream sensitivity by spatial frequency, which this diagnostic "
      "did not measure. Spatial shaping is untested, not ruled out."), "",
      "## Reading",
      "- The activations themselves are spatially correlated (x̃ adjacent correlation 0.27–0.70), but their A4 rounding error is essentially white: neighbouring "
      "tokens fall in the same grid cell only ≈ 27–48% of the time in the error-carrying types, and each token has its own dynamic scale, so the rounding "
      "residuals decorrelate. The exception, attn2.to_out (same-cell 0.81, correlation 0.25, band-1 0.48), carries a negligible share of the error.",
      "- At A8 the error is white to three digits, as expected for fine grids.",
      "- One cross-attention site type, attn2.to_q, carries ≈ 72% of the output-space activation error at both precisions. This is a side observation, not "
      "acted on (nothing new is authorized)."]
atomic_write_text(os.path.join(D, "REPORT.md"), "\n".join(L) + "\n")
print("\n".join(L[-8:]))
