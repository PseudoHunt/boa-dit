"""results/attn_share/compute.md from compute.json, convpath.json and kernel_support.json."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boa_dit.common import atomic_write_text  # noqa: E402

OUT = os.path.join(ROOT, "results", "attn_share")


def load(n):
    p = os.path.join(OUT, n)
    return json.load(open(p)) if os.path.exists(p) else None


def main():
    c, cv, ks = load("compute.json"), load("convpath.json"), load("kernel_support.json")
    g2 = load("gate2_verdict.json") or {}
    kp = g2.get("k_pass")
    L = ["# Attention sharing — compute accounting\n",
         "Generated by `scripts/make_attn_compute.py` from `compute.json`, `convpath.json` and `kernel_support.json`. "
         "FLOPs = 2 × MACs, softmax counted as 5 ops/score, per image per CFG branch per forward. DiT-XL/2: C = 1152, "
         "16 heads, MLP ratio 4, 28 blocks. N = 256 / 1024 / 4096 tokens (256 px, 512 px, 1024 px at patch 2).\n",
         "## 1. FLOPs per block per image (GFLOP)\n"]
    Ns = list(c["per_N"])
    items = list(c["per_N"][Ns[0]]["block_flops"])
    L.append("| op | " + " | ".join(f"N = {n}" for n in Ns) + " |")
    L.append("| --- |" + " ---: |" * len(Ns))
    for it in items:
        L.append(f"| {it} | " + " | ".join(f"{c['per_N'][n]['block_flops'][it] / 1e9:.3f}" for n in Ns) + " |")
    L.append("| **block total** | " + " | ".join(f"**{c['per_N'][n]['block_total'] / 1e9:.2f}**" for n in Ns) + " |")
    L.append("| model total (28 blocks + embed/final) | " +
             " | ".join(f"{c['per_N'][n]['model_total_per_branch'] / 1e9:.1f}" for n in Ns) + " |\n")
    L.append("## 2–3. Fraction removed at a shared step, and end to end\n")
    L.append("Removed at a shared step: Q and K projections, QKᵀ, softmax. V1/V2 keep a dense AV; V4 does AV over 32 "
             "entries per row; V3 replaces AV with a direct 31×31 depthwise convolution (2 · 961 · N · C FLOPs). At "
             "N = 256 that convolution costs more than dense AV (961 > 256 taps), so V3 removes less than V1. End to end "
             "= (k / 50) × 28 × removed / model total; both CFG branches share equally, so the fraction is the same with "
             "or without CFG.\n")
    ks_ = list(next(iter(c["per_N"][Ns[0]]["variants"].values()))["end_to_end_frac_saved"])
    L.append("| variant | N | block FLOPs removed | " + " | ".join(f"end to end, k = {k}" for k in ks_) + " |")
    L.append("| --- | ---: | ---: |" + " ---: |" * len(ks_))
    for v in c["per_N"][Ns[0]]["variants"]:
        for n in Ns:
            e = c["per_N"][n]["variants"][v]
            L.append(f"| {v} | {n} | {100 * e['block_frac_removed']:.1f}% | " +
                     " | ".join(f"{100 * e['end_to_end_frac_saved'][k]:.1f}%" for k in ks_) + " |")
    L.append(f"\nPlainly: at N = 256 the saving is small (a few percent end to end even at k = {kp or '20'}), because "
             "the MLP and projections dominate a block. It grows with N because QKᵀ and softmax grow as N². "
             "Dense stored maps grow as N² too (V1 at N = 4096 is 16 · 4096² · 2 B = 537 MB per block, branch and step), "
             "so at high N only a compact form such as V3 is usable. Caveat on the V3 rows at N = 1024 / 4096: they assume "
             "a 31×31 kernel still suffices on a 32×32 / 64×64 grid. Section 6 finds the kernel uses its full support at "
             "16×16; if that scales with the grid, a 64×64 grid needs up to 127×127 taps (2 · 16129 · N · C FLOPs), "
             "which is more than dense AV at N = 4096 (2 · N² · C, i.e. 4096 taps). The V3 compute saving at high N "
             "therefore depends on an untested property: a bounded kernel support.\n")
    m = c.get("measured")
    L.append("## 4. Measured latency, whole model (A30, N = 256)\n")
    if m:
        L.append(f"{m['batch']}; {m['iters']} timed iterations, median.\n")
        L.append("| path | median ms / forward | min ms |")
        L.append("| --- | ---: | ---: |")
        t = m["timings"]
        for k, v in t.items():
            L.append(f"| {k} | {v['median_ms']:.1f} | {v['min_ms']:.1f} |")
        base, sh = t["baseline (fused SDPA)"]["median_ms"], t["shared map, V-only projection"]["median_ms"]
        fl = c["per_N"]["256"]["variants"]["V1/V2 dense stored map"]["block_frac_removed"]
        L.append(f"\nRealized saving per shared forward: {100 * (1 - sh / base):+.1f}% (FLOPs estimate for a fully shared "
                 f"forward: {100 * fl:.1f}%). The gap is plain PyTorch: the stored map is materialized and applied with "
                 "an unfused batched matmul, while the baseline uses fused SDPA.\n")
    else:
        L.append("Pending.\n")
    L.append("## 5. Per-block attention sublayer: full attention vs V1 (dense map) vs V3 (convolution)\n")
    if cv:
        vf = cv["verify"]
        L.append(f"Conv path check: V3 as a depthwise 2-D convolution on the token grid (kernel κ, row-normalized by "
                 f"conv(1, κ)) vs the dense V3 map: max relative difference {vf['max_rel_fp32']:.1e} in fp32 "
                 f"(tolerance {vf['tolerance']:g}); {vf['max_rel_fp16_last_block']:.1e} when the conv runs in fp16 "
                 f"(fp16 rounding against an fp32 reference). Blocks {vf['blocks_checked']}, window {vf['kernel_window']}.\n")
        b = cv["bench"]
        L.append(f"Synthetic inputs, random weights, {b['dtype']}, batch {b['batch_rows']} rows; ms for the whole batch "
                 "(projections included in the sublayer timing). GFLOPs per row.\n")
        L.append("| N | path | GFLOP / row | ms / block (sublayer) | ms core only |")
        L.append("| ---: | --- | ---: | ---: | ---: |")
        for n, r in b["per_N"].items():
            core = dict(zip(r["ms_block_attention_sublayer"], r["ms_core_only"].values()))
            for (path, ms), gf in zip(r["ms_block_attention_sublayer"].items(), r["gflops_per_row_attention_sublayer"].values()):
                L.append(f"| {n} | {path} | {gf:.2f} | {ms:.2f} | {core[path]:.2f} |")
        L.append("")
    else:
        L.append("Pending.\n")
    L.append("## 6. Effective support of the V3 kernel\n")
    if ks:
        for br, d in ks["per_branch"].items():
            e = d["excess_over_floor"]
            L.append(f"- {br}: side of the smallest centered square holding 95% of κ's mass, over (window, block, head) "
                     f"at k = {ks['k']}: median {d['median_side']:.0f}; full support (31) in {100 * d['frac_full_31']:.1f}%; "
                     f"≤ 15 in {100 * d['frac_side_le_15']:.1f}%; histogram {d['side_histogram']}. Secondary "
                     f"(floor = 10th percentile of κ, removed): the floor holds a median {100 * e['median_floor_mass_share']:.0f}% "
                     f"of the mass and the excess still has median side {e['median_side']:.0f}.")
        L.append("\nReading: the kernel is not compact. Early attention is a broad, near-uniform floor plus a weak "
                 "local peak, and both spread over the whole 16×16 grid, so a 31×31 convolution needs its full "
                 "support. The convolution path is therefore not cheap at this resolution. Whether the support stays "
                 "bounded at larger grids (which would make it cheap relative to N²) is untested.\n")
    atomic_write_text(os.path.join(OUT, "compute.md"), "\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
