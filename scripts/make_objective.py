"""Objective diagnostics (DiT-XL/2): results/objective/REPORT.md from the JSONs (pre-registration rule.md)."""
import csv
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from boa_dit.common import atomic_write_text  # noqa: E402
from make_gateA import paired  # noqa: E402

O = os.path.join(ROOT, "results", "objective")
RES = os.path.join(ROOT, "results")
LIN = ["attn.qkv", "attn.proj", "mlp.fc1", "mlp.fc2"]
STEPS = list(range(0, 50, 5))


def load(*p):
    p = os.path.join(*p)
    return json.load(open(p)) if os.path.exists(p) else None


def fmt(r):
    return f"{100 * r[0]:+.1f}% [{100 * r[1]:+.1f}, {100 * r[2]:+.1f}]"


def main():
    L = ["# Objective diagnostics, DiT-XL/2 256 — report (generated by `scripts/make_objective.py`; pre-registration `rule.md`)\n",
         "Base model for every residual and arm: heig-8 (`deflate_heig_r8_w4`). Sampler as the stored latent eval: DDIM-50, eta 0, "
         "cfg w = 1.5 (CFG on the first 3 eps channels), fp16 autocast, batch 32, eval seeds 0–511. Calibration seeds 1000–1031.\n"]
    # D4
    d4 = load(O, "proxy", "d4.json")
    L.append("## D4 — is the step-error proxy a valid screen?")
    if d4:
        L.append(f"Proxy = rel. MSE of the guided prediction vs FP on the FP trajectory (eval seeds 0–63 × steps 0, 5, …, 45). "
                 f"FP through the same harness: {d4['fp_floor']:.1e} (bit-exact).\n")
        L.append("| arm | proxy | stored latent rel. MSE (seeds 0–511) |")
        L.append("| --- | ---: | ---: |")
        for n, v in sorted(d4["arms"].items(), key=lambda kv: kv[1]["latent_rel_mse"] or 9):
            L.append(f"| {n} | {v['proxy']:.5f} | {v['latent_rel_mse']:.5f} |" if v["latent_rel_mse"] else f"| {n} | {v['proxy']:.5f} | — |")
        sp = d4.get("spearman_all", d4["spearman"])
        n = d4.get("n_arms_all", d4["n_arms"])
        L.append(f"\nSpearman **{sp:.3f}** over {n} arms (Pearson {d4.get('pearson_all', d4['pearson']):.3f}); the 17 stored arms alone: "
                 f"{d4['spearman']:.3f}.")
        verdict = "VALID" if sp >= 0.9 else ("NOT VALID, and below 0.8: the PixArt-Σ screen must switch to latent MSE" if sp < 0.8 else
                                              "NOT VALID (between 0.8 and 0.9: no forced switch)")
        L.append(f"\n**Read 3: {verdict}.** It orders the coarse groups right (carry arms vs uniform-base arms) but misranks arms "
                 "within a few percent of each other (static-8 vs dc-8; E3/E4/E5 tie on the proxy while their latent MSEs span "
                 "0.079–0.088). A PixArt-Σ screen decision close to its 5% threshold should be confirmed on latent or image error.\n")
    # D1
    d1 = load(O, "d1.json")
    L.append("## D1 — guidance (CFG)")
    L.append("Toy check: x_c = (1, 1), x_u = (1, 0), w = 4 → v = (1, 4); error on the channel where the branches differ counts 16× "
             "in ‖E v‖², against about 1× in the per-branch sum.\n")
    if d1:
        net = d1["network"]
        L.append(f"**Layer level** (heig-8 effective residual E_eff = (W − W_q)(I − VVᵀ), its own calibration state). Model-level "
                 f"r_cfg = Σ tr(E H_cfg Eᵀ)/Σ tr(E H_cur Eᵀ) = **{d1['model_r_cfg']:.2f}**.\n")
        L.append("| layer type | mean r_cfg | mean (diff + cross) share | share of total CFG-weighted error |")
        L.append("| --- | ---: | ---: | ---: |")
        for ln, v in d1["by_type"].items():
            L.append(f"| {ln} | {v['r_cfg']:.2f} | {v['diffcross_share']:.2f} | {v['share_of_cfg_error']:.2f} |")
        L.append(f"\nLayers with (diff + cross) share ≥ 30%: {len(d1['layers_diffcross_ge_30pct'])} of 112; together they hold "
                 f"**{100 * d1['their_share_of_cfg_error']:.1f}%** of Σ tr(E H_cfg Eᵀ) → layer part "
                 f"{'passes' if d1['read1_layer_part'] else 'fails'} (needs ≥ 50%).\n")
        L.append("Per bucket, blocks 2, 10, 27 (r_cfg by bucket 0–9):\n")
        L.append("| layer | " + " | ".join(f"b{b}" for b in range(10)) + " |")
        L.append("| --- | " + " | ".join("---:" for _ in range(10)) + " |")
        for l in (2, 10, 27):
            for ln in LIN:
                bk = d1["layers"][f"b{l}.{ln}"]["buckets"]
                L.append(f"| b{l}.{ln} | " + " | ".join(f"{x['cfg'] / x['cur']:.2f}" for x in bk) + " |")
        L.append(f"\n**Network level** (eval seeds 0–31 × 10 steps, 3 guided channels): ‖δ_g‖²/mean(‖δ_c‖², ‖δ_u‖²) = "
                 f"**{net['ratio_g_over_mean_branch']:.2f}** (needs ≥ 2); against the H_cur-weighted branch energy "
                 f"{net['ratio_g_over_cur_weighted']:.2f}, which the layer-level aggregate r_cfg = {d1['model_r_cfg']:.2f} is meant to "
                 f"predict. corr(δ_c, δ_u) = {net['corr_cu_mean']:.2f}. Split of ‖δ_g‖²: shared {100 * net['split_share']['shared']:+.0f}%, "
                 f"difference {100 * net['split_share']['diff']:+.0f}%, cross {100 * net['split_share']['cross']:+.0f}%: the branch errors are "
                 "correlated and the cross term cancels much of the difference term.\n")
        L.append("| step | " + " | ".join(str(s) for s in STEPS) + " |")
        L.append("| --- | " + " | ".join("---:" for _ in STEPS) + " |")
        L.append("| ‖δ_g‖²/mean branch | " + " | ".join(f"{x:.2f}" for x in net["ratio_by_step"]) + " |")
        L.append(f"\n**Read 1, guidance is a lever: {'HOLDS' if d1['read1_lever'] else 'FAILS'}** (layer part "
                 f"{d1['read1_layer_part']}, network part {d1['read1_network_part']}).\n")
    # D2
    d2 = load(O, "d2.json")
    L.append("## D2 — sampler frequency response")
    if d2:
        L.append(f"FP sampler, eval seeds 0–31, error injected into the guided prediction at one step with heig-8's measured energy; "
                 f"4 equal-area radial bands of the 32×32 DFT (band 1 lowest). The unperturbed continuation is bit-exact: "
                 f"{d2['continuation_bitexact']}.\n")
        L.append("| step | G band 1 | band 2 | band 3 | band 4 | white | Jacobian-free | b1/b4 [95% CI] | S band 1 | S 2 | S 3 | S 4 | harm 1 | 2 | 3 | 4 |")
        L.append("| ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
        for t in STEPS:
            g = d2["G"][str(t)]
            r = d2["ratio_b1_b4"][str(t)]
            L.append(f"| {t} | " + " | ".join(f"{np.mean(g[f'band{b}']):.3g}" for b in range(1, 5)) + f" | {np.mean(g['white']):.3g} | "
                     f"{d2['jacobian_free_G'][str(t)]:.3g} | {r[0]:.2f} [{r[1]:.2f}, {r[2]:.2f}] | " +
                     " | ".join(f"{x:.2f}" for x in d2["S"][str(t)]) + " | " + " | ".join(f"{x:.2f}" for x in d2["harm"][str(t)]) + " |")
        L.append(f"\n**Read 2, the sampler is directional: {'HOLDS' if d2['read2_directional'] else 'FAILS'}** "
                 f"({d2['read2_directional_steps']} of the first five steps qualify; needs ≥ 2). Early and mid steps amplify low-frequency "
                 "error 5–20× more than high-frequency error. By steps 40–45 the gain is flat across bands, as the Jacobian-free view "
                 "predicts. heig-8's own error moves into band 1 mid-trajectory (S band 1 = 0.53–0.73 at steps 15–25), where G is "
                 "largest.\n")
    hk = load(O, "hk_sigma.json")
    if hk:
        L.append(f"**H_K's σ = {hk['sigma_tokens']:.3f} tokens.** Weighted least-squares fit of the token blur's |B(f)|² to "
                 f"Ĝ = mean over steps 0–20 of G/G(band 1) = {[round(x, 3) for x in hk['G_hat_norm_band1_steps0_20']]}. "
                 f"**Limitation:** the 16×16 token grid represents {[round(x, 2) for x in hk['band_weight_representable']]} of bands 1–4 "
                 "(Nyquist 0.25 cycles/latent px). Bands 3–4, and most of band 2, are within-patch frequencies carried by the channel "
                 "dimension, which a token-grid blur cannot shape. So H_K can only re-weight error inside band 1: a weak test of the "
                 "band 1 vs band 4 contrast that passed read 2.\n")
    # D3
    se = load(RES, "engine", "sensitivity.json")
    if se:
        L.append("## D3 — suffix sensitivity ρ (round-2 §2, not re-run)")
        L.append("Bucket-mean ρ for blocks 2 / 10 / 20 / 27: " + " / ".join(f"{se['blocks'][b]['bucket_mean']['rho']:.3f}" for b in ("2", "10", "20", "27")) +
                 f"; spread ≥ 10 everywhere. **Gate: {'PASS' if se['read2a_pass'] else 'FAIL'}** ({se['read2a_blocks_passing']}/4).\n")
    # arms
    L.append("## Arms (one-sided, heig-8 otherwise; latent rel. MSE on seeds 0–511, paired bootstrap CI vs heig-8)")
    heig = load(RES, "gate1", "eval", "latent_deflate_heig_r8_w4.json")
    L.append("| arm | what | rel. latent MSE | vs heig-8 | earns a place (≥ 5%, CI > 0) |")
    L.append("| --- | --- | ---: | --- | --- |")
    L.append(f"| heig-8 | base | {heig['rel_mse_mean']:.5f} | — | — |")
    arms = [("CFG-solve", "deflate_heig_r8_w4_cfgsolve", "H_cfg in the solve, subspace from H_cur"),
            ("CFG-full", "deflate_heig_r8_w4_cfgfull", "H_cfg in the solve and the top-8 subspace"),
            ("H_K", "deflate_heig_r8_w4_hk", "token-blurred Gram (σ above) in the solve and the subspace")]
    got = {}
    for lab, name, what in arms:
        js = load(O, "eval", f"latent_{name}.json")
        if not js:
            L.append(f"| {lab} | {what} | pending | pending | — |")
            continue
        r = paired(js, heig)
        got[lab] = r
        L.append(f"| {lab} | {what} | {js['rel_mse_mean']:.5f} | {fmt(r)} | {'YES' if r[0] >= 0.05 and r[1] > 0 else 'no'} |")
    for path, labs in (("per_block.json", ("deflate_heig_r8_w4", "deflate_heig_r8_w4_cfgsolve", "deflate_heig_r8_w4_cfgfull")),
                       ("per_block_hk.json", ("deflate_heig_r8_w4_hk",))):
        pb = load(O, path)
        if not pb:
            continue
        have = [k for k in labs if isinstance(pb.get(k), dict)]
        L.append(f"\nPer-block output error (`{path}`; block l on the arm's own prefix, held-out seeds 1032–1047, all four linears as in the arm):\n")
        L.append("| block | " + " | ".join(have) + " |")
        L.append("| ---: | " + " | ".join("---:" for _ in have) + " |")
        for l in range(28):
            L.append(f"| {l} | " + " | ".join(f"{pb[k]['blocks'][l]['b_as_arm']['mse']:.4g}" for k in have) + " |")
    L.append("\n## Reads")
    if d1:
        cfg_place = any(got.get(k) and got[k][0] >= 0.05 and got[k][1] > 0 for k in ("CFG-solve", "CFG-full"))
        L.append(f"1. Guidance lever: {'HOLDS' if d1['read1_lever'] else 'FAILS'}. CFG loss earns a place: "
                 f"{'YES' if cfg_place else ('NO' if all(k in got for k in ('CFG-solve', 'CFG-full')) else 'pending')}.")
    if d2:
        hkp = got.get("H_K")
        L.append(f"2. Sampler directional: {'HOLDS' if d2['read2_directional'] else 'FAILS'}. H_K earns a place: "
                 f"{('YES' if hkp[0] >= 0.05 and hkp[1] > 0 else 'NO') if hkp else 'pending'}.")
    if d4:
        L.append(f"3. Proxy valid: {'YES' if d4.get('spearman_all', d4['spearman']) >= 0.9 else 'NO'}.")
    L.append("4. A loss that passes read 1 or 2 AND earns a place is the first H_col replacement on the PixArt-Σ H-SVDQuant base. If "
             "none earns a place (and ρ fails, as it does), the latent error here is not steerable by a per-layer objective at W4, "
             "and the engine line closes.")
    arm_quant = ("quant_deflate_heig_r8_w4_cfgsolve", "quant_deflate_heig_r8_w4_cfgfull", "quant_deflate_heig_r8_w4_hk")
    tot = sum(float(r[5]) for r in csv.reader(open(os.path.join(RES, "gpu_hours.csv")))
              if len(r) >= 6 and (r[0] == "objective" or (r[0] == "deflate" and r[1].startswith(arm_quant))))
    L.append(f"\n## Compute\nA30-hours, stage `objective` plus the three arm quantizations (logged under `deflate`): **{tot:.2f}** of 2.\n")
    L.append("## Deviations\n- D1's diagnostic Grams use TF32 GEMM inputs (fp32 storage and accumulation). The arms' Grams are "
             "exactly the pipeline's (fp32).\n- H_K: the σ fit and its token-grid limitation are above.")
    atomic_write_text(os.path.join(O, "REPORT.md"), "\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
