    for fam, ff in R["fits"].items():
        L.append(f"- {fam} fits: " + "; ".join(f"γ {g[6:]}: a {np.round(v['a'], 4).tolist()} (pred {v['predicted_objective']:.4f} vs base {v['baseline_objective']:.4f})"
                                             for g, v in ff.items() if g.startswith("gamma_")))
    if S:
        L += ["", f"Development (seeds {S['dev_seeds'][0]}–{S['dev_seeds'][1]}): base latent {S['dev_base_latent']:.5f}.", "",
              "| family | selected | a | dev latent | candidates (distinct models) | identity |", "| --- | --- | --- | ---: | --- | --- |"]
        for fam, s in S["selected"].items():
            if s:
                L.append(f"| {fam} | {s['name']} | {np.round(s['a'], 4).tolist()} | {s['dev_latent']:.5f} | {s['n_candidates']} ({s['n_distinct_models']}) | {s['identity']} |")
            else:
                L.append(f"| {fam} | not run | | | | |")
        for fam, v in S["fit_actual_vs_predicted"].items():
            L.append(f"- fit check {fam}: actual change {v['actual_fit_change']:+.5f} vs predicted " + ", ".join(f"{k} {p:+.5f}" for k, p in v["predicted_change"].items()))
