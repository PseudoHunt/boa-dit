def boot(a, b, ratio, n=2000):
    a, b = np.asarray(a), np.asarray(b)
    idx = np.random.default_rng(0).integers(0, len(a), (n, len(a)))
    d = (a[idx].mean(1) / b[idx].mean(1) - 1) if ratio else (a[idx] - b[idx]).mean(1)
    v = (a.mean() / b.mean() - 1) if ratio else (a - b).mean()
    return {"v": float(v), "ci": [float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))], "median": float(np.median(a - b)),
            "wins": int((a < b).sum())}


pct = lambda v: f"{100 * v['v']:+.2f}% [{100 * v['ci'][0]:+.2f}, {100 * v['ci'][1]:+.2f}] (wins {v['wins']}/128)"
dif = lambda v: f"{v['v']:+.4f} [{v['ci'][0]:+.4f}, {v['ci'][1]:+.4f}]"
