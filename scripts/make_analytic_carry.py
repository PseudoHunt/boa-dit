    if not R:
        continue
    L += ["", f"## {title}", "", f"Fit baseline latent {R['fit_base_latent']:.5f}; repeat noise {R['repeat_noise_norm_4img']:.2e}; accepted h = {R['h']}."]
    for c in R["h_checks"]:
        L.append(f"- h check (fit h {c['h_fit']}, compared {c['compared_h']}): column rel. diff {np.round(c['col_rel_diff'], 3).tolist()}, usable {c['usable']}, "
                 f"mixed rel. error {c['mixed_rel_err']:.3f} → {'OK' if c['ok'] else 'FAILED'}")
    if "capacity" in R["endpoint"]:
        cp = R["endpoint"]["capacity"]
        L.append(f"- Endpoint response: singular values {np.round(cp['singular_values'], 4).tolist()}; span(R) explains {100 * cp['fraction_of_fit_sq_error_explained']:.2f}% of FIT squared error (linear, fit images).")
