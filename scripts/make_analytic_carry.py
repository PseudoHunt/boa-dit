    L += ["", "## 4b. E2 analytic solve (local fixed-feature surrogate)", "", "| group | fit E0 energy | fit after | fit rel. improvement (exported fp16) | dev rel. improvement (exported) | update output energy (fit) |",
          "| --- | ---: | ---: | --- | --- | ---: |"]
    for g, v in SO["groups"].items():
        L.append(f"| {g} | {v['fit']['E0_energy']:.4g} | {v['fit']['after']:.4g} | {100 * v['fit']['rel_improvement']:.2f}% ({100 * v['fit']['rel_improvement_exported']:.2f}%) | "
                 f"{100 * v['dev']['rel_improvement']:.2f}% ({100 * v['dev']['rel_improvement_exported']:.2f}%) | {v['fit']['update_output_energy']:.4g} |")
