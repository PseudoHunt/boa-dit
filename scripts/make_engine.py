"""Engine round 2: results/engine/REPORT.md from the JSONs (round closed early by the W4A4 redirect)."""
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boa_dit.common import atomic_write_text  # noqa: E402

E = os.path.join(ROOT, "results", "engine")


def load(*p):
    p = os.path.join(E, *p)
    return json.load(open(p)) if os.path.exists(p) else None


def main():
    L = ["# Engine round 2 — report (generated by `scripts/make_engine.py`; pre-registration `rule.md`)\n",
         "**Closed early.** The W4A4 redirect (prior art arXiv 2610.11315; `results/w4a4/prior_art.md`) stopped this round "
         "after §1 and §2. Sections 3–8 did not run any arm. Section 0 was done: the H4dsf FID-5k was stopped, its "
         "partial GPU time was logged by hand, Gate 1 was committed (`d7246ac`), and the heartbeat was restarted.\n"]
    bl = load("attribution", "blocks.json")
    L.append("## §1 Attribution on heig-8 (seeds 0–63)")
    if bl:
        a = bl["arms"]
        L.append(f"Base rerun: rel. latent MSE {a['base']['rel_mse_mean']:.5f}; max abs per-image difference vs the "
                 f"stored heig-8 values {a['base']['integrity_max_abs_diff_vs_stored']:.1e}.\n")
        sh = {int(k[5:]): v["share"] for k, v in a.items() if k.startswith("block")}
        top = sorted(sh, key=lambda l: -sh[l])[:3]
        pos = np.clip(np.array([sh[l] for l in range(28)]), 0, None)
        x = np.sort(pos)
        n = len(x)
        gini = 2 * np.sum(np.arange(1, n + 1) * x) / (n * x.sum()) - (n + 1) / n
        top3 = sum(sh[l] for l in top)
        L.append("| block | share of heig-8 error removed by restoring the block to FP |")
        L.append("| ---: | ---: |")
        for l in range(28):
            L.append(f"| {l} | {100 * sh[l]:+.1f}% |")
        L.append(f"\nTop 3 blocks: {top} with shares {', '.join(f'{100 * sh[l]:.1f}%' for l in top)}. Their sum is "
                 f"**{100 * top3:.1f}%**; normalized by the sum of positive shares it is {100 * top3 / pos.sum():.1f}%. "
                 f"The sum of positive shares is {100 * pos.sum():.1f}%, and the Gini coefficient is {gini:.2f}.")
        L.append(f"\n**Read 1 (concentrated iff top3 ≥ 40%): {'HOLDS' if top3 >= 0.40 else 'FAILS'}.** The remaining error is "
                 f"{'concentrated' if top3 >= 0.40 else 'spread across blocks (bits-limited, not a single target)'}.\n")
    ly = load("attribution", "layers.json")
    if ly:
        L.append("| layer (top-3 blocks) | share removed |")
        L.append("| --- | ---: |")
        for k, v in ly["arms"].items():
            L.append(f"| {k} | {100 * v['share']:+.1f}% |")
        L.append("")
    se = load("sensitivity.json")
    L.append("## §2 Network sensitivity F_l and the leverage ρ")
    if se:
        L.append("| block | step | λmax/λmedian | ρ | err energy in F's top-32 | in bottom-32 (isotropic 0.028) |")
        L.append("| ---: | --- | ---: | ---: | ---: | ---: |")
        for b, d in se["blocks"].items():
            for k, m in d.items():
                L.append(f"| {b} | {k} | {m['lmax_over_lmedian']:.3g} | {m['rho']:.3f} | {m['err_top32']:.3f} | {m['err_bottom32']:.3f} |")
        L.append(f"\n**Read 2a (ρ ≥ 1 and spread ≥ 10 in ≥ 2 of 4 blocks, bucket mean): "
                 f"{'PASS' if se['read2a_pass'] else 'FAIL'}** ({se['read2a_blocks_passing']} of 4). The leverage is above 1 "
                 "only in block 2. Elsewhere, GPTQ-plus-carry already leaves its block error in directions the output barely "
                 "responds to (ρ ≈ 0.02–0.2). §5 (A′) would have been skipped.\n")
    L.append("## Deviations and findings recorded before the round was stopped")
    al = load("alloc.json")
    if al:
        L.append(f"- **§3 heig-alloc is degenerate on this model.** r90 ranges over {min(al['r90'].values())}–"
                 f"{max(al['r90'].values())}, so the cap that meets 0.148 bits is {al['cap']}, and it binds in all 112 layers: "
                 "heig-alloc equals heig-8. The rank-8 share of a layer's Hessian-weighted error has a median of 2%; it is "
                 "51% in block 2 qkv. A greedy share-per-bit fallback was computed (`alloc_greedy.json`) and rejected "
                 "before running: shares are scale-free, so it spent most bits on attn.proj (cheap, low importance). An "
                 "importance-weighted version was planned. No §3 arm ran.")
    L.append("- **§4 asymmetric target, literal form is broken.** At block 0, where x̃ = x and so C = H exactly, "
             "W·C·(H + 0.01·mean diag·I)⁻¹ moved W by 40% (‖W̃ − W‖/‖W‖ = 0.40). The damping is large next to most of "
             "H's eigenvalues, because a few massive channels dominate the mean diagonal. The correction form "
             "W̃ = W + W(C − H)(H + damp)⁻¹ reduces to W exactly when C = H; on blocks 0–1 its drift matches heig-8's. "
             "Only a 2-block smoke test ran; its artifacts were deleted. No §4 arm ran.")
    L.append("- §5–§8 did not start.")
    atomic_write_text(os.path.join(E, "REPORT.md"), "\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
