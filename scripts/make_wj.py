"""results/temporal/weights_joint/REPORT.md from the JSONs (PROTOCOL.md). Run: python scripts/make_wj.py"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import numpy as np  # noqa: E402

from boa_dit.common import atomic_write_text  # noqa: E402
from boa_dit.weights_joint.common import CAP_H, OUT, boot_reduction, spent  # noqa: E402

J = lambda f: json.load(open(os.path.join(OUT, f))) if os.path.exists(os.path.join(OUT, f)) else None
pct = lambda r: f"{-100 * r['reduction']:+.1f}% [{-100 * r['ci'][1]:+.1f}, {-100 * r['ci'][0]:+.1f}]"
L = ["# Weight-space cancellation oracle and joint two-table GPTQ pilot: report (generated by `scripts/make_wj.py`; protocol "
     "`PROTOCOL.md`)", "", f"Pilot compute: {spent():.3f} of {CAP_H} A30-h (stage `weights_joint`). Everything here is an "
     "**exploratory** screen unless stated otherwise.", ""]
v = J("validation_synthetic.json")
if v:
    L += ["## Validation (synthetic, CPU)", "", "All checks " + ("**pass**" if v["all_pass"] else "**FAIL**") + ": "
          + ", ".join(f"{k} {'✓' if x else '✗'}" for k, x in v["checks"].items()) + ".", ""]
o = J("oracle.json")
if o:
    ss, lv = o["same_state"]["overall"], o["live"]
    L += ["## Part 0: weight-space cancellation oracle (seeds 4000–4015, fp32, unquantized W_minus = 2W − W_plus)", "",
          f"Source: {o['source']}. Stage 1 is a **weight-induced prediction-error replay** (not an activation experiment). Weight "
          f"symmetry as stored: discrepancy {o['symmetry']['symmetry_discrepancy_rel']:.2e} (rel.).", "",
          "**Same-state** (fp32 FP trajectory, all 50 steps, guided 4 eps channels):", "",
          f"- energy of e_plus {ss['energy_plus']:.4g}, of e_minus {ss['energy_minus']:.4g}; mean cosine(e_plus, e_minus) over steps "
          f"{ss['cos_mean_over_steps']:+.3f}",
          f"- energy of the mean (e_plus + e_minus)/2: {ss['energy_mean']:.4g} = **{100 * ss['mean_over_individual']:.1f}%** of the mean "
          "individual energy (0% would be perfect opposition, 100% no cancellation)", "",
          "**Live trajectories** (endpoint latent rel. MSE vs the fp32 FP endpoint; paired bootstrap):", "",
          "| arm | rel. MSE | vs static W_plus | vs static W_minus |", "| --- | ---: | --- | --- |"]
    for k in ("static_plus", "static_minus", "alt_plus_minus", "alt_minus_plus"):
        x = lv[k]
        L.append(f"| {k} | {x['rel_mse_mean']:.5f} | {pct(x['vs_static_plus']) if 'vs_static_plus' in x else '—'} | "
                 f"{pct(x['vs_static_minus']) if 'vs_static_minus' in x else '—'} |")
    L += ["", f"Alternating/static-plus endpoint error ratio (absolute): {lv['ratio_alt_pm_over_static_plus_abs_err']:.3f}; Stage-1 "
          f"reference (prediction-error sign flip, different settings): {o['stage1_reference']['ratio']:.4f}.", ""]
a = J("audit.json")
if a:
    g = a["aggregate_cost_weighted"]
    L += ["## Part 1: where GPTQ leaves reconstruction cost (incremental cost per input column, natural processing order)", "",
          f"Static GPTQ reproduces heig-8's W_q exactly on all layers: {a['all_layers_reproduce_heig8']}; telescoping vs the damped "
          f"quadratic: max rel. {a['telescoping_max_rel']:.1e}.", "",
          "| columns | share of total reconstruction cost (cost-weighted over 112 layers) |", "| --- | ---: |"]
    for k, lab in (("final1", "final column"), ("final16", "final 16"), ("final64", "final 64"), ("top16", "highest-cost 16"), ("top64", "highest-cost 64")):
        L.append(f"| {lab} | {100 * g[k]:.2f}% |")
    L += ["", "A diagnostic of headroom for the terminal-column hypothesis, not an endpoint predictor.", ""]
b = J("build.json")
if b:
    t = b["totals"]
    L += ["## Part 2: joint constructions (β = 0.1; damped PHP metric, summed over 112 layers)", "",
          f"Static heig-8 reconstruction: {t['static']['recon']:.5g}.", "",
          "| construction | recon Q_A | recon Q_B | shared ‖(E_A+E_B)/2‖² | alternating ‖(E_A−E_B)/2‖² | surrogate |", "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for c in ("B_final1", "C_final16", "D_top16", "E_rand16", "F_all"):
        x = t[c]
        L.append(f"| {c} | {x['recon_A']:.5g} | {x['recon_B']:.5g} | {x['shared']:.5g} | {x['alternating']:.5g} | {x['surrogate']:.5g} |")
    L.append("")
r = J("arms.json")
if r:
    A = r["arms"]
    L += ["## Parts 4–5: sampled arms (design seeds 4000–4031; exploratory 32-seed screen)", "",
          f"Identical tables alternated = static, bit for bit: {r.get('identical_tables_bitexact')}.", "",
          "| arm | latent rel. MSE | vs A [95% CI] | prediction C (abs.) | C/I | codes differing | bits/weight (packed) | sim. weight buffers | sampling s |",
          "| --- | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for k, x in A.items():
        s = x["storage"]
        L.append(f"| {k} | {x['rel_mse_mean']:.5f} | {pct(x['vs_A']) if 'vs_A' in x else '—'} | {x['diag']['C']:.4g} | {x['diag']['C_over_I']:.4f} | "
                 f"{100 * s.get('frac_codes_differ_pair', 0):.3f}% | {s['bits_per_weight']:.3f} | {s['runtime_buffer_bytes_simulation'] / 2**30:.2f} GiB | {x['sampling_s']:.1f} |")
    L += ["", "Bits/weight are computed packed sizes (4-bit codes + fp16 scale/zero per row + fp16 carries + selection metadata); the "
          "files actually written store uint8 codes (1 byte/weight/table). Entropy figures, where shown in arms.json, are "
          "estimates, not achieved compression. Weight buffers are the simulation's dequantized fp32 tables; alternate tables are "
          "not free. No packed INT4 kernel was built.", ""]
    q = {}
    pr = lambda x, y: boot_reduction(A[x]["rel_mse_per_seed"], A[y]["rel_mse_per_seed"]) if x in A and y in A else None
    sel = [k for k in ("B_final1", "C_final16", "D_top16", "E_rand16") if k in A]
    best = min(sel, key=lambda k: A[k]["rel_mse_mean"]) if sel else None
    L += ["## Interpretation (exploratory)", ""]
    if "indep" in A:
        jbest = min([k for k in sel + ["F_all"] if k in A], key=lambda k: A[k]["rel_mse_mean"]) if sel else None
        if jbest:
            L.append(f"- **Joint vs the existing independent pair:** best joint ({jbest}) vs indep: {pct(pr(jbest, 'indep'))}.")
    if "D_top16" in A and "E_rand16" in A:
        L.append(f"- **Selective (highest-cost 16) vs random 16:** {pct(pr('D_top16', 'E_rand16'))}.")
    if best:
        L.append(f"- Most promising selective pair: **{best}**.")
        for ctl in ("A", "B", "mean", "hp"):
            k = f"{best}:{ctl}"
            if k in A:
                L.append(f"  - alternating {best} vs {k}: {pct(pr(best, k))}")
            else:
                L.append(f"  - {k}: **unrun**")
    L.append("- A lower endpoint error alone does not show temporal shaping beats extra precision; see the :hp and :mean rows.")
atomic_write_text(os.path.join(OUT, "REPORT.md"), "\n".join(L) + "\n")
print("\n".join(L))
