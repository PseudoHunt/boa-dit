"""results/SUMMARY.md for the closed BoA-for-DiT project, from the result JSONs (no hand-typed numbers)."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import make_gateA as G  # noqa: E402
from boa_dit.common import atomic_write_text  # noqa: E402

RES = G.RES
ev = lambda n: json.load(open(os.path.join(RES, "stage2", "eval", f"latent_{n}.json")))
p = lambda r: f"{100 * r[0]:+.1f}% [{100 * r[1]:+.1f}, {100 * r[2]:+.1f}]"


def main():
    pooled = {b: ev(f"uniform_w{b}_K1_lam1_brequal") for b in (4, 3)}
    uni = {b: G.uniform(b) for b in (4, 3)}
    full = {b: ev(f"full_w{b}_K4_lam1_brcfg_gain_iso_rho0.003_fp32_gmedian") for b in (4, 3)}
    rtn = {b: ev(f"rtn_w{b}") for b in (4, 3)}
    fa = json.load(open(os.path.join(RES, "stage2", "fid_anchors.json")))["anchors"]
    ts = {b: G.paired(G.arm("time2-16", b), G.arm("static-32", b)) for b in (4, 3)}
    su = {b: G.paired(G.arm("static-32", b), uni[b]) for b in (4, 3)}
    ra = json.load(open(os.path.join(RES, "stage2", "row_attribution.json")))
    gd = {(s, b): G.paired(G.load(os.path.join(RES, "stage2", "eval", f"latent_guard_{s}_w{b}.json")), uni[b])
          for s in ("gate", "err") for b in (4, 3)}
    gpu = sum(float(l.split(",")[-1]) for l in open(os.path.join(RES, "gpu_hours.csv")).read().splitlines()[1:]
              if not l.startswith("attn_share"))
    top = ra["top3_blocks"][0]
    L = ["# BoA for DiT — summary (closed project)\n",
         "Generated by `scripts/make_summary_boa.py`. DiT-XL/2 256, DDIM-50, cfg 1.5, weight-only quantization of the 112 "
         "block linears (adaLN at W8; embedders, final layer, VAE in FP). Primary metric: matched-seed relative latent "
         "MSE vs FP on seeds 0–511; FID-2k as a sanity check. Full log in `REPORT.md`.\n",
         "## Main numbers (rel. latent MSE)\n",
         "| | RTN | pooled | uniform | full | uniform + static-32 correction |",
         "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for b in (4, 3):
        L.append(f"| W{b} | {rtn[b]['rel_mse_mean']:.4f} | {pooled[b]['rel_mse_mean']:.4f} | {uni[b]['rel_mse_mean']:.4f} | "
                 f"{full[b]['rel_mse_mean']:.4f} | {G.arm('static-32', b)['rel_mse_mean']:.4f} |")
    L.append(f"\nFID-2k anchors: FP {fa['FP']['fid2k']:.2f}, uniform W4 {fa['uniform W4']['fid2k']:.2f}, "
             f"uniform W3 {fa['uniform W3']['fid2k']:.2f}.\n")
    L.append("## Findings\n")
    L.append("Percentages are reductions in rel. latent MSE (positive = better, negative = worse), with paired bootstrap "
             "95% CIs over the 512 images.\n")
    L.append(f"- Reweighting calibration statistics by sampler gain and adaLN gate energy does not help. `full` vs "
             f"`uniform`: W4 {p(G.paired(full[4], uni[4]))}, W3 {p(G.paired(full[3], uni[3]))} (Gate 2 STOP). The "
             "pre-registered W4 diagnostic set (`gate2b.md`) found no arm ≥ 5% (STOP).")
    L.append(f"- Time-indexed low-rank residual correction loses to a static one at equal extra bits: time2-16 vs "
             f"static-32 W4 {p(ts[4])}, W3 {p(ts[3])} (Gate A STOP). The static correction itself is effective: "
             f"static-32 vs uniform W4 {p(su[4])}, W3 {p(su[3])}, for 0.593 extra bits/param (not FID-checked).")
    L.append(f"- Error concentrates in one place: swapping block {top} back to FP removes "
             f"{100 * ra['blocks'][str(top)]['contribution_share']:.0f}% of the W4 error, "
             f"{100 * ra['layers'][f'b{top}.attn.qkv']['contribution_share']:.0f}% from its `attn.qkv` alone.")
    L.append(f"- Keeping the top-100 rows at W8 RTN increases error (gate-ranked W4 {p(gd[('gate', 4)])}, error-ranked "
             f"W4 {p(gd[('err', 4)])}; W3 {p(gd[('gate', 3)])} / {p(gd[('err', 3)])}). **This is unexplained**: higher "
             "precision cannot raise a layer's own error. Suspects: inter-layer cancellation of quantization errors, or "
             "an interaction between the guard and BoA's sequential calibration (later blocks were calibrated on inputs "
             "from the un-guarded model). Not investigated further; no further runs on this project.")
    L.append("- Infrastructure: GPU peer-to-peer copies on the host were silently wrong. One eval was invalidated, "
             "quarantined (`stage2/eval_invalid/`) and rerun; all checkpoint loads now go through CPU and are verified.")
    L.append(f"\nGPU-hours (all BoA stages, from `gpu_hours.csv`): {gpu:.2f}.\n")
    atomic_write_text(os.path.join(RES, "SUMMARY.md"), "\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
