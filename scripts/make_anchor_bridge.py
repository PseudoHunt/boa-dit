"""Generate results/anchor_bridge/REPORT.md from the br1 JSON outputs (missing stages reported as unrun)."""
import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "results", "anchor_bridge")


def j(n):
    f = os.path.join(OUT, n)
    return json.load(open(f)) if os.path.exists(f) else None


def tables(res, L):
    L += ["| arm | cheap / FP calls | latent rel. MSE mean | median | PSNR (dB) | LPIPS |", "|---|---|---:|---:|---:|---:|"]
    for a, s in res["summary"].items():
        c = res["calls"][a]
        L.append(f"| {a} | {c['cheap']} / {c['fp']} | {s['rel_mse']['mean']:.5f} | {s['rel_mse']['median']:.5f} | {s['psnr']['mean']:.2f} | {s['lpips']['mean']:.4f} |")
    L += ["", "| contrast | mean-MSE ratio [95% CI] | mean diff [CI] | median diff | wins | ΔLPIPS [CI] | ΔPSNR [CI] |", "|---|---:|---:|---:|---:|---:|---:|"]
    for k, v in res["contrasts"].items():
        m, lp, ps = v["rel_mse"], v["lpips"], v["psnr"]
        L.append(f"| {k.replace('_vs_', ' / ')} | {m['ratio']:.3f} [{m['ratio_ci'][0]:.3f}, {m['ratio_ci'][1]:.3f}] | {m['diff']:+.5f} [{m['diff_ci'][0]:+.5f}, "
                 f"{m['diff_ci'][1]:+.5f}] | {m['median_diff']:+.5f} | {m['wins_x']}/{m['n']} | {lp['diff']:+.4f} [{lp['diff_ci'][0]:+.4f}, {lp['diff_ci'][1]:+.4f}] | "
                 f"{ps['diff']:+.2f} [{ps['diff_ci'][0]:+.2f}, {ps['diff_ci'][1]:+.2f}] |")


def main():
    ch, sc, dv, fr, cf = (j(n) for n in ("checks.json", "screen.json", "dev.json", "frozen.json", "conf.json"))
    rows = [r for r in csv.reader(open(os.path.join(ROOT, "results", "gpu_hours.csv"))) if r and r[0] == "br1"]
    tot = sum(float(r[-1]) for r in rows)
    L = ["# Retrospective anchor-bridge correction (br1): report", "",
         "Protocol `PROTOCOL.md` (pre-registered 2026-10-30, commit 41cecc8; amendments dated). Generated by `scripts/make_anchor_bridge.py`.",
         f"**GPU: {tot:.3f} of 0.5 A30-h** ({', '.join(f'{r[1]} {float(r[-1]):.4f}' for r in rows)}).",
         "aa1's C sampler (static A8 cheap model, FP anchors every 4 calls with reuse; activation feedback off). Fidelity to FP-50 (fake-quant simulation); no speed claim.", "",
         "IDs: C = anchors 0, 4, …, 48; C_last49 = anchors 0, …, 44, 49 (13); CB1 = bridge correction λ = 1 (zero extra calls); CBlam = bridge with the frozen",
         "global multiplier λ*; CB1_re = bridge λ = 1 then both models re-evaluated at the corrected state (diagnostic, 12 extra calls each).", ""]
    L += ["## Checks"]
    if ch:
        L += [f"- B1 DDIM coefficients vs ddim_sample rel. L2: {', '.join(f'step {k} {v:.1e}' for k, v in ch['B1_coeff_rel_l2'].items())}",
              f"- B2 sampler reproduces aa1 C bitwise {ch['B2_C_bitwise_aa1']}; λ = 0 = C bitwise {ch['B2_lambda0_bitwise_C']}; counts {ch['B2_counts']}",
              f"- B3 counts {ch['B3_counts']}; B4 synthetic (linear drift corrected exactly, random walk leaves +0.002) {ch['B4_synthetic']['pass']}",
              f"- **All checks pass: {ch['pass']}**"]
    else:
        L.append("- **Unrun.**")
    L += ["", "## S1 / S2: does the anchor jump predict the hold error? (16 dev images, C's own trajectory, 12 intervals)"]
    if sc:
        s1, s2 = sc["S1_cached"], sc["S2_replay"]
        L += ["", "| comparison | cosine | magnitude ratio | residual after subtraction |", "|---|---:|---:|---:|",
              f"| S1 bridge Ĥ vs coefficient-weighted hold residual H | {s1['cos_H_hhat']:.3f} | ‖Ĥ‖/‖H‖ {s1['norm_hhat_over_H']:.3f} | {s1['residual_H_after_bridge']:.3f} "
              f"[{s1['residual_H_after_bridge_ci'][0]:.3f}, {s1['residual_H_after_bridge_ci'][1]:.3f}] |",
              f"| S2 bridge Ĥ vs actual window deviation δx (FP replay) | {s2['cos_dx_hhat']:.3f} | ‖Ĥ‖/‖δx‖ {s2['norm_hhat_over_dx']:.3f} | {s2['residual_after_bridge']:.3f} "
              f"[{s2['residual_after_bridge_ci'][0]:.3f}, {s2['residual_after_bridge_ci'][1]:.3f}] |",
              f"| S2 coefficient-only H vs δx | {s2['cos_dx_H']:.3f} | ‖H‖/‖δx‖ {s2['norm_H_over_dx']:.3f} | {s2['residual_after_H']:.3f} |", "",
              f"- Least-squares scale λ_ls = {s2['lambda_ls']:.3f} [{s2['lambda_ls_ci'][0]:.3f}, {s2['lambda_ls_ci'][1]:.3f}] → λ* = {sc['lambda_star']}.",
              f"- Forward-extrapolation indicator: cosine of successive anchor jumps {s1['forward_extrapolation_cosine']:+.3f}.",
              "", "| interval start a | cos(δx, Ĥ) | ‖Ĥ‖/‖δx‖ | residual after bridge | cos(δx, H) | ‖H‖/‖δx‖ |", "|---:|---:|---:|---:|---:|---:|"]
        for a, r in sc["per_interval"].items():
            L.append(f"| {a} | {r['cos_dx_hhat']:.3f} | {r['norm_hhat_over_dx']:.3f} | {r['residual_after_bridge']:.3f} | {r['cos_dx_H']:.3f} | {r['norm_H_over_dx']:.3f} |")
        L.append("- Diagnostic FP calls (same-state, replay) are not part of the method.")
    else:
        L.append("- **Unrun.**")
    for title, res in (("S3 small live run (60208–60223, batch 16; exploratory)", dv), ("Confirmation (98100–98163, fresh, batch 32, opened once)", cf)):
        L += ["", f"## {title}", ""]
        if not res:
            L.append("- **Unrun.**")
            continue
        tables(res, L)
    if dv:
        L.append(f"- Confirmation gate: {dv['gate']['ratios_vs_min_C_Clast49']} → **{'confirm' if dv['gate']['proceed'] else 'stop'}** ({dv['gate']['rule']}).")
    if cf:
        L += [f"- **Primary ({cf['primary'].replace('_vs_', ' / ')}): {cf['reading_primary']}.**", f"- CB1 / C: {cf['reading_CB1_vs_C']}; C_last49 / C: {cf['reading_C_last49_vs_C']}."]
    L += ["", "## Related work (limited search, 2026-10-30; no novelty claim)",
          "- FSampler (arXiv 2511.09180): periodic real calls with finite-difference extrapolation between them. Q-Drift (arXiv 2603.18095): sampler-side drift",
          "  correction for quantized models from paired calibration runs. Neither was found to apply a retrospective interpolation between consecutive anchor",
          "  discrepancies; a broader search remains necessary."]
    open(os.path.join(OUT, "REPORT.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
