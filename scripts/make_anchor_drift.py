"""Generate results/anchor_drift/REPORT.md from the ad1 JSON outputs (missing stages reported as unrun)."""
import csv
import json
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "results", "anchor_drift")


def j(n):
    f = os.path.join(OUT, n)
    return json.load(open(f)) if os.path.exists(f) else None


def tables(res, L):
    L += ["| arm | latent rel. MSE mean | median | PSNR (dB) | LPIPS |", "|---|---:|---:|---:|---:|"]
    for a, s in res["summary"].items():
        L.append(f"| {a} | {s['rel_mse']['mean']:.5f} | {s['rel_mse']['median']:.5f} | {s['psnr']['mean']:.2f} | {s['lpips']['mean']:.4f} |")
    L += ["", "| contrast | mean-MSE ratio [95% CI] | mean diff [CI] | median diff | wins | ΔLPIPS [CI] | ΔPSNR [CI] |", "|---|---:|---:|---:|---:|---:|---:|"]
    for k, v in res["contrasts"].items():
        m, lp, ps = v["rel_mse"], v["lpips"], v["psnr"]
        L.append(f"| {k.replace('_vs_', ' / ')} | {m['ratio']:.3f} [{m['ratio_ci'][0]:.3f}, {m['ratio_ci'][1]:.3f}] | {m['diff']:+.5f} [{m['diff_ci'][0]:+.5f}, "
                 f"{m['diff_ci'][1]:+.5f}] | {m['median_diff']:+.5f} | {m['wins_x']}/{m['n']} | {lp['diff']:+.4f} [{lp['diff_ci'][0]:+.4f}, {lp['diff_ci'][1]:+.4f}] | "
                 f"{ps['diff']:+.2f} [{ps['diff_ci'][0]:+.2f}, {ps['diff_ci'][1]:+.2f}] |")
    it = res["interaction"]
    L += ["", f"- Objective × feedback interaction I = [E(C.L) − E(C.D)] − [E(AC.L) − E(AC.D)] = {it['I_abs']:+.5f} [{it['I_abs_ci'][0]:+.5f}, {it['I_abs_ci'][1]:+.5f}] "
          f"(drift gain without feedback {it['drift_gain_fb_off']:+.5f} [{it['drift_gain_fb_off_ci'][0]:+.5f}, {it['drift_gain_fb_off_ci'][1]:+.5f}], with "
          f"{it['drift_gain_fb_on']:+.5f} [{it['drift_gain_fb_on_ci'][0]:+.5f}, {it['drift_gain_fb_on_ci'][1]:+.5f}])."]


def main():
    ch, pr, dv, dg, fr, cf = (j(n) for n in ("checks.json", "profile.json", "dev.json", "diag.json", "frozen.json", "conf.json"))
    tr = {a: j(f"train_{a}.json") for a in ("C_D", "E_D")}
    rows = [r for r in csv.reader(open(os.path.join(ROOT, "results", "gpu_hours.csv"))) if r and r[0] == "ad1"]
    tot = sum(float(r[-1]) for r in rows)
    L = ["# Anchor-drift calibration of the low-rank branch (ad1): report", "",
         "Protocol `PROTOCOL.md` (pre-registered 2026-10-30, commit 0030279; amendments dated). Generated by `scripts/make_anchor_drift.py`.",
         f"**GPU: {tot:.3f} of 2.0 A30-h** ({', '.join(f'{r[1]} {float(r[-1]):.4f}' for r in rows)}).",
         "Fidelity to a generated FP-50 reference on DiT-XL/2 256 (fake-quant simulation); one training seed per arm. **No speedup, novelty or generation-quality claim.**", "",
         "IDs (all anchored arms: FP anchors every 4 calls with reuse; C = feedback off, AC = feedback on): C0 / AC0 = unrefitted base carry; C.L / AC.L = joint-pilot",
         "local-objective refits C_L / E_L (u200); C.D / AC.D = drift-objective refits C_D / E_D trained here (u200). Q*/A* = the same carries without anchors (dev only).", ""]
    L += ["## Checks"]
    if ch:
        L += [f"- D1 anchored training path restore bitwise {ch['D1_restore_bitwise']}; D2 anchor-term gradient rel. L2 {ch['D2_anchor_grad_rel_l2']:.2f} (pass {ch['D2_pass']}); "
              f"D3 checkpoint forward bitwise {ch['D3_forward_bitwise']}, gradient rel. L2 {ch['D3_grad_rel_l2']:.1e}; D4 quantizer calls per site in the gradient pass "
              f"{ch['D4_calls_per_site_fwd_plus_recompute']}",
              f"- D5 u0 export = base {ch['D5_u0_export_equals_base']}; base carry = aa1 C / AC {ch['D5_aa1_bitwise']}; carry swap = joint latents {ch['D5_swap_bitwise_vs_joint']}",
              f"- D6 training-path vs evaluation-sampler endpoint rel. L2 {ch['D6_training_path_vs_eval_sampler_rel_l2_AC0_4img']:.3f} (reported)",
              f"- **All checks pass: {ch['pass']}**"]
        if pr:
            L.append(f"- Profile: C_D {pr['C_D']['sec_per_update']:.2f} s/update, E_D {pr['E_D']['sec_per_update']:.2f} s/update, peak {pr['E_D']['peak_mem_GiB']:.1f} GiB.")
    else:
        L.append("- **Unrun.**")
    L += ["", "## Training (200 updates, joint-pilot draw plan, lr 1e-4, batch 4)"]
    for a, t in tr.items():
        if t:
            lg = t["log"]
            f = lambda s, k: np.mean([r[k] for r in s])
            L.append(f"- {a}: {t['sec_per_update']:.2f} s/update, peak {t['peak_mem_GiB']:.1f} GiB; normalized drift loss first/last 20 updates {f(lg[:20], 'loss'):.4f} → "
                     f"{f(lg[-20:], 'loss'):.4f}; window local loss {f(lg[:20], 'local_window_norm'):.4f} → {f(lg[-20:], 'local_window_norm'):.4f} (training draws, noisy).")
        else:
            L.append(f"- {a}: **not trained.**")
    for title, res in (("Development (60208–60223, batch 16; exploratory)", dv), ("Confirmation (97100–97163, fresh, batch 32, opened once)", cf)):
        L += ["", f"## {title}", ""]
        if not res:
            L.append("- **Unrun.**")
            continue
        tables(res, L)
    if dv:
        L.append(f"- Divergence guard: {dv['divergence_guard']}.")
    if cf:
        L += [f"- **Drift vs local, feedback off (C.D / C.L): {cf['reading_drift_vs_local_fb_off']}.**",
              f"- **Drift vs local, feedback on (AC.D / AC.L): {cf['reading_drift_vs_local_fb_on']}.**",
              f"- Feedback after drift calibration (AC.D / C.D): {cf['reading_feedback_after_drift']}; after local calibration (AC.L / C.L): {cf['reading_feedback_after_local']}.",
              "- Simulation timing (s per 32-image trajectory, all models resident): " + ", ".join(f"{a} {v['median']:.1f}" for a, v in cf["timing_s_per_batch32"].items()) + "."]
    L += ["", "## Held-out drift / local energies (8 dev images, own anchored trajectories, same-state FP diagnostic calls)", ""]
    if dg:
        L += ["| arm | local energy Σ‖e_t‖² (non-anchor) | drift energy Σ‖e_t − e_a‖² | drift / local [CI] | window ρ | anchor identity residual |", "|---|---:|---:|---:|---:|---:|"]
        for a, r in dg["arms"].items():
            q = r["drift_over_local_nonanchor"]
            L.append(f"| {a} | {r['local_energy_nonanchor']:.4g} | {r['drift_energy_nonanchor']:.4g} | {q['v']:.3f} [{q['ci'][0]:.3f}, {q['ci'][1]:.3f}] | "
                     f"{r['window_uncentered_corr']:.3f} | {r['anchor_identity_rel_residual']:.1e} |")
        L += ["", "- Each arm on its own trajectory; cross-arm differences include trajectory changes."]
    else:
        L.append("- Not run.")
    L += ["", "## Related work (limited search, 2026-10-30; no novelty claim)",
          "- Q&C (arXiv 2503.02508): quantization combined with feature caching; temporal-aware calibration and variance compensation.",
          "- LearniBridge (arXiv 2606.26778): learnable low-rank correction of cached features. Q-Drift (arXiv 2603.18095): sampler-side drift correction for quantized models.",
          "- None of these was found to fit a quantization branch to the anchored-prediction increment; a broader search and equation-level comparison remain necessary."]
    open(os.path.join(OUT, "REPORT.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
