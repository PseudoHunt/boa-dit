"""results/weight_anchor_controls/REPORT.md from the wac1 JSONs. Run: python scripts/make_weight_anchor_controls.py"""
import csv
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boa_dit.common import atomic_write_text

OUT = os.path.join(ROOT, "results", "weight_anchor_controls")
J = lambda f: json.load(open(os.path.join(OUT, f))) if os.path.exists(os.path.join(OUT, f)) else None
CH, DV, TM, CF = (J(f) for f in ("checks.json", "dev.json", "timing.json", "conf.json"))
rows = [r for r in csv.reader(open(os.path.join(ROOT, "results", "gpu_hours.csv"))) if r and r[0] == "wac1"]
spent = sum(float(r[-1]) for r in rows)
rc = lambda d: f"{100 * d['rel_change']:+.1f}% [{100 * d['ci'][0]:+.1f}, {100 * d['ci'][1]:+.1f}]"
dc = lambda d, f="+.4f": f"{d['diff']:{f}} [{d['ci'][0]:{f}}, {d['ci'][1]:{f}}]"
DESC = {"FP50": "FP at all 50 calls (reference)", "Q": "plain W4", "A": "FP anchors, W4 between", "R": "anchors + calibrated reuse (wa1 method)",
        "S": "FP anchors, hold last FP output (no other calls)", "R1": "anchors + reuse with β = 1", "FP13": "standard 13-step DDIM, FP", "FPk": "latency-matched FP-k"}

L = ["# Weight-anchor controls (wac1): report (generated by `scripts/make_weight_anchor_controls.py`)", "",
     "Bed (unchanged from wa1): heig-8 W4A16 (simulated quantization), DiT-XL/2 256, DDIM-50, cfg 1.5, fp16 autocast, batch 32; K = 4 anchors (13 FP calls), "
     "frozen wa1 β table, s = 1. Protocol `PROTOCOL.md`; timing-unit audit of the wa1 numbers `timing_audit.md`; asset inventory `release_inventory.md`.",
     f"**GPU: {spent:.3f} of 0.5 A30-h.** No K = 8, no FID, no new method.", ""]
if CH:
    L += ["## Correctness checks", "",
          f"- C1, on dev 92000–92031 the harness reproduces the wa1 cached latents bitwise: {CH['C1']}.",
          f"- C2, S with K = 1 equals FP50 bitwise: **{CH['C2_S_K1_equals_FP50']}**.",
          f"- C3, call counts as registered: **{CH['C3_pass']}**.",
          f"- C4, zeroing the auxiliary (variance) channels 4–7 leaves the FP50 endpoint bitwise unchanged: **{CH['C4_aux_zero_equals_FP50']}**, so S holding them cannot affect any result.", ""]


def arm_table(R, title):
    out = [title, "", "| arm | behaviour | W4 calls | FP calls | latent rel. MSE (mean) | median | PSNR | LPIPS |", "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
    out.append(f"| FP50 | {DESC['FP50']} | 0 | 50 | 0 | 0 | ∞ | 0 |")
    for a, v in R["arms"].items():
        c = R["calls"][a]
        out.append(f"| {a} | {DESC.get(a, a)} | {c['w4']} | {c['fp']} | {np.mean(v['rel_mse']):.5f} | {np.median(v['rel_mse']):.5f} | {np.mean(v['psnr']):.2f} | {np.mean(v['lpips']):.4f} |")
    n = len(next(iter(R["arms"].values()))["rel_mse"])
    out += ["", "| contrast (x vs y) | latent rel. MSE change [95% CI] | median per-image Δ latent | x wins | ΔPSNR | ΔLPIPS | x wins (LPIPS) |", "| --- | --- | ---: | ---: | --- | --- | ---: |"]
    for k, v in R["contrasts"].items():
        out.append(f"| {k.replace('_vs_', ' vs ')} | {rc(v['rel_mse'])} | {v['rel_mse']['median_diff']:+.5f} | {v['rel_mse']['wins_x']}/{n} | {dc(v['psnr'], '+.2f')} | {dc(v['lpips'])} | {v['lpips']['wins_x']}/{n} |")
    out += ["", "Pre-registered readings: " + "; ".join(f"**{k.replace('_vs_', ' vs ')}: {v}**" for k, v in R["readings"].items()) + ".", ""]
    return out


if DV:
    L += arm_table(DV, "## Development (exploratory; images 92000–92031 were used in wa1)")
if TM:
    L += ["## Measured cost (complete trajectories)", "", f"Device {TM['device']}. {TM['conditions']}. Median [min, max] of 5 timed repetitions.", "",
          "| arm | W4 / FP calls | batch 32: wall s | batch 32: CUDA-event s | batch 1: wall s | working mem, batch 32 (GB) | models needed | est. memory needed, batch 32 (GB) |",
          "| --- | --- | --- | --- | --- | ---: | --- | ---: |"]
    for a in ("FP50", "R", "S", "Q", "A", "R1", "FP13"):
        b, o = TM["batch32"][a], TM["batch1"][a]
        w = lambda x: f"{x['median']:.3f} [{x['min']:.3f}, {x['max']:.3f}]"
        L.append(f"| {a} | {b['calls']['w4']} / {b['calls']['fp']} | {w(b['wall_s'])} | {w(b['cuda_event_s'])} | {w(o['wall_s'])} | {b['working_mem_bytes'] / 1e9:.2f} | "
                 f"{' + '.join(TM['models_needed'][a])} | {b['est_needed_mem_bytes (needed resident + working)'] / 1e9:.2f} |")
    rb = TM["resident_model_bytes"]
    L += ["", f"Resident model bytes: FP {rb['fp'] / 1e9:.2f} GB, simulated W4 {rb['w4_sim'] / 1e9:.2f} GB (dequantized fp32, no packed storage), both {rb['both'] / 1e9:.2f} GB. "
              "Estimated memory needed = resident bytes of the models the arm needs + measured working memory during the trajectory. The simulated W4 model has no low-bit "
              "kernels: its timing says nothing about deployed W4.",
          "", f"**First decision: FP-50 faster than R at batch 32: {TM['fp50_faster_than_R_batch32']}** (batch 1: {TM['fp50_faster_than_R_batch1']}). "
              + ("No latency-matched FP-k comparison is made (FP-50 fits within R's time and is the zero-discrepancy reference)." if TM["fp50_faster_than_R_batch32"]
                 else f"Latency-matched FP-k frozen by timing: {TM['fpk']}."), ""]
if CF:
    L += arm_table(CF, "## Confirmation (fresh seeds 93000–93063, opened once)")
L += ["## Budget ledger", "", "| run | start | end | GPU-h |", "| --- | --- | --- | ---: |"] + [f"| {r[1]} | {r[3]} | {r[4]} | {float(r[5]):.4f} |" for r in rows] + \
     [f"| **total** | | | **{spent:.3f}** |", "",
      "Reproduce: `python -m boa_dit.weight_anchor.controls dev|timing|conf`, then `python scripts/make_weight_anchor_controls.py`. C1 needs the wa1 dev latents "
      "(`ckpt/weight_anchor/live_dev_latents.pt`, VM-only; regenerate with `python -m boa_dit.weight_anchor.run live_dev`). Inputs and their regeneration: `release_inventory.md`."]
_i = os.path.join(OUT, "decision.md")
L += ["", open(_i).read()] if os.path.exists(_i) else ["", "## Decision memo", "", "_Not yet written._"]
atomic_write_text(os.path.join(OUT, "REPORT.md"), "\n".join(L) + "\n")
print("\n".join(L))
