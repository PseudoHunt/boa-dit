def src_block(obj, start, end):
    """Literal source lines of obj between the first line containing `start` and the first after it containing `end`."""
    lines, first = inspect.getsourcelines(obj)
    i = next(k for k, l in enumerate(lines) if start in l)
    j = next(k for k, l in enumerate(lines) if k >= i and end in l)
    path = os.path.relpath(inspect.getsourcefile(obj), os.path.dirname(OUT.rstrip("/")) + "/..")
    body = "".join(f"{first + k:4d}  {lines[k]}" for k in range(i, j + 1))
    return f"`{path}` lines {first + i}–{first + j}:\n\n```python\n{body}```\n"


def clip_cells(tab_path, T, nb):
    """(layer, timestep bucket) clip rates of the single-table A8 ranges (histogram estimate, calibration data)."""
    if not os.path.exists(tab_path):
        return None, None
    tb = torch.load(tab_path, map_location="cpu")
    w = T // nb
    cells, by_type = [], {}
    for k, v in tb.items():
        cr = v["clip_rate"].numpy()
        for b in range(nb):
            cells.append((float(cr[b * w:(b + 1) * w].mean()), k, b))
        by_type.setdefault(k.split(".", 1)[1], []).append(cr.reshape(nb, w).mean(1))
    typ = {t: np.mean(v, axis=0) for t, v in by_type.items()}
    return sorted(cells, reverse=True), typ


