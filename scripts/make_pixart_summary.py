"""results/attn_share/pixart/SUMMARY.md from verdict.json, stats.json and gpu_hours.csv."""
import csv
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boa_dit.common import atomic_write_text  # noqa: E402

OUT = os.path.join(ROOT, "results", "attn_share", "pixart")
v = json.load(open(os.path.join(OUT, "verdict.json")))
d = json.load(open(os.path.join(OUT, "stats.json")))
c = d["cross_attention_control"]
gh = sum(float(r["gpu_hours"]) for r in csv.DictReader(open(os.path.join(ROOT, "results", "gpu_hours.csv"))) if "pixart" in r["run"])
fr = v["frac_pairs_within_ge_0.8_per_step"]
r2 = [c["within_diffprompt"][s][j] / c["within_sameprompt"][s][j] for s in range(8) for j in range(len(c["heads"]))]
L = ["# PixArt-Σ 1024 (4096 tokens, text-conditioned): early self-attention diagnostic — summary\n",
     "Generated by `scripts/make_pixart_summary.py`. FP model, 16 images (8 fixed prompts × seeds 0/1), DPM-Solver++ 20 steps, "
     "guidance 4.5, all 28 blocks × 16 heads, steps 0–9. Pre-registration and full tables: `gate.md`; facts: `model_facts.md`.\n",
     f"## Verdict: **{v['verdict']}**\n",
     "| condition (steps 0–7) | result | needed | holds |", "| --- | --- | --- | --- |",
     f"| A: within ≥ 0.8 in ≥ 70% of pairs at every step; KL ratio ≥ 3 in ≥ half | per-step fraction "
     f"{', '.join(f'{x:.2f}' for x in fr[:8])}; KL share {v['A_kl_share_among_clearing']:.2f} | every step ≥ 0.70 | {v['A']} |",
     f"| B: diff-/same-prompt within ratio ≥ 0.9 | in {100 * v['B_frac_ratio_ge_0.9']:.1f}% of triples (median {v['B_ratio_median']:.3f}) | ≥ 70% | {v['B']} |",
     f"| C: floor-subtracted 95% residual square | median {v['C_side_min_median']:.0f} tokens; ≤ 21 in {100 * v['C_frac_side_le_21']:.1f}% | "
     f"median ≤ 13, ≥ 90% ≤ 21 | {v['C']} |",
     f"\ns_max = {v['s_max']} (agreement holds at steps 0–{v['s_max_contiguous']} of 20).\n",
     "## What it means\n",
     f"- **Prompt-independence survives text conditioning.** Early self-attention rows agree across different prompts as "
     f"much as across seeds of one prompt (median ratio {v['B_ratio_median']:.3f}). The cross-attention control (block "
     f"{c['block']}, heads {c['heads']}) is strongly prompt-dependent (diff/same ratio {min(r2):.2f}–{max(r2):.2f} at "
     f"s ≤ 7). See `cross_attention_control.png`.",
     f"- **But the shared window is short.** Cross-image agreement decays after step {v['s_max_contiguous']} of 20 (15% of the "
     "schedule), against 14 of 50 (30%) on class-conditional DiT-XL/2 at 256 px. That fails A as pre-registered. The "
     "pre-registered STOP label (\"specific to class-conditional DiT\") overstates it: the image-independence is real but "
     f"brief, while prompt-independence holds in {100 * v['B_frac_ratio_ge_0.9']:.0f}% of (block, head, step ≤ 7) triples.",
     f"- **The linear-time form is ruled out.** With the floor removed (min κ, {100 * v['floor_share_min_median']:.0f}% of the mass), "
     f"the residual 95% support is the full 127 × 127 offset range at the median ({100 * v['C_frac_full_127']:.0f}% of kernels "
     f"exactly full). With the median floor ({100 * v['floor_share_median_median']:.0f}% of the mass) it is still "
     f"{v['C_side_median_floor_median']:.0f}. \"Global mean of V + small convolution\" does not describe these maps, matching "
     "DiT-XL/2 at 256 px.",
     "",
     "## Not run (STOP at the gate, as the handoff specifies)\n",
     "- §3 compute-path timing (single-channel / grouped conv and FFT against SDPA at N = 4096). The code is ready in "
     "`boa_dit/attn_share/pixart/compute.py` (about 15 GPU-minutes) if wanted regardless.",
     "- §4 qualitative replacement grid and CLIP score. The code is ready in `boa_dit/attn_share/pixart/sanity.py`.",
     "",
     "## Records\n",
     "- FP images: `fp_grid.jpg`. Plots: `heatmaps.png`, `cross_attention_control.png`.",
     f"- Processor parity: max rel {v['parity']['explicit_vs_sdpa_max_rel']:.1e} vs default SDPA, against an fp16 noise floor of "
     f"{v['parity']['sdpa_math_vs_sdpa_default_max_rel']:.1e} (math-backend SDPA vs default). The tolerance of 1e-3 is below "
     "that floor; this is recorded in `gate.md`, and the tolerance was not changed.",
     f"- GPU-hours: {gh:.2f} logged, plus about 5 unlogged GPU-minutes (prompt encoding, facts, parity). Cap 1.5.",
     "- Untested caveat (both models): κ averages each offset without weighting by pair count."]
atomic_write_text(os.path.join(OUT, "SUMMARY.md"), "\n".join(L) + "\n")
print("\n".join(L))
