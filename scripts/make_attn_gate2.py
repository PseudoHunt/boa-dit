"""Gate 2 (attention sharing): results/attn_share/gate2.md, FID-vs-k plot and matched-seed grid from the arm JSONs."""
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boa_dit.common import atomic_savefig, atomic_write_json, atomic_write_text  # noqa: E402

OUT = os.path.join(ROOT, "results", "attn_share")
ORDER = ["k5", "k10", "k15", "k20", "k15-sel", "k10-onemap", "k10-uniform", "fp"]
DESC = {"k5": "s < 5, all heads", "k10": "s < 10, all heads", "k15": "s < 15, all heads", "k20": "s < 20, all heads",
        "k15-sel": "s < 15, heads with Gate 1 within ≥ 0.8", "k10-onemap": "s < 10, single map M[·,·,5]",
        "k10-uniform": "control (not in verdict): s < 10, uniform 1/256 maps",
        "fp": "check (not in verdict): patched model, sharing off"}
BAR = {5: 1.0, 10: 1.0, 15: 2.0, 20: 2.0}


def top1(a, R):
    """Per-image ResNet-50 top-1 on seeds 0-511: from the arm JSON, else from the label-accuracy rerun."""
    if a == "fp-ref":
        return np.array(json.load(open(os.path.join(OUT, "fp_resnet_top1_512.json")))["top1"])
    if R.get(a) is not None and "top1_512" in R[a]:
        return np.array(R[a]["top1_512"])
    p = os.path.join(OUT, "eval", f"label_acc_{a}.json")
    return np.array(json.load(open(p))["top1_512"]) if os.path.exists(p) else None


def acc_vs_fp(t, t_fp, y):
    """Label accuracy, and its difference to FP with a paired bootstrap 95% CI over the 512 images."""
    a, b = (t == y).astype(float), (t_fp == y).astype(float)
    rng = np.random.default_rng(0)
    bs = [a[i].mean() - b[i].mean() for i in (rng.integers(0, len(a), len(a)) for _ in range(2000))]
    lo, hi = np.percentile(bs, [2.5, 97.5])
    return a.mean(), a.mean() - b.mean(), lo, hi


def load(a):
    p = os.path.join(OUT, "eval", f"gate2_{a}.json")
    return json.load(open(p)) if os.path.exists(p) else None


def main():
    fp_fid = json.load(open(os.path.join(ROOT, "results", "stage2", "fid_anchors.json")))["anchors"]["FP"]["fid2k"]
    R = {a: load(a) for a in ORDER}
    from boa_dit.model import labels_for_seeds
    y = np.array(labels_for_seeds(list(range(512))))
    t_fp = top1("fp-ref", R)
    ACC = {a: acc_vs_fp(top1(a, R), t_fp, y) for a in ORDER if top1(a, R) is not None}
    L = ["# Attention sharing — Gate 2: does sharing early attention maps cost image quality?\n",
         "Generated by `scripts/make_attn_gate2.py` from `results/attn_share/eval/gate2_*.json`.\n",
         f"FP DiT-XL/2 256, cfg 1.5, DDIM-50, seeds 0–1999 for FID-2k (vs ADM reference stats); FP FID-2k anchor "
         f"**{fp_fid:.2f}** (`results/stage2/fid_anchors.json`, same seeds). Maps: Gate 1 mean maps from the 32 "
         "calibration images, cond and uncond separately, fp16. Secondary (information only): rel. latent MSE vs FP "
         "and ResNet-50 top-1 class change on seeds 0–511; IS from torchvision Inception-v3 (not comparable to "
         "published IS).\n",
         f"ResNet-50 label accuracy (top-1 vs the conditioning label y, seeds 0–511): FP **{100 * (t_fp == y).mean():.1f}%** "
         "(from `fp_resnet_top1_512.json`, the decoded FP reference latents); Δ vs FP with a paired bootstrap 95% CI.\n",
         "| arm | definition | FID-2k | ΔFID vs FP | IS | rel. latent MSE (mean / median) | class changed | label acc | Δ acc vs FP | GPU-h |",
         "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for a in ORDER:
        r = R[a]
        if r is None:
            L.append(f"| {a} | {DESC[a]} | pending | — | — | — | — | — | — | — |")
            continue
        L.append(f"| {a} | {DESC[a]} | {r['fid2k']:.2f} | {r['fid2k'] - fp_fid:+.2f} | {r['is_mean']:.1f} ± {r['is_std']:.1f} | "
                 f"{r['rel_mse_mean_512']:.4f} / {r['rel_mse_median_512']:.4f} | {100 * r['class_changed_frac_512']:.1f}% | "
                 + (f"{100 * ACC[a][0]:.1f}% | {100 * ACC[a][1]:+.1f} [{100 * ACC[a][2]:+.1f}, {100 * ACC[a][3]:+.1f}] | "
                    if a in ACC else "pending | — | ") + f"{r['gpu_hours']:.2f} |")
    L.append("")
    L.append("Reading of the rule (fixed 2026-10-25T10:12Z in commit aa9b67c, before any Gate 2 arm finished): PASS iff FID(k10) ≤ FP + 1.0 "
             "and FID(k15) ≤ FP + 2.0. `k_pass` = largest k ∈ {5, 10, 15, 20} whose FID is within its bar: +1.0 for "
             "k ≤ 10 and +2.0 for k ≥ 15 (k20 is held to the k15 bar). STOP if k5 already exceeds +1.0.\n")
    v = {"fp_fid2k": fp_fid}
    d = {k: R[f"k{k}"]["fid2k"] - fp_fid for k in BAR if R[f"k{k}"] is not None}
    if 10 in d and 15 in d and 5 in d:
        passed = d[10] <= 1.0 and d[15] <= 2.0
        k_pass = max([k for k in BAR if k in d and d[k] <= BAR[k]], default=0)
        v.update({"delta_fid": d, "pass": passed, "k_pass": k_pass, "k5_over_1": d[5] > 1.0})
        L.append(f"- ΔFID k10 = {d[10]:+.2f} (≤ +1.0: **{d[10] <= 1.0}**); ΔFID k15 = {d[15]:+.2f} "
                 f"(≤ +2.0: **{d[15] <= 2.0}**); ΔFID k5 = {d[5]:+.2f}.")
        L.append(f"- k_pass = **{k_pass}**" + ("" if 20 in d else " (k20 pending)") + ".")
        if R["fp"] is not None:
            L.append(f"- Check: the patched model with sharing off reproduces FID-2k {R['fp']['fid2k']:.2f} "
                     f"(anchor {fp_fid:.2f}); rel. latent MSE vs the FP reference {R['fp']['rel_mse_mean_512']:.1e}.")
        if R["k10-uniform"] is not None and R["k10"] is not None:
            L.append(f"- Control: uniform maps over the same window give FID-2k {R['k10-uniform']['fid2k']:.2f} vs "
                     f"{R['k10']['fid2k']:.2f} for the stored maps (rel. latent MSE {R['k10-uniform']['rel_mse_mean_512']:.4f} "
                     f"vs {R['k10']['rel_mse_mean_512']:.4f}).")
        main_arms = [a for a in ("k5", "k10", "k15", "k20", "k15-sel", "k10-onemap") if a in ACC]
        if main_arms:
            drops = [a for a in main_arms if ACC[a][3] < 0]
            L.append(f"- Label accuracy across the six arms: {', '.join(f'{a} {100 * ACC[a][0]:.1f}%' for a in main_arms)} "
                     f"(FP {100 * (t_fp == y).mean():.1f}%). " +
                     ("Flat: every arm's CI for Δ vs FP includes 0, so the class changes are benign bifurcations "
                      "(a different valid image of the same class), not damage." if not drops else
                      f"Drop with CI excluding 0 in: {', '.join(f'{a} {100 * ACC[a][1]:+.1f} pts' for a in drops)}.") +
                     ("" if len(main_arms) == 6 else " (some arms pending)"))
        verdict = "PASS" if passed else ("STOP (k5 already costs > 1.0 FID)" if d[5] > 1.0 else "STOP")
        if passed and R["k10-uniform"] is None:
            verdict = "PASS (provisional: the uniform-control FID has not landed)"
        L.append(f"\n**Gate 2: {verdict}**\n")
        v["verdict"] = verdict
    else:
        L.append("**Gate 2: PENDING**\n")
    L.append("Plots: `gate2_fid_vs_k.png`, `gate2_grid.png` (seeds 0–7, rows = arms, matched noise and class).\n")
    atomic_write_json(os.path.join(OUT, "gate2_verdict.json"), v)
    atomic_write_text(os.path.join(OUT, "gate2.md"), "\n".join(L) + "\n")
    plots(R, fp_fid)
    print("\n".join(L))


def plots(R, fp_fid):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import torch
    ks = [k for k in (5, 10, 15, 20) if R[f"k{k}"] is not None]
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.plot([0] + ks, [fp_fid] + [R[f"k{k}"]["fid2k"] for k in ks], marker="o", label="all heads")
    for a, mk in (("k15-sel", "s"), ("k10-onemap", "^"), ("k10-uniform", "x")):
        if R[a] is not None:
            ax.scatter([R[a]["k"]], [R[a]["fid2k"]], marker=mk, s=60, label=a, zorder=3)
    ax.axhline(fp_fid + 1, color="gray", ls=":", lw=1); ax.axhline(fp_fid + 2, color="gray", ls="--", lw=1)
    ax.set_xlabel("shared window k (steps s < k)"); ax.set_ylabel("FID-2k"); ax.legend(fontsize=8)
    fig.tight_layout(); atomic_savefig(fig, os.path.join(OUT, "gate2_fid_vs_k.png")); plt.close(fig)
    rows = [a for a in ["fp", "k5", "k10", "k15", "k20", "k15-sel", "k10-onemap", "k10-uniform"]
            if os.path.exists(os.path.join(OUT, "maps", f"grid_{a}.pt"))]
    if not rows:
        return
    fig, axs = plt.subplots(len(rows), 8, figsize=(16, 2.1 * len(rows)), squeeze=False)
    for r, a in enumerate(rows):
        g = torch.load(os.path.join(OUT, "maps", f"grid_{a}.pt"), map_location="cpu")
        for c in range(8):
            axs[r, c].imshow(g[c].permute(1, 2, 0).numpy()); axs[r, c].set_xticks([]); axs[r, c].set_yticks([])
        axs[r, 0].set_ylabel(a, fontsize=11)
    fig.tight_layout(); atomic_savefig(fig, os.path.join(OUT, "gate2_grid.png")); plt.close(fig)


if __name__ == "__main__":
    main()
