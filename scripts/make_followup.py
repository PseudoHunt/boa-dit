def boot_ratio(a, b, n=2000, seed=0):
    """Paired bootstrap of mean(a)/mean(b) - 1 over items (same convention as the experiment scripts)."""
    a, b = np.asarray(a), np.asarray(b)
    idx = np.random.default_rng(seed).integers(0, len(a), (n, len(a)))
    r = a[idx].mean(1) / b[idx].mean(1) - 1
    return {"rel_change": a.mean() / b.mean() - 1, "ci": [float(np.percentile(r, 2.5)), float(np.percentile(r, 97.5))]}


