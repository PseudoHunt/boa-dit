"""results/attn_share/SUMMARY.md from the gate verdict JSONs and arm results (no hand-typed numbers)."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boa_dit.common import atomic_write_text  # noqa: E402

OUT = os.path.join(ROOT, "results", "attn_share")


def load(n):
    p = os.path.join(OUT, n)
    return json.load(open(p)) if os.path.exists(p) else None


def main():
    st = load("gate1_stats.json")["stats"]
    v1, v2, v3 = load("gate1_verdict.json"), load("gate2_verdict.json"), load("gate3_verdict.json")
    ev = {a: load(f"eval/gate2_{a}.json") for a in ("k5", "k10", "k15", "k20", "k15-sel", "k10-onemap", "k10-uniform", "fp")}
    c, cv, ks = load("compute.json"), load("convpath.json"), load("kernel_support.json")
    import numpy as np
    A = {k: np.array(v, dtype=float) for k, v in st.items()}
    e = slice(0, 10)
    fp = v2["fp_fid2k"]
    d = {k: ev[k]["fid2k"] - fp for k in ev if ev[k] is not None}
    L = ["# Sample-independent attention in DiT — summary\n",
         "Generated by `scripts/make_attn_summary.py`. Model: **DiT-XL/2, 256 px, class-conditional ImageNet**, DDIM-50, "
         "cfg 1.5, FP weights. Details in `gate1.md`, `gate2.md`, `gate3.md` and `compute.md`; dated log in "
         "`../REPORT.md`.\n",
         "## What was shown\n",
         f"At high-noise steps, a DiT-XL/2 block's attention map is, to a good approximation, a property of the "
         f"(block, head, step, position) and not of the image. The mean map over 32 calibration images "
         f"(16 classes × 2 noises) can replace the computed softmax(QKᵀ) for every image. Sharing steps 0–14 costs "
         f"{d['k15']:+.2f} FID-2k, and steps 0–19 cost {d['k20']:+.2f} (FP {fp:.2f}, same 2,000 seeds). Uniform maps over "
         f"steps 0–9 cost {d['k10-uniform']:+.2f}, so the shared maps carry real structure, not just near-uniformity. "
         f"The maps are class-independent (cross-image row cosine at s ≤ 9: same class "
         f"{np.median(A['within_sameclass'][e]):.3f} vs different class {np.median(A['within_diffclass'][e]):.3f}) and "
         f"branch-independent (cond vs uncond mean map {np.median(A['branch_cos_median'][e]):.3f}). They are close to "
         f"translation-invariant: a 31×31 offset kernel per head rebuilds the mean map at cosine "
         f"{np.median(A['kernel_cos_median'][e]):.3f}." + (
             f" In images, the kernel form (V3, {v3['V3']['bytes'] / 1e6:.1f} MB for all {v3['k_pass']} shared steps) is "
             f"{v3['V3']['delta_vs_V1']:+.2f} FID-2k from the full per-step maps "
             f"({v3['V3']['fid2k'] - fp:+.2f} vs FP)." if v3 and v3.get("V3", {}).get("fid2k") else "") + "\n",
         "This shares attention **across samples**. Existing diffusion caching methods (DeepCache, TeaCache, FORA, "
         "Δ-DiT, ToCa, and PAB, which broadcasts attention across steps in video DiTs) reuse computation across adjacent "
         "steps of one sample, and ToMe-SD merges tokens spatially. As far as we know, the cross-sample axis is untaken.\n",
         "## Gates\n",
         "| gate | verdict | key numbers |", "| --- | --- | --- |",
         f"| 1: phenomenon real, non-trivial | {v1['verdict']} | ≥ 70% of (block, head) pairs with within ≥ 0.8 at every "
         f"s ≤ 9 (pooled {v1['pooled_frac_s0_9']:.2f}); KL-ratio share {v1['kl_ratio_ge3_share_among_clearing_s0_9']:.2f}; "
         f"s_max = {v1['s_max']} |",
         f"| 2: image quality | {v2['verdict']} | ΔFID-2k k5 {d['k5']:+.2f}, k10 {d['k10']:+.2f}, k15 {d['k15']:+.2f}, "
         f"k20 {d['k20']:+.2f}; k_pass = {v2['k_pass']} |"]
    if v3 and "verdict" in v3:
        parts = [f"{n} {v3[n]['delta_vs_V1']:+.2f} at {100 * v3[n]['frac_of_V1']:.2f}% of V1" for n in ("V2", "V3", "V4", "V5")
                 if v3[n].get("fid2k") is not None]
        L.append(f"| 3: cheap storage (k = {v3['k_pass']}) | {v3['verdict']} | ΔFID-2k vs V1: {'; '.join(parts)} |")
    else:
        L.append("| 3: cheap storage | pending | |")
    L.append("")
    if v3 and "verdict" in v3:
        L.append(f"Gate 3 notes: V3 misses the +0.5 bar by {v3['V3']['delta_vs_V1'] - 0.5:.2f} FID-2k, at "
                 f"{100 * v3['V3']['frac_of_V1']:.2f}% of V1's size. V2 and V4 cannot meet the ≤ 10% size condition on "
                 f"their own ({100 * v3['V2']['frac_of_V1']:.0f}% and {100 * v3['V4']['frac_of_V1']:.1f}%). Top-32 "
                 f"sparsification (V4) breaks the model ({v3['V4']['delta_vs_V1']:+.1f} FID-2k), consistent with the "
                 "near-uniform floor that holds about half of each kernel's mass. V2 (windowed, "
                 f"{v3['V2']['delta_vs_V1']:+.2f}) and V5 (branch-shared, {v3['V5']['delta_vs_V1']:+.2f}) are each "
                 "nearly free. Their combination would be exactly 10% of V1; it was not run, because Gate 3 had already "
                 "failed. It is the obvious next storage test.\n")
    L.append("## Speed: deferred, not claimed\n")
    if c:
        fr = {n: c["per_N"][n]["variants"]["V1/V2 dense stored map"]["end_to_end_frac_saved"] for n in c["per_N"]}
        kk = str(v2["k_pass"]) if str(v2["k_pass"]) in fr["256"] else max(fr["256"], key=int)
        L.append(f"At 256 px (N = 256 tokens) attention is a small part of a DiT block, so sharing k = {kk} steps "
                 f"removes only {100 * fr['256'][kk]:.1f}% of the FLOPs end to end (N = 1024: {100 * fr['1024'][kk]:.1f}%; "
                 f"N = 4096: {100 * fr['4096'][kk]:.1f}%).")
        m = c.get("measured")
        if m:
            t = m["timings"]
            sv = 1 - t["shared map, V-only projection"]["median_ms"] / t["baseline (fused SDPA)"]["median_ms"]
            L.append(f" Measured on the A30 at N = 256, a fully shared forward changes latency by {100 * sv:+.1f}% "
                     "against fused SDPA (plain PyTorch, no custom kernel).")
        share = {n: sum(c["per_N"][n]["block_flops"][k] for k in ("QK^T", "softmax", "AV (dense map)")) /
                 c["per_N"][n]["block_total"] for n in c["per_N"]}
        mlp = sum(c["per_N"]["4096"]["block_flops"][k] for k in ("fc1", "fc2")) / c["per_N"]["4096"]["block_total"]
        L.append(f"\n\n**No speed claim is made for this model.** The next step is a high-token-count model: **PixArt-Σ at "
                 f"1024 px (4096 tokens)**. There the N² attention core (QKᵀ, softmax, AV) grows to {100 * share['4096']:.0f}% "
                 f"of a block's FLOPs, up from {100 * share['256']:.0f}% at 256 tokens, at the same width (C = 1152). That is "
                 f"comparable to the MLP ({100 * mlp:.0f}%), not a majority. Dense stored maps cannot fit there "
                 "(16 · 4096² · 2 B = 537 MB per block, branch and step). There the compact V3 kernel is the only "
                 "viable form.")
    if ks:
        kd = ks["per_branch"]["cond"]
        L.append(f"\n\nOpen risk for that step: at 256 px the V3 kernel is not compact. The smallest centered square "
                 f"holding 95% of its mass is the full 31×31 in {100 * kd['frac_full_31']:.0f}% of (window, block, head) "
                 "cases. A convolution path is cheap at 4096 tokens only if the kernel's support stays bounded as the grid "
                 "grows; that has to be measured first on PixArt-Σ.")
    L.append("\n")
    if cv:
        r = cv["bench"]["per_N"]
        f4 = r["4096"]["ms_block_attention_sublayer"]
        L.append(f"Per-block microbenchmarks (`compute.md` §5; synthetic inputs, A30): at N = 4096 a dense stored map "
                 f"applied to all rows takes {f4['V1 dense stored map']:.1f} ms vs {f4['full attention (fused SDPA)']:.1f} ms "
                 f"for fused attention, but needs 537 MB per block-step. The V3 convolution takes "
                 f"{f4['V3 conv (31x31 depthwise)']:.0f} ms in PyTorch/cuDNN. **A fast kernel-form implementation does not "
                 "exist yet**; it is a prerequisite for the PixArt-Σ step, along with bounded kernel support.\n")
    kr = load("kernel_residual_support.json")
    if kr:
        L.append("## Residual-kernel support (floor removed)\n")
        L.append("From the saved V3 kernels (`artifacts/V3_kernels_k20.pt`), per (block, head, window), k = 20; "
                 "κ_res = (κ − floor)₊; side = smallest centered square holding 95% of κ_res's mass (full = 31). "
                 "Rule: compact iff median side ≤ 9 and ≥ 90% of kernels ≤ 15. Source: `kernel_residual_support.json`.\n")
        L.append("| branch | floor | floor share (median [p10, p90]) | median side | ≤ 9×9 | ≤ 15×15 | full 31×31 | verdict |")
        L.append("| --- | --- | ---: | ---: | ---: | ---: | ---: | --- |")
        for br, d in kr["per_branch"].items():
            for how, r in d.items():
                L.append(f"| {br} | {how}(κ) | {100 * r['floor_share_median']:.0f}% [{100 * r['floor_share_p10']:.0f}, "
                         f"{100 * r['floor_share_p90']:.0f}] | {r['side_median']:.0f} | {100 * r['frac_side_le_9']:.1f}% | "
                         f"{100 * r['frac_side_le_15']:.1f}% | {100 * r['frac_side_31']:.1f}% | {r['verdict']} |")
        L.append(f"\n**Verdict: {kr['verdict']}.** It holds whether the floor is the minimum or the median of κ. On DiT-XL/2 "
                 "at 256 px, the non-uniform part of early attention is spread over the whole 16×16 grid, not concentrated "
                 "in a small window. A \"global mean of V + small convolution\" form does not reproduce these maps here.\n")
    L.append("## Not verified\n")
    L.append("- Text-to-image models (PixArt-Σ): text cross-attention and prompts may change how image-independent "
             "early self-attention is.")
    L.append("- Video DiTs.")
    L.append("- Any resolution other than 256 px, and so the kernel-support scaling the speed case depends on.")
    L.append("- Other samplers and step counts (all results use DDIM-50, cfg 1.5).\n")
    atomic_write_text(os.path.join(OUT, "SUMMARY.md"), "\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
