"""results/dit_joint/REPORT.md from eval.json, select.json, train_*.json, profile.json, checks.json (results/dit_joint/PROTOCOL.md).
Run: python scripts/make_dit_joint.py"""
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boa_dit.common import atomic_write_json, atomic_write_text

OUT = os.path.join(ROOT, "results", "dit_joint")
J = lambda f: json.load(open(os.path.join(OUT, f))) if os.path.exists(os.path.join(OUT, f)) else None
E, S, P, CH = J("eval.json"), J("select.json"), J("profile.json"), J("checks.json")
TR = {a: J(f"train_{a}.json") for a in ("C_L", "E_L", "C_R", "E_R")}
C = E["configs"]


def boot(a, b, ratio, n=2000):
    a, b = np.asarray(a), np.asarray(b)
    idx = np.random.default_rng(0).integers(0, len(a), (n, len(a)))
    if ratio:
        d = a[idx].mean(1) / b[idx].mean(1) - 1
        v = a.mean() / b.mean() - 1
    else:
        d = (a[idx] - b[idx]).mean(1)
        v = (a - b).mean()
    return {"v": float(v), "ci": [float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))], "median": float(np.median(a - b)), "wins": int((a < b).sum() if ratio else (a > b).sum())}


def contrast(x, y):
    return {"latent": boot(C[x]["rel_mse"], C[y]["rel_mse"], True), "psnr": boot(C[x]["psnr"], C[y]["psnr"], False), "lpips": boot(C[x]["lpips"], C[y]["lpips"], False),
            "lpips_wins": int((np.asarray(C[x]["lpips"]) < np.asarray(C[y]["lpips"])).sum())}


PAIRS = [("B", "A", "feedback effect"), ("C_L", "A", "carry (local) without feedback"), ("C_R", "A", "carry (rollout) without feedback"),
         ("D_L", "C_L", "stacking (local): D vs C"), ("D_L", "B", "stacking (local): D vs B"), ("D_R", "C_R", "stacking (rollout): D vs C"),
         ("D_R", "B", "stacking (rollout): D vs B"), ("E_R", "D_R", "**primary: joint training (rollout), fixed updates**"),
         ("E_L", "D_L", "local-objective integration control"), ("E_R", "E_L", "rollout-specific contribution with feedback"),
         ("E_R", "A", "E_R vs A"), ("E_R", "B", "E_R vs B")]
SEC = [("E_R*", "D_R*", "selected: E_R* vs D_R*"), ("E_L*", "D_L*", "selected: E_L* vs D_L*"), ("E_R*", "E_L*", "selected: E_R* vs E_L*")]
RES = {f"{x}_vs_{y}": {**contrast(x, y), "label": lab} for x, y, lab in PAIRS + SEC if x in C and y in C}
pct = lambda v: f"{100 * v['v']:+.1f}% [{100 * v['ci'][0]:+.1f}, {100 * v['ci'][1]:+.1f}]"
dif = lambda v, f="+.3f": f"{v['v']:{f}} [{v['ci'][0]:{f}}, {v['ci'][1]:{f}}]"
L = ["# DiT activation-feedback + weight-correction pilot: report (generated by `scripts/make_dit_joint.py`)", "",
     f"GPU: {P['gpu'] if P else '?'}. Protocol and amendments: `results/dit_joint/PROTOCOL.md`. Checks: {'all passed' if CH and CH.get('pass') else 'see checks.json'}.",
     "One training seed per arm (a pilot); the image bootstraps do not measure training-seed variance. Paired latent/PSNR/LPIPS are fidelity to FP, not generation quality.", "",
     "## Configurations (sealed seeds 61000–61127, n = 128)", "", "| config | latent rel. MSE | PSNR | LPIPS | s/image | clip rate | state bytes (last batch) |", "| --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
order = ["W4A16_orig", "W4A16_common", "A", "B", "C_L", "D_L", "E_L", "C_R", "D_R", "E_R", "C_L*", "D_L*", "E_L*", "C_R*", "D_R*", "E_R*"]
for k in order:
    if k in C:
        c = C[k]
        L.append(f"| {k} | {np.mean(c['rel_mse']):.5f} | {np.mean(c['psnr']):.2f} | {np.mean(c['lpips']):.4f} | {c.get('sec_per_image', float('nan')):.3f} | "
                 f"{c.get('clip_rate', float('nan')):.2e} | {c.get('state_bytes_last_batch', '—')} |")
L += ["", "`*` = checkpoint selected on development seeds 60200–60231 (secondary, practical comparison)."]
if S:
    L += ["", "| arm | dev latent at 0 / 25 / 50 / 100 / 200 updates | selected |", "| --- | --- | --- |"]
    for a, v in S["arms"].items():
        L.append(f"| {a} | {' / '.join(f'{v['dev_latent'][f'u{u}']:.5f}' for u in (0, 25, 50, 100, 200))} | {v['label']} |")
L += ["", "## Predeclared contrasts (paired bootstrap over the 128 images, 2,000 resamples)", "",
      "| contrast | latent (rel. change) | PSNR | LPIPS | latent wins / 128 | median latent diff |", "| --- | --- | --- | --- | ---: | ---: |"]
for k, v in RES.items():
    L.append(f"| {v['label']} ({k.replace('_vs_', ' vs ')}) | {pct(v['latent'])} | {dif(v['psnr'], '+.2f')} | {dif(v['lpips'], '+.4f')} | {v['latent']['wins']} | {v['latent']['median']:+.5f} |")
p = RES.get("E_R_vs_D_R")
ok = None
if p:
    lat = p["latent"]
    better_AB = all(RES[k]["latent"]["ci"][1] < 0 for k in ("E_R_vs_A", "E_R_vs_B") if k in RES)
    lp_reg = p["lpips"]["ci"][0] > 0
    useful = lat["v"] <= -0.05 and lat["ci"][1] < 0 and better_AB and not lp_reg
    rollout = useful and RES.get("E_R_vs_E_L", {}).get("latent", {}).get("ci", [0, 0])[1] < 0
    L += ["", "## Decision rule (pilot prioritization, PROTOCOL §C)",
          f"- E_R vs D_R latent {pct(lat)}; E_R better than A and B (CIs below 0): {better_AB}; clear LPIPS regression: {lp_reg}.",
          f"- **Useful joint-training signal (≥ 5% lower latent MSE vs D_R, CI below 0, better than A/B, no LPIPS regression): {useful}.**",
          f"- Rollout term credited (E_R also beats E_L): {rollout}.",
          "- Smaller or uncertain effects are inconclusive. A flat result means this pilot did not establish integration; it does not show that no combination can work."]
L += ["", "## Costs", ""]
if P:
    L += [f"- Profile: " + "; ".join(f"{a} {P[a]['sec_per_update']:.2f} s/update, peak {P[a]['peak_mem_GiB']:.1f} GiB" for a in ("C_L", "E_L", "C_R", "E_R") if a in P)]
for a, t in TR.items():
    if t:
        L.append(f"- Training {a}: {t['updates']} updates, {t.get('gpu_hours', float('nan')):.3f} GPU-h, {t['sec_per_update']:.2f} s/update (prefix generation included), peak {t['peak_mem_GiB']:.1f} GiB")
if "diag" in E:
    L += ["", "## Temporal coherence diagnostic (seeds 61000–61031, FP-trajectory states; C = T·‖mean_t e_t‖², I = mean_t ‖e_t‖²)", "",
          "| config | C | I | C/I |", "| --- | ---: | ---: | ---: |"]
    L += [f"| {k} | {np.mean(v['C']):.4g} | {np.mean(v['I']):.4g} | {v['C_over_I']:.3f} |" for k, v in E["diag"].items()]
atomic_write_json(os.path.join(OUT, "contrasts.json"), RES)
atomic_write_text(os.path.join(OUT, "REPORT.md"), "\n".join(L) + "\n")
print("\n".join(L))
