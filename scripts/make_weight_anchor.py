def live_tab(R, title):
    out = [title, "", "| arm | latent rel. MSE | PSNR (dB) | LPIPS | W4 calls | FP calls |", "| --- | ---: | ---: | ---: | ---: | ---: |"]
    import numpy as np
    for a, v in R["arms"].items():
        c = R["calls_per_batch"][a]
        out.append(f"| {a} | {np.mean(v['rel_mse']):.5f} | {np.mean(v['psnr']):.2f} | {np.mean(v['lpips']):.4f} | {c['w4']} | {c['fp']} |")
    out += ["", "| contrast | latent rel. MSE change | ΔPSNR | ΔLPIPS | latent wins |", "| --- | --- | --- | --- | ---: |"]
    for k, v in R["paired"].items():
        out.append(f"| {k} | {rc(v['latent'])} | {dc(v['psnr'], '+.2f')} | {dc(v['lpips'])} | {v['latent_wins']}/{len(next(iter(R['arms'].values()))['rel_mse'])} |")
    return out


