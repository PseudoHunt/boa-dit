"""Generate results/activation_bridge_overnight/REPORT.md and MORNING_STATUS.md from the abn1 JSON outputs."""
import csv
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "results", "activation_bridge_overnight")
STAGES = [("checks", "checks.json", "Correctness gate"), ("s1", "s1.json", "Stage 1 — FP anchors K4, 256 confirmation images"),
          ("s2", "s2.json", "Stage 2 — W8 anchors K4, first 128"), ("s3", "s3.json", "Stage 3 — K8 (FP and W8), first 128"),
          ("s4", "s4.json", "Stage 4 — existing local refit + bridge, first 128"), ("s5", "s5.json", "Stage 5 — diagnostics (8 dev images)"),
          ("s6", "s6.json", "Stage 6 — FID-2k pilot"), ("s7", "timing.json", "Stage 7 — timing")]


def j(n):
    f = os.path.join(OUT, n)
    return json.load(open(f)) if os.path.exists(f) else None


def status(r, key):
    if r is None:
        return "not run"
    if key == "checks":
        return "pass" if r.get("pass") else "FAILED"
    return r.get("status", "complete")


def tables(r, L, label):
    L += [f"*{label}*", "", "| arm | cheap / high calls | bridge corrections | latent rel. MSE mean | median | PSNR | LPIPS |", "|---|---|---:|---:|---:|---:|---:|"]
    fr = j("frozen.json")["expected_counts"]
    calls = r["calls"] if isinstance(r.get("calls"), dict) else {}
    for a, s in r["summary"].items():
        c = calls.get(a) or fr.get(a, {})                                     # s3.json: per-arm counts overwritten by a note (asserted at runtime = expected)
        L.append(f"| {a} | {c.get('cheap', '—')} / {c.get('high', '—')} | {c.get('corrections', '—')} | {s['rel_mse']['mean']:.5f} | {s['rel_mse']['median']:.5f} | "
                 f"{s['psnr']['mean']:.2f} | {s['lpips']['mean']:.4f} |")
    L += ["", "| contrast | mean-MSE ratio [95% CI] | mean diff [CI] | median diff | wins | ΔLPIPS [CI] | ΔPSNR [CI] |", "|---|---:|---:|---:|---:|---:|---:|"]
    for k, v in r["contrasts"].items():
        m, lp, ps = v["rel_mse"], v["lpips"], v["psnr"]
        L.append(f"| {k.replace('_vs_', ' / ')} | {m['ratio']:.3f} [{m['ratio_ci'][0]:.3f}, {m['ratio_ci'][1]:.3f}] | {m['diff']:+.5f} [{m['diff_ci'][0]:+.5f}, "
                 f"{m['diff_ci'][1]:+.5f}] | {m['median_diff']:+.5f} | {m['wins_x']}/{m['n']} | {lp['diff']:+.4f} [{lp['diff_ci'][0]:+.4f}, {lp['diff_ci'][1]:+.4f}] | "
                 f"{ps['diff']:+.2f} [{ps['diff_ci'][0]:+.2f}, {ps['diff_ci'][1]:+.2f}] |")
    L.append("")


def inter_line(it, label):
    return (f"- {label}: I = {it['definition']} = {it['I']:+.5f} [{it['I_ci'][0]:+.5f}, {it['I_ci'][1]:+.5f}] (feedback gain with bridge "
            f"{it['gain_with_bridge']:+.5f} [{it['gain_with_bridge_ci'][0]:+.5f}, {it['gain_with_bridge_ci'][1]:+.5f}], without {it['gain_without_bridge']:+.5f} "
            f"[{it['gain_without_bridge_ci'][0]:+.5f}, {it['gain_without_bridge_ci'][1]:+.5f}])")


def main():
    R = {k: j(f) for k, f, _ in STAGES}
    rows = [r for r in csv.reader(open(os.path.join(ROOT, "results", "gpu_hours.csv"))) if r and r[0] == "abn1"]
    tot = sum(float(r[-1]) for r in rows)
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=ROOT).stdout.strip()
    L = ["# Overnight abn1: activation feedback, anchor reuse and retrospective bridge — report", "",
         "Protocol `PROTOCOL.md` (pre-registered 2026-10-30; amendments dated). Generated by `scripts/make_activation_bridge.py`.",
         f"**GPU: {tot:.3f} of 6.0 A30-h** ({', '.join(f'{r[1]} {float(r[-1]):.3f}' for r in rows)}).",
         "Fidelity = endpoint latent rel. MSE / PSNR / LPIPS vs FP50 on DiT-XL/2 256 (fake-quant simulation). Confirmation cohort 110000–110255 (Stages 2–4 reuse its "
         "first 128: one shared cohort, not independent replications). Secondary contrasts are exploratory and unadjusted.", "",
         "Arms: C = static A8 + anchor reuse; AC = DCT-4 feedback + reuse; G = matched-range stateless quantizer (AC's guarded path, zero carried state) + reuse;",
         "B = + bridge (multiplier 1); .w8 = W8A16 anchors (H8); .k8 = anchors every 8 calls; LCB / LACB = joint-pilot local refits C_L / E_L (u200) + bridge.", ""]
    ch = R["checks"]
    L += ["## Correctness gate"]
    if ch:
        L += [f"- Reproduce aa1 C / AC / FP50: {ch['C1_reproduce_aa1']}; br1 CB1: {ch['C1_reproduce_br1_CB1']}; λ = 0 = base incl. state: {ch['C2_lambda0_equals_base_incl_state']}",
              f"- No anchors = plain: {ch['C3_no_anchor_equals_plain']}; K1 = H50 (no corrections): {ch['C4_K1_equals_H50']}; H8-50 = wa8 cache: {ch['C10_H8_50_reproduces_wa8']}",
              f"- Identical stateless cheap/high → zero discrepancy and bridge: {ch['C5_identical_stateless_zero']}; counts/quantizer updates: {ch['C6_pass']} "
              f"({ {k: v['counts'] for k, v in ch['C6_counts'].items()} })",
              f"- Anchor calls recorded {ch['C7_anchor_calls_recorded']}; other samples unchanged when one is perturbed: bitwise {ch['C7_independent_bitwise']} "
              f"(max abs {ch['C7_other_samples_unchanged_max_abs']:.1e}); resume before/after anchor: {ch['C8_resume_bitwise']}",
              f"- Synthetic bridge (constant → 0, linear drift cancels, K4/K8): {ch['C9_synthetic']}",
              f"- G ignores carried state = zero-state AC: {ch['C11_G_ignores_state_equals_zero_state_AC']}; C vs G bitwise {ch['C_vs_G_bitwise']} (rel. L2 {ch['C_vs_G_rel_l2']:.3f}) "
              f"→ {'aliased' if ch['C_vs_G_bitwise'] else 'kept separate'}; diagnostics on/off bitwise {ch['C12_diag_on_off_bitwise']}",
              f"- **Gate: {'pass' if ch['pass'] else 'FAILED'}**", ""]
    else:
        L += ["- not run", ""]
    for key, f, title in STAGES[1:5]:
        r = R[key]
        L += [f"## {title}", ""]
        if not r or r.get("status") != "complete":
            L += [f"- **{status(r, key)}**", ""]
            continue
        tables(r, L, "confirmation cohort" if key != "s5" else "development")
        if key == "s1":
            L += [f"- **Primary ACB / CB: {r['reading_primary']}.**", f"- ACB / GB (feedback memory, matched range): {r['reading_ACB_vs_GB']}; AC / G: {r['reading_AC_vs_G']}.",
                  inter_line(r["interaction_matched"], "Matched interaction"), inter_line(r["interaction_package"], "Package interaction (C/CB in place of G/GB)"), ""]
        if key == "s2":
            L += [f"- CB.w8 / C.w8 (bridge with W8 anchors): {r['reading_CB.w8_vs_C.w8']}; ACB.w8 / CB.w8: {r['reading_ACB.w8_vs_CB.w8']}. {r['note']}.", ""]
        if key == "s3":
            L += [f"- Noninferiority ({r['margin']}): {r['noninferiority_vs_ordinary_K4']}. Calls: K8 = 50 cheap + 7 high (6 corrections); K4 = 50 + 13 (12).", ""]
        if key == "s4":
            L += [f"- LCB / CB: {r['reading_LCB_vs_CB']}; LACB / ACB: {r['reading_LACB_vs_ACB']}. {r['note']}.", ""]
        L.append("- Simulation timing (s per 32-image trajectory, harness with all stage models resident): " +
                 ", ".join(f"{a} {v['median']:.1f}" for a, v in r["timing_s_per_batch32"].items()) + ".")
        L.append("")
    r = R["s5"]
    L += ["## Stage 5 — mechanism diagnostics (8 development images, own trajectories)", ""]
    if r and r.get("status") == "complete":
        L += ["| arm | raw discrepancy energy | held-error energy | anchor-jump energy | cos(H, Ĥ) | centered corr | ‖Ĥ‖/‖H‖ | ‖H−Ĥ‖²/‖H‖² | replay cos(δx, Ĥ) @0/20/40 | replay residual @0/20/40 |",
              "|---|---:|---:|---:|---:|---:|---:|---:|---|---|"]
        for a, v in r["arms"].items():
            rp = v["replay"]
            rc = " / ".join("%.2f" % rp[k]["cos_dx_Hhat"] for k in rp)
            rr = " / ".join("%.2f" % rp[k]["residual_after_bridge"] for k in rp)
            L.append(f"| {a} | {v['raw_discrepancy_energy']:.4g} | {v['held_error_energy']:.4g} | {v['anchor_jump_energy']:.4g} | {v['cos_H_Hhat']:.3f} | {v['centered_corr_H_Hhat']:.3f} | "
                     f"{v['magnitude_Hhat_over_H']:.3f} | {v['residual_over_H']:.3f} | {rc} | {rr} |")
        L += ["", f"- {r['limitation']}. Definitions: {r['definitions']}.", ""]
    else:
        L += [f"- **{status(r, 's5')}**", ""]
    r = R["s6"]
    L += ["## Stage 6 — generation-quality pilot (FID-2k, class-balanced 112000–113999)", ""]
    if r and r.get("status") == "complete":
        L += [f"- FID-2k: {r['fid2k']}", f"- Paired generated-sample bootstrap (1,000 draws): {r['paired_boot']}", f"- {r['note']}", ""]
    else:
        L += [f"- **{status(r, 's6')}**" + (f" (required estimate {r['required_estimate_h']:.2f} A30-h; spent at decision {r['spent_at_decision_h']:.2f})" if r and "required_estimate_h" in r else ""), ""]
    r = R["s7"]
    L += ["## Stage 7 — timing (simulation)", ""]
    if r and r.get("status") == "complete":
        L += ["| arm @ batch | median s | spread | s / image | peak alloc GB | model bytes GB | feedback state B / image |", "|---|---:|---|---:|---:|---:|---:|"]
        for a, v in r["arms"].items():
            L.append(f"| {a} | {v['median_s']:.2f} | {v['spread_s'][0]:.2f}–{v['spread_s'][1]:.2f} | {v['per_image_s']:.3f} | {v['peak_allocated'] / 1e9:.2f} | "
                     f"{v['model_bytes_resident'] / 1e9:.2f} | {v['feedback_state_bytes_per_image_incl_cfg']:.0f} |")
        L += [""] + [f"- {k}: {v}" for k, v in r.items() if k.startswith(("bridge_increment", "feedback_overhead", "cost_condition"))] + [f"- {r['note']}.", f"- SANA: {r['sana']}.", ""]
    else:
        L += [f"- **{status(r, 's7')}**", ""]
    open(os.path.join(OUT, "REPORT.md"), "w").write("\n".join(L) + "\n")
    M = ["# MORNING_STATUS (abn1)", "", f"Head commit: {head} on branch activation-bridge-overnight (worktree /home/boa-dit-abn).",
         f"GPU: {tot:.3f} of 6.0 A30-h. Running at shutdown: none (the queue exits after the last stage and releases its lock).", "", "| stage | status |", "|---|---|"]
    for k, f, title in STAGES:
        M.append(f"| {title} | {status(R[k], k)} |")
    M += ["", "Artifacts: `results/activation_bridge_overnight/` (JSON, REPORT.md, per-image metrics inside each stage JSON); latents and per-batch checkpoints in",
          "`ckpt/activation_bridge_overnight/` (local only, not uploaded — standing instruction: models/artifacts are regenerated from code; hashes in `artifacts.json`).",
          "Answers to the six questions: see the end of REPORT.md (written after the queue finished)."]
    open(os.path.join(OUT, "MORNING_STATUS.md"), "w").write("\n".join(M) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
