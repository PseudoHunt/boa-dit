def load(*p):
    p = os.path.join(*p)
    return json.load(open(p)) if os.path.exists(p) else None


def red(x, y):
    """'+a% [lo, hi]' reduction of x vs y (positive = x better), and the raw tuple."""
    if x is None or y is None:
        return "pending", None
    r = paired(x, y)
    return f"{100 * r[0]:+.1f}% [{100 * r[1]:+.1f}, {100 * r[2]:+.1f}]", r


def sub(js, n):
    return None if js is None else {**js, "rel_mse_per_image": js["rel_mse_per_image"][:n]}


def passes(r, thr):
    return r is not None and r[0] >= thr and r[1] > 0


def spent():
    tot, by = 0.0, {}
    for row in csv.reader(open(os.path.join(R, "gpu_hours.csv"))):
        if len(row) < 6 or row[3] < START or row[5] == "gpu_hours":
            continue
        h = float(row[5])
        tot += h
        by[row[0]] = by.get(row[0], 0.0) + h
    return tot, by


