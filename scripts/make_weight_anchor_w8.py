"""Generate results/weight_anchor_w8/REPORT.md from the wa8 JSON outputs (missing stages are reported as unrun)."""
import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "results", "weight_anchor_w8")
ARMS = ("FP50", "Q4", "H8", "A8", "R8", "S8", "R_FP")


def j(name):
    f = os.path.join(OUT, name)
    return json.load(open(f)) if os.path.exists(f) else None


def pct(c):
    return f"{100 * c['rel_change']:+.1f}% [{100 * c['ci'][0]:+.1f}, {100 * c['ci'][1]:+.1f}]"


def spent():
    rows = [r for r in csv.reader(open(os.path.join(ROOT, "results", "gpu_hours.csv"))) if r and r[0] == "wa8"]
    return rows, sum(float(r[-1]) for r in rows)


def arm_table(res, L):
    L += ["| arm | Q4 / H8 / FP calls | latent rel. MSE mean | median | PSNR mean (dB) | LPIPS mean |", "|---|---|---:|---:|---:|---:|"]
    for a in ARMS:
        c = res["calls"][a]
        s = res["summary"].get(a)
        if s is None:
            L.append(f"| {a} | {c['q4']} / {c['h8']} / {c['fp']} | 0 (reference) | 0 | — | — |")
        else:
            L.append(f"| {a} | {c['q4']} / {c['h8']} / {c['fp']} | {s['rel_mse']['mean']:.5f} | {s['rel_mse']['median']:.5f} | "
                     f"{s['psnr']['mean']:.2f} | {s['lpips']['mean']:.4f} |")


def contrast_table(res, L):
    L += ["| contrast | latent MSE change [95% CI] | mean diff [95% CI] | median diff | wins | ΔLPIPS [95% CI] | ΔPSNR [95% CI] |",
          "|---|---:|---:|---:|---:|---:|---:|"]
    for k, v in res["contrasts"].items():
        m = v["rel_mse"]
        L.append(f"| {k.replace('_vs_', ' vs ')} | {pct(m)} | {m['diff']:+.5f} [{m['diff_ci'][0]:+.5f}, {m['diff_ci'][1]:+.5f}] | {m['median_diff']:+.5f} | "
                 f"{m['wins_x']}/{len(res['arms']['R8']['rel_mse'])} | {v['lpips']['diff']:+.4f} [{v['lpips']['ci'][0]:+.4f}, {v['lpips']['ci'][1]:+.4f}] | "
                 f"{v['psnr']['diff']:+.2f} [{v['psnr']['ci'][0]:+.2f}, {v['psnr']['ci'][1]:+.2f}] |")


def retained(rb, L):
    L.append(f"- Retained benefit B = (E_Q4 − E_R8)/(E_Q4 − E_R_FP) = **{rb['B']:.3f}** [{rb['B_ci'][0]:.3f}, {rb['B_ci'][1]:.3f}]"
             + ("" if rb["interpretable"] else " — **not interpreted** (denominator CI includes 0)") + ".")
    L.append(f"  Unnormalized gains over Q4: R8 {rb['gain_R8']:.5f} [{rb['gain_R8_ci'][0]:.5f}, {rb['gain_R8_ci'][1]:.5f}], "
             f"R_FP {rb['gain_R_FP']:.5f} [{rb['gain_R_FP_ci'][0]:.5f}, {rb['gain_R_FP_ci'][1]:.5f}]; "
             f"E: Q4 {rb['E']['Q4']:.5f}, R8 {rb['E']['R8']:.5f}, R_FP {rb['E']['R_FP']:.5f}.")


def main():
    P, B, C, D, DR, K8, F = (j(n) for n in ("PROTOCOL", "build.json", "checks.json", "dev.json", "drift.json", "dev_k8.json", "conf.json"))
    rows, tot = spent()
    L = ["# W8 anchors for cross-precision error reuse (wa8): report", "",
         "Protocol: `PROTOCOL.md` (pre-registered 2026-10-30, commit 53f48e0, before any build or generation). Generated by `scripts/make_weight_anchor_w8.py`.",
         f"**GPU: {tot:.3f} of 1.0 A30-h** (ledger tag wa8: " + ", ".join(f"{r[1]} {float(r[-1]):.4f}" for r in rows) + ").",
         "This is an accuracy and discrepancy-persistence pilot. **No speedup, generation-quality, equal-cost or novelty claim follows from it.**", ""]
    L += ["## H8 construction (fixed-calibration W8 + rank-8 carry)"]
    if B:
        a = B["aggregate_errors"]
        bt = B["bytes_theoretical"]
        L += [f"- Replay audit at bits = 4 (all 112 layers): " + ", ".join(f"{k} {v}" for k, v in B["w4_replay_all"].items())
              + f"; W4 codes {B['w4_replay_codes_range']}.",
              f"- W8: codes {B['w8_codes_range']} (0..255), dequantization bitwise {B['w8_dequant_bitexact_all']}, finite {B['w8_finite_all']}.",
              f"- Weight error (mean over layers ‖W−Q‖/‖W‖): W4 {a['w4']['rel_weight_err_mean']:.4f}, W8 {a['w8']['rel_weight_err_mean']:.5f}.",
              f"- Σ H-weighted error tr(E H Eᵀ): W4 {a['w4']['H_quad']:.4g} → {a['w4']['H_quad_after_carry']:.4g} after carry; "
              f"W8 {a['w8']['H_quad']:.4g} → {a['w8']['H_quad_after_carry']:.4g} after carry.",
              f"- Theoretical packed bytes (whole model; {bt['assumptions']}): W4 bed {bt['w4_whole_model_bytes'] / 1e6:.1f} MB, "
              f"H8 {bt['w8_whole_model_bytes'] / 1e6:.1f} MB, fp16 {bt['fp16_whole_model_bytes'] / 1e6:.1f} MB. Components: quantized linears W4 "
              f"{bt['w4_linear_bytes'] / 1e6:.1f} MB / W8 {bt['w8_linear_bytes'] / 1e6:.1f} MB; carry {bt['carry_bytes'] / 1e6:.2f} MB (each model); "
              f"adaLN {bt['adaln_bytes'] / 1e6:.1f} MB; other {bt['other_bytes'] / 1e6:.1f} MB. R8 needs W4 + H8 resident "
              f"(shared adaLN/other in principle: {(bt['w4_linear_bytes'] + bt['w8_linear_bytes'] + 2 * bt['carry_bytes'] + bt['adaln_bytes'] + bt['other_bytes']) / 1e6:.1f} MB)."]
        if C:
            rb = C["resident_model_bytes_simulation"]
            L.append(f"- Actual simulation resident bytes (fp32 dequantized weights): FP {rb['fp'] / 1e9:.2f} GB, Q4 {rb['q4'] / 1e9:.2f} GB, H8 {rb['h8'] / 1e9:.2f} GB "
                     f"(+ carry {C['resident_carry_bytes_simulation'] / 1e6:.1f} MB each). These are simulation numbers, not deployment numbers.")
        L.append(f"- Artifact `ckpt/weight_anchor_w8/h8.pt` sha256 `{B['hashes_sha256']['h8.pt']}` (not in Git; regenerate with `python -m boa_dit.weight_anchor.w8 build`).")
    else:
        L.append("- **Unrun.**")
    L += ["", "## Correctness checks"]
    if C:
        L += [f"- C1 (vs cached wac1 latents on 92000–92031): {C['C1']}", f"- C2 R8 with K = 1 equals H8-50: {C['C2_R8_K1_equals_H8']}",
              f"- C3 Q = H: zero correction {C['C3_Q_equals_H_zero_correction']}, equals Q4 {C['C3_equals_Q4']}",
              f"- C4 anchors share latent/timestep/labels: {C['C4_anchor_same_state']} ({C['C4_n_anchors']} anchors)", f"- C5 call counts: {C['C5_pass']}",
              f"- C6 outputs finite {C['C6_outputs_finite']}; rebuilt-W4 forward bitwise {C['C6_rebuilt_w4_forward_bitexact']}; channels 4–7 zeroed leaves FP50 unchanged "
              f"{C['C6c_aux_zero_equals_FP50']}; batch 8 vs 32 (H8) max abs {C['C6b_batch8_vs_batch32_H8_max_abs']:.3g} (bitwise {C['C6b_bitwise']}, recorded only)",
              f"- **All stop conditions pass: {C['pass']}**"]
    else:
        L.append("- **Unrun.**")
    for title, res, key in (("Development (94000–94031, exploratory: nothing selected)", D, "reading_R8_vs_A8_dev"),
                            ("Confirmation (94100–94163, fresh, opened once)", F, "reading_R8_vs_A8")):
        L += ["", f"## {title}"]
        if not res:
            L.append("- **Unrun.**")
            continue
        arm_table(res, L)
        L.append("")
        contrast_table(res, L)
        L += ["", f"- **Pre-registered reading of R8 vs A8: {res[key]}.**"]
        if "anchor_adequate_H8_better_than_Q4" in res:
            L.append(f"- Anchor adequacy (H8 latent MSE below Q4, CI excludes 0): **{res['anchor_adequate_H8_better_than_Q4']}**.")
        retained(res.get("retained_benefit") or res["retained_benefit_dev"], L)
    L += ["", "## Discrepancy persistence (development traces, same states along the uncorrected Q4 trajectory)"]
    if DR:
        L.append(f"- {DR['label']}; trace trajectory equals the Q4 arm: {DR['trace_trajectory_equals_Q4_arm']}. d = ε_Q4 − ε_H8, e = ε_Q4 − ε_FP (channels 0–3).")
        L += ["", "| lag | cos(d_t, d_a) mean | ‖d_t‖/‖d_a‖ median | Σ‖d_t−d_a‖²/Σ‖d_t‖² [CI] | shuffled | Σ‖e_t−d_a‖²/Σ‖e_t‖² [CI] | FP-anchor Σ‖e_t−e_a‖²/Σ‖e_t‖² |",
              "|---:|---:|---:|---:|---:|---:|---:|"]
        for lg, r in DR["lags"].items():
            L.append(f"| {lg} | {r['cos_mean']:.3f} | {r['norm_ratio_median']:.3f} | {r['ratio_d']['v']:.3f} [{r['ratio_d']['ci'][0]:.3f}, {r['ratio_d']['ci'][1]:.3f}] | "
                     f"{r['shuffled_ratio_d']['v']:.3f} | {r['corrected_fp_err_ratio']['v']:.3f} [{r['corrected_fp_err_ratio']['ci'][0]:.3f}, "
                     f"{r['corrected_fp_err_ratio']['ci'][1]:.3f}] | {r['fp_anchor_reuse_err_ratio']['v']:.3f} |")
        L += ["", "By stage of t (ratio Σ‖d_t−d_a‖²/Σ‖d_t‖²; corrected FP-error ratio):", ""]
        for lg, r in DR["lags"].items():
            L.append(f"- lag {lg}: " + "; ".join(f"{s} {v['ratio_d']['v']:.3f} / {v['corrected_fp_err_ratio']['v']:.3f}" for s, v in r["by_stage"].items()))
        L += ["", "Offline fixed-period anchoring on the same traces (not endpoint or speed metrics):", "",
              "| K | anchors | Σ‖d_t−d_a‖²/Σ‖d_t‖² | Σ‖e_t−d_a‖²/Σ‖e_t‖² (H8-anchor reuse) | Σ‖e_t−e_a‖²/Σ‖e_t‖² (FP-anchor reuse) |", "|---:|---:|---:|---:|---:|"]
        for kk, r in DR["fixed_period"].items():
            L.append(f"| {kk} | {r['n_anchors']} | {r['ratio_d']['v']:.3f} | {r['corrected_fp_err_ratio']['v']:.3f} [{r['corrected_fp_err_ratio']['ci'][0]:.3f}, "
                     f"{r['corrected_fp_err_ratio']['ci'][1]:.3f}] | {r['fp_anchor_reuse_err_ratio']['v']:.3f} |")
        fpz = DR["frozen_prediction_k8"]
        L += ["", f"- Frozen K = 8 prediction ({fpz['frozen_utc']}): {fpz['predicted_sign']} (offline ratio {fpz['offline_ratio']:.3f}).",
              "- Small W4–W8 discrepancy drift does not bound H8's own error; the corrected FP-error column is the relevant local quantity."]
    else:
        L.append("- **Unrun.**")
    L += ["", "## Optional K = 8 development check"]
    if K8:
        c = K8["R8_vs_A8_k8"]["rel_mse"]
        L.append(f"- R8 vs A8 at K = 8 (7 anchors, dev only): {pct(c)}; predicted {K8['predicted']['predicted_sign']}, observed {K8['observed_sign']} "
                 f"(agrees: {K8['agrees']}). A preliminary check of one diagnostic, not validation of a law or a selection method.")
    else:
        L.append("- **Not run.**")
    L += ["", "## Cost record for Monday (simulation only)",
          "- Calls per 50-step trajectory: R8 = 50 Q4 + 13 H8 + 0 FP; H8-50 = 50 H8. First-order real cost of R8 vs H8-50: 50·C_Q4 + 13·C_H8 + overhead vs 50·C_H8,",
          "  so C_Q4/C_H8 < 0.74 is necessary at K = 4 with zero overhead. No time measured here bears on that ratio (W4 and W8 are both fp32-dequantized in simulation).",
          "- A hardware study must compare full trajectories and quality against H8 at matched latency, not only against Q4 or A8.", ""]
    open(os.path.join(OUT, "REPORT.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
